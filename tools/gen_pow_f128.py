#!/usr/bin/env python3
"""Generate the 640-bit constants of `powq`'s table-free third tier.

Two mathematical constants, evaluated to 1500 bits with mpmath and truncated:
ln(2) scaled by 2^640 (the reduction of `2^f = e^(f ln 2)`) and log2(e) scaled
by 2^639 (the Newton correction `log2(1 + e) = log2(e)*(e - e^2/2 + ...)`).
No fitted coefficients, no transcription from another library.

Usage:
    python3 tools/gen_pow_f128.py > src/f128_/pow_tables.rs
"""
from mpmath import mp, mpf, log, floor

mp.prec = 1500

LIMBS = 10


def limbs(value):
    """`value` as `LIMBS` little-endian 64-bit limbs."""
    assert 0 <= value < 1 << (64 * LIMBS), value
    parts = [f"0x{value >> (64 * i) & (1 << 64) - 1:016x}" for i in range(LIMBS)]
    rows = [", ".join(parts[i:i + 2]) for i in range(0, LIMBS, 2)]
    return "[\n" + "".join(f"    {row},\n" for row in rows) + "]"


print("""//! Generated by tools/gen_pow_f128.py - do not edit by hand.
//!
//! The 640-bit constants of `powq`'s third tier, both mathematical: ln(2) and
//! log2(e), evaluated to 1500 bits with mpmath and truncated.
#![allow(clippy::unreadable_literal)]
""")
print("/// ln(2), scaled by 2^640 and truncated.")
print(f"pub const LN2: [u64; {LIMBS}] = {limbs(int(floor(log(2) * mpf(2) ** 640)))};")
print()
print("/// log2(e), scaled by 2^639 and truncated.")
print(f"pub const LOG2E: [u64; {LIMBS}] = {limbs(int(floor(mpf(2) ** 639 / log(2))))};")

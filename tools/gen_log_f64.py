#!/usr/bin/env python3
"""Generate constants for the f64 logarithm family (ln, log2, log10, ln_1p).

Design (small-table + low-degree double-double):
  x = 2^e · m,  m ∈ [1, 2);  i = top 7 mantissa bits, so m ∈ [1+i/128, 1+(i+1)/128)
  inv = INV_TABLE[i] ≈ 1/(bin centre);  r = m·inv − 1 ∈ [−1/256, 1/256]
  ln(m) = ln(1+r) − ln(inv) = ln(1+r) + L_TABLE[i]
  ln(x) = e·ln2 + L_TABLE[i] + ln(1+r),  ln(1+r) = r·P(r),  P = ∑ (−r)^k/(k+1)
"""
from mpmath import mp, mpf, log as mlog
import struct
mp.prec = 250

def f64(x): return struct.unpack('<d', struct.pack('<d', float(x)))[0]
def dd(x):
    hi = f64(x); lo = f64(mpf(x) - mpf(hi)); return hi, lo
def hexf(v): return repr(float(v))

N = 128

# Extended-precision ln2: high word has >=11 trailing zero bits so e·HI is exact
# for |e| < 2^(53-42) (e ranges over the binary exponent, |e| <= 1074 < 2^11).
ln2 = mlog(2)
b = struct.unpack('<Q', struct.pack('<d', f64(ln2)))[0] & ~((1 << 11) - 1)
LN2_HI = struct.unpack('<d', struct.pack('<Q', b))[0]
LN2_LO = f64(ln2 - mpf(LN2_HI))
print("//! Constants for the f64 logarithm family — generated by `tools/gen_log_f64.py`.")
print("//! Do not edit by hand; re-run the generator instead.")
print("#![allow(clippy::unreadable_literal, clippy::excessive_precision)]\n")
print(f"pub(super) const LN2_HI: f64 = {hexf(LN2_HI)};")
print(f"pub(super) const LN2_LO: f64 = {hexf(LN2_LO)};")

# Inverse table and L = −ln(inv) (double-double)
inv_tab, l_tab = [], []
for i in range(N):
    centre = mpf(1) + (mpf(i) + mpf('0.5')) / N
    inv = f64(mpf(1) / centre)
    inv_tab.append(inv)
    l_tab.append(dd(-mlog(mpf(inv))))
print(f"\npub(super) const INV_TABLE: [f64; {N}] = [")
for v in inv_tab:
    print(f"    {hexf(v)},")
print("];")
print(f"\npub(super) const L_TABLE: [(f64, f64); {N}] = [")
for hi, lo in l_tab:
    print(f"    ({hexf(hi)}, {hexf(lo)}),")
print("];")

# P(r) = ln(1+r)/r = sum_{k>=0} (-r)^k/(k+1), double-double, degree 12
print(f"\npub(super) const LN1P_P_COEFFS: [(f64, f64); 13] = [")
for k in range(13):
    hi, lo = dd(mpf((-1) ** k) / (k + 1))
    print(f"    ({hexf(hi)}, {hexf(lo)}),")
print("];")

# log2(x) = e + ln(m)·log2(e);  log10(x) = ln(x)·log10(e)
from mpmath import e as me
log2_e_hi, log2_e_lo = dd(mpf(1) / mlog(2))
log10_e_hi, log10_e_lo = dd(mpf(1) / mlog(10))
print(f"\npub(super) const LOG2_E_HI: f64 = {hexf(log2_e_hi)};")
print(f"pub(super) const LOG2_E_LO: f64 = {hexf(log2_e_lo)};")
print(f"pub(super) const LOG10_E_HI: f64 = {hexf(log10_e_hi)};")
print(f"pub(super) const LOG10_E_LO: f64 = {hexf(log10_e_lo)};")

#!/usr/bin/env python3
"""Enumerate every binary32 pair (x, y) whose exact x^y is a rounding tie.

A tie is a dyadic p·2^q with p odd that sits halfway between two f32 values:
in the normal range p has exactly 25 bits; in the subnormal range q = -150 and
p is any odd integer below 2^24 (p = 1 included: 2^-150 is a tie between 0 and
the smallest subnormal).  With x = c^b·2^E (c odd) and y = a/b, x^y = c^a·2^(E·a/b),
so the enumeration is over (c, a, b, E) with E·a/b an integer, y an f32, and
x an f32.  Sign copies cover the negative-base branch for integer y.

No finite-precision fallback can decide these (issue #14); they gate
`powf`'s exact-case detector against the CORE-MATH oracle.

    python3 tools/gen_powf_ties.py > tests/cases/f32_powf.wc
"""
from fractions import Fraction
import struct
import sys


def is_f32(v: Fraction) -> bool:
    """Whether the rational `v` is exactly a finite binary32."""
    if abs(v) >= Fraction(2) ** 128 or (v != 0 and abs(v) < Fraction(2) ** -149):
        return False
    f = float(v)
    return Fraction(f) == v and struct.unpack("f", struct.pack("f", f))[0] == f


def hexf(v: Fraction) -> str:
    return float(v).hex()


def main() -> None:
    cases = set()
    P24, P25 = 1 << 24, 1 << 25

    def add(c: int, a: int, b: int, E: int) -> None:
        y = Fraction(a, b)
        x = Fraction(c**b) * Fraction(2) ** E
        if is_f32(x) and is_f32(y):
            cases.add((x, y))
            if y.denominator == 1:
                cases.add((-x, y))

    # Normal range: p = c^a with 2^24 <= p < 2^25, result exponent E·a/b in
    # [-150, 103] (so p·2^(E·y) lands between 2^-126 and 2^128).
    for c in range(3, 5792, 2):
        a = 2
        while c**a < P25:
            if c**a >= P24:
                b = 1
                while c**b < P24:
                    for q in range(-150, 104):  # q = E·a/b
                        if (q * b) % a == 0:
                            add(c, a, b, q * b // a)
                    b += 1
            a += 1

    # Subnormal range: result p·2^-150 with p odd below 2^24, E·a/b = -150.
    # a = 1 needs E = -150·b, never an f32 base, so a >= 2 and c <= 4095;
    # a negative base power 1/c^a is dyadic only for c = 1.
    for c in range(3, 4096, 2):
        a = 2
        while c**a < P24:
            b = 1
            while c**b < P24:
                if (150 * b) % a == 0:
                    add(c, a, b, -150 * b // a)
                b += 1
            a += 1

    # Power-of-two base: 2^(E·y) = 2^-150 for every f32 y = -150/E.
    for E in range(-149, 128):
        if E != 0:
            y = Fraction(-150, E)
            x = Fraction(2) ** E
            if is_f32(y):
                cases.add((x, y))
                if y.denominator == 1:
                    cases.add((-x, y))

    print("# Every binary32 (x, y) with x^y exactly on a rounding tie (issue #14).")
    print("# Columns: x, y.  Generated by `python3 tools/gen_powf_ties.py`.")
    for x, y in sorted(cases, key=lambda t: (float(t[1]), float(t[0]))):
        print(f"{hexf(x)},{hexf(y)}")
    print(len(cases), file=sys.stderr)


if __name__ == "__main__":
    main()

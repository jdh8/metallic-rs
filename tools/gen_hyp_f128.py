#!/usr/bin/env python3
"""Generate mathematical constants for the binary128 hyperbolics.

python3 tools/gen_hyp_f128.py > src/f128_/hyp_tables.rs
No fitted coefficients: factorials, Bernoulli rationals, and exp2 values.
"""
from mpmath import mp

mp.prec = 1500


def fixed(x, scale):
    n = int(mp.nint(x * mp.mpf(2)**scale))
    assert 0 <= n < 1 << 384
    limbs = [f'{(n >> k) & ((1 << 128)-1):032x}' for k in (0, 128, 256)]
    return '[' + ', '.join('0x' + s[:16] + '_' + s[16:] for s in limbs) + ']'


def table(name, values, scale, doc):
    print(f'\n/// {doc}')
    print('/// Generate: `python3 tools/gen_hyp_f128.py > src/f128_/hyp_tables.rs`.')
    print('#[rustfmt::skip]')
    print(f'pub const {name}: [[u128; 3]; {len(values)}] = [')
    for x in values:
        print('    ' + fixed(x, scale) + ',')
    print('];')


print('''//! Generated by tools/gen_hyp_f128.py; do not edit by hand.
//! Mathematical constants evaluated independently at 1500 bits.
#![allow(clippy::unreadable_literal)]''')
u = mp.mpf(2)**-8
for name, offset in [('SINH', 3), ('COSH', 2)]:
    c = [1/mp.factorial(2*k+offset) for k in range(30)]
    assert u**11/mp.factorial(20+offset) < mp.mpf(2)**-145
    assert u**31/mp.factorial(60+offset) < mp.mpf(2)**-390
    table(name, c, 384, f'1/(2k+{offset})!, k=0..29, at scale 2^384.')
c = [abs(2**(2*n)*(2**(2*n)-1)*mp.bernoulli(2*n)/mp.factorial(2*n))
     for n in range(2, 46)]
# tanh(x)/x = 1 - u*(c0 - u*(c1 - ...)); alternating tail.
assert c[15]*u**16 < mp.mpf(2)**-145
assert c[43]*u**44 < mp.mpf(2)**-400
table('TANH', c, 384, 'Magnitudes of tanh Taylor terms x^(2k+3), k=0..43, at 2^384.')
for name, step in [('T0', 64), ('T1', 4096), ('T2', 262144)]:
    table(name, [mp.power(2, mp.mpf(j)/step) for j in range(64)], 383,
          f'2^(j/{step}), j=0..63, at scale 2^383.')
table('EXP', [mp.log(2)**k/mp.factorial(k) for k in range(1, 21)], 384,
      'ln(2)^k/k!, k=1..20, at scale 2^384; exp2 residual below 2^-18.')

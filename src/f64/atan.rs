/// Relative half-width of the `atan`/`atan2` fast-path Ziv gate.  Over a dense
/// sweep of the active band the fast kernel's relative error peaks well below
/// 2⁻⁶⁸; the gate at 2⁻⁶³ keeps a comfortable margin and defers the rest to the
/// double-double kernel, which stays the correctly-rounded reference.
const ATAN_ZIV_EPS: f64 = 1.0842021724855044e-19; // 2⁻⁶³

/// Relative half-width of the `asin`/`acos` fast-path Ziv gate.  The table kernel
/// ([`asin_b`]) is end-to-end accurate to ~2⁻⁶¹ — including the reflection's 2×
/// cancellation of `π/2 − √t·B` near `|x| = ½` — so the gate at 2⁻⁵⁹ keeps a ~4×
/// margin and defers the rest (~1.5%) to the accurate [`asin_pos`].  Wider than
/// [`ATAN_ZIV_EPS`] because the lean table leg trades a touch of accuracy for a
/// much cheaper hot path.
const ASIN_ZIV_EPS: f64 = 1.734723475976807e-18; // 2⁻⁵⁹

/// Negate a double-double.
#[inline]
fn neg(v: DoubleDouble) -> DoubleDouble {
    DoubleDouble {
        high: -v.high,
        low: -v.low,
    }
}

/// `big + small` as a double-double when `|big.high| ≥ |small.high|`, via
/// Fast2Sum on the high words — leaner than the general [`DoubleDouble`] `Add`
/// (no 2Sum).  Used for the inverse-trig fast-path offsets (`π/2`, `π`), which
/// always dominate the kernel term `√t·B ≤ π/3`.
#[inline]
fn add_ordered(big: DoubleDouble, small: DoubleDouble) -> DoubleDouble {
    let s = fast_sum(big.high, small.high);
    fast_sum(s.high, s.low + (big.low + small.low))
}

/// Ziv gate: round `v` to `f64` when both ends of its `±eps_rel·|v|` (relative)
/// error interval agree, else `None` to fall back to the accurate kernel.
#[inline]
fn ziv_at(v: DoubleDouble, eps_rel: f64) -> Option<f64> {
    let eps = v.high.abs() * eps_rel;
    let lo = v.high + (v.low - eps);
    let hi = v.high + (v.low + eps);
    (lo == hi).then_some(lo)
}

/// [`ziv_at`] at the `atan`/`atan2` gate width.
#[inline]
fn ziv(v: DoubleDouble) -> Option<f64> {
    ziv_at(v, ATAN_ZIV_EPS)
}

/// Arctangent of a double-double `q ∈ [0, 1]`, as a double-double.
#[inline]
fn atan_dd(q: DoubleDouble) -> DoubleDouble {
    // For `q < 2⁻⁴⁰`, `atan(q) = q − q³/3 + …` agrees with `q` far below ½ ulp, so
    // the correctly-rounded `q.high` is the answer; dropping the low word also
    // protects against a `from_quotient` residual that underflowed to subnormal.
    if q.high < 9.094947017729282e-13 {
        return DoubleDouble {
            high: q.high,
            low: 0.0,
        };
    }

    let k = (q.high * 8.0).round_ties_even();
    let c = k * 0.125;
    let table = ATAN_TABLE[k as usize];

    // u = (q − c) / (1 + q·c), |u| ≤ 1/16 (c is an exact power-of-two multiple).
    let denom = q * c
        + DoubleDouble {
            high: 1.0,
            low: 0.0,
        };
    let u = (q + DoubleDouble { high: -c, low: 0.0 }) * denom.recip();

    atan_cell(table, u)
}

/// Accurate counterpart of [`atan_cell_fast`]: finish from a reduced cell via the
/// full double-double series `atan(k/8 + …) = table + u·Σ(−1)ᵏu²ᵏ/(2k+1)`.
///
/// `table = atan(k/8)` and `|u| ≤ 1/16`.  Shared by [`atan_dd`] and the fused
/// `atan2` reduction, which differ only in how they form `u`.
#[inline]
fn atan_cell(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    table + u * poly_dd(u * u, &ATAN_COEFFS)
}

/// Lean counterpart of [`atan_dd`], the inverse-trig functions' fast path.
///
/// The cell reduction is identical, but `atan(u)/u = 1 − w/3 + w²·(…)` peels the
/// two leading terms into double-double (`w = u²`, `1/3` carried as a
/// double-double coefficient) and evaluates only the tiny tail ([`ATAN_TAIL`])
/// in plain `f64`, replacing the 16-term double-double Horner.  A [`ziv`] gate on
/// the reconstructed result accepts it or defers to [`atan_dd`].
#[inline]
fn atan_dd_fast(q: DoubleDouble) -> DoubleDouble {
    if q.high < 9.094947017729282e-13 {
        return DoubleDouble {
            high: q.high,
            low: 0.0,
        };
    }

    let k = (q.high * 8.0).round_ties_even();
    let c = k * 0.125;
    let table = ATAN_TABLE[k as usize];

    let denom = q * c + ONE;
    let u = (q + DoubleDouble { high: -c, low: 0.0 }) * denom.recip();

    atan_cell_fast(table, u)
}

/// Finish the fast path from a reduced cell: `atan(k/8 + …) = table + u·(1 − u²/3 + …)`.
///
/// `table = atan(k/8)` and `u` is the cell-reduced argument (`|u| ≤ 1/16`).  Shared
/// by [`atan_dd_fast`] and [`atan_recip_fast`], which differ only in how they form `u`.
#[inline]
fn atan_cell_fast(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    let w = u * u;
    let wh = w.high;
    let w2 = wh * wh;
    // 1 − w/3 in double-double (ATAN_COEFFS[1] = −1/3); tail w²·(1/5 − w/7 + …).
    let bracket = (ONE + w * ATAN_COEFFS[1])
        + DoubleDouble {
            high: w2 * crate::poly(wh, &ATAN_TAIL),
            low: 0.0,
        };
    table + u * bracket
}

/// `atan(1/a)` for `a > 1`, the fast path's reflection leg, without ever forming
/// `1/a` as a double-double.
///
/// With `v = 1/a`, the cell reduction `u = (v − c)/(1 + v·c)` becomes
/// `u = (1 − a·c)/(a + c)` after multiplying through by `a`.  So the leg spends one
/// `1/a` (a plain `f64`, only to pick the cell `k = round(8/a)`) plus the cell's own
/// `recip` — **two** divisions, versus the **three** of `atan_dd_fast(ONE / a)`, whose
/// `DoubleDouble / f64` reciprocal alone costs two.  `1 − a·c` is exact (`a·c ≈ 1`
/// inside the cell and `from_product` is exact), so `u` is at least as accurate as
/// the original, and `|u| ≤ 1/16` exactly as in [`atan_dd_fast`].
#[inline]
fn atan_recip_fast(a: f64) -> DoubleDouble {
    let inv = 1.0 / a;

    // a > 1.1e12: atan(1/a) = 1/a to far below ½ ulp (matches `atan_dd_fast`'s guard,
    // since `(ONE / a).high == 1.0 / a`).
    if inv < 9.094947017729282e-13 {
        return DoubleDouble {
            high: inv,
            low: 0.0,
        };
    }

    let k = (inv * 8.0).round_ties_even();
    let c = k * 0.125;
    let table = ATAN_TABLE[k as usize];

    // u = (1 − a·c)/(a + c).  `1 − a·c` is exact and `a + c` is a normalized pair.
    let num = ONE + neg(DoubleDouble::from_product(a, c));
    let den = DoubleDouble::from_sum(a, c);
    let u = num * den.recip();

    atan_cell_fast(table, u)
}

/// `B(u) = asin(t)/t` for the cell `(r, j)` (`u = j/128 + r`, `|r| ≤ 2⁻⁸`), as an
/// un-normalized double-double: the tabulated lead `ASIN_LEAD[j]` plus the tiny
/// plain-`f64` correction `d = r·poly(r, ASIN_POLY[j])` folded into the low word.
///
/// The 33-cell table replaces the old whole-interval series (5 double-double
/// leads + degree-13 tail), so the correction is degree-7 in `|r| ≤ 2⁻⁸` and
/// stays ~2⁻¹⁰, keeping its `f64` evaluation rounding ~2⁻⁶³.  Like CORE-MATH's
/// `acos` kernel, but consumed un-normalized and with free FMA contraction
/// (round-to-nearest, no `FENV_ACCESS`).  The caller multiplies by the argument
/// (`t` directly, or the reflection's `√t = 2s`).
#[inline]
fn asin_b(r: f64, j: usize) -> DoubleDouble {
    let lead = ASIN_LEAD[j];
    let d = r * crate::poly(r, &ASIN_POLY[j]);
    DoubleDouble {
        high: lead.high,
        low: lead.low + d,
    }
}

/// `asin(a)` for `a = |x| ∈ [0, 1]`, the fast path, as a double-double in
/// `[0, π/2]`.  Direct series `a·B(a²)` for `a < ½`; for `a ≥ ½` the double-angle
/// reflection `asin(a) = π/2 − √t·B((1−a)/2)` with `t = 2−2a` — both `t` and
/// `u = ¼t` exact (Sterbenz), so only the multiplier `√t = 2s` needs a low word
/// (one division), avoiding the double-double `sqrt`.  A [`ziv_at`] gate accepts
/// it or defers to the accurate [`asin_pos(a, atan_dd)`](asin_pos).
#[inline]
fn asin_fast(a: f64) -> DoubleDouble {
    if a < 0.5 {
        let jf = (128.0 * (a * a)).round_ties_even();
        let r = crate::correct_mul_add(a, a, -(jf * 0.0078125)); // a² − j/128, exact-product residual
        asin_b(r, jf as usize) * a
    } else if a == 1.0 {
        FRAC_PI_2 // asin(1) = π/2 (and avoids √0 → 0/0 in the reflection)
    } else {
        let t = 2.0 * (1.0 - a); // 2 − 2a, exact (Sterbenz)
        let z = t.sqrt(); // √t = 2s
        let zl = crate::correct_mul_add(z, z, -t) * ((-0.5 / t) * z); // √t low word, one division
        let u = 0.25 * t; // exact, = (1−a)/2 = s²
        let jf = (128.0 * u).round_ties_even();
        let r = u - jf * 0.0078125; // exact
        add_ordered(
            FRAC_PI_2,
            neg(asin_b(r, jf as usize) * DoubleDouble { high: z, low: zl }),
        )
    }
}

/// `acos(x)` for `x ∈ [−1, 1]`, the fast path, as a double-double in `[0, π]`.
/// `acos(x) = π/2 − asin(x)`: the direct series for `|x| < ½`; for `|x| ≥ ½` the
/// double-angle `2·asin(s) = √t·B(u)` (`s = √((1−|x|)/2)`), signed through `√t`
/// and offset by 0 (`x > 0`) or `π` (`x < 0`) — the same table and reduction as
/// [`asin_fast`].
#[inline]
fn acos_fast(x: f64) -> DoubleDouble {
    let a = x.abs();
    if a < 0.5 {
        let jf = (128.0 * (x * x)).round_ties_even();
        let r = crate::correct_mul_add(x, x, -(jf * 0.0078125));
        // acos(x) = π/2 − asin(x) = π/2 + (−x)·B(x²)
        add_ordered(FRAC_PI_2, asin_b(r, jf as usize) * (-x))
    } else if a == 1.0 {
        // acos(1) = 0, acos(−1) = π (and avoids √0 → 0/0 in the reflection).
        if x.is_sign_negative() {
            PI
        } else {
            DoubleDouble {
                high: 0.0,
                low: 0.0,
            }
        }
    } else {
        let t = 2.0 * (1.0 - a); // 2 − 2a, exact (Sterbenz)
        let z = t.sqrt().copysign(x); // √t·sign(x) = ±2s
        let zl = crate::correct_mul_add(z, z, -t) * ((-0.5 / t) * z);
        let u = 0.25 * t;
        let jf = (128.0 * u).round_ties_even();
        let r = u - jf * 0.0078125;
        let p = asin_b(r, jf as usize) * DoubleDouble { high: z, low: zl };
        if x.is_sign_negative() {
            add_ordered(PI, p)
        } else {
            p
        }
    }
}

/// `asin(|x|)` for `a = |x| ∈ [0, 1]`, as a double-double in `[0, π/2]`.
///
/// `asin(a) = atan(a/√(1−a²))`; the branch keeps the `atan` argument in `[0, 1]`.
#[inline]
fn asin_pos<K: Fn(DoubleDouble) -> DoubleDouble>(a: f64, kernel: K) -> DoubleDouble {
    if a == 1.0 {
        return FRAC_PI_2;
    }

    // c = √(1 − a²) as a double-double (a² exact, so the cancellation near a = 1
    // is captured).
    let c = sqrt_dd(ONE + neg(DoubleDouble::from_product(a, a)));

    if a <= c.high {
        kernel(DoubleDouble { high: a, low: 0.0 } * c.recip())
    } else {
        // a/c > 1 ⇒ atan(a/c) = π/2 − atan(c/a)
        FRAC_PI_2 + neg(kernel(c / a))
    }
}

/// Magnitude of `atan(|x|)` in `[0, π/2]`, as a double-double, via `kernel`.
#[inline]
fn atan_mag<K: Fn(DoubleDouble) -> DoubleDouble>(a: f64, kernel: K) -> DoubleDouble {
    if a > 1.0 {
        // atan(a) = π/2 − atan(1/a)
        FRAC_PI_2 + neg(kernel(ONE / a))
    } else {
        kernel(DoubleDouble { high: a, low: 0.0 })
    }
}

/// Arctangent
#[must_use]
#[inline]
pub fn atan(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }

    let a = x.abs();
    if a.is_infinite() {
        return core::f64::consts::FRAC_PI_2.copysign(x);
    }

    // Fast path: for |x| > 1 reflect via atan(a) = π/2 − atan(1/a) using the
    // division-frugal [`atan_recip_fast`]; otherwise the direct cell kernel.  The
    // accurate fallback keeps the shared [`atan_mag`] reflection.
    let fast = if a > 1.0 {
        FRAC_PI_2 + neg(atan_recip_fast(a))
    } else {
        atan_dd_fast(DoubleDouble { high: a, low: 0.0 })
    };
    let magnitude = ziv(fast).unwrap_or_else(|| {
        let m = atan_mag(a, atan_dd);
        m.high + m.low
    });
    magnitude.copysign(x)
}

/// Arcsine
#[must_use]
#[inline]
pub fn asin(x: f64) -> f64 {
    let a = x.abs();
    if !(a <= 1.0) {
        return f64::NAN; // |x| > 1 or NaN
    }

    let magnitude = ziv_at(asin_fast(a), ASIN_ZIV_EPS).unwrap_or_else(|| {
        let m = asin_pos(a, atan_dd);
        m.high + m.low
    });
    magnitude.copysign(x)
}

/// Arccosine
#[must_use]
#[inline]
pub fn acos(x: f64) -> f64 {
    if !(x.abs() <= 1.0) {
        return f64::NAN; // |x| > 1 or NaN
    }

    ziv_at(acos_fast(x), ASIN_ZIV_EPS).unwrap_or_else(|| {
        // acos(x) = π/2 − asin(x): π/2 − asin_pos(x) for x ≥ 0, π/2 + asin_pos(|x|)
        // for x < 0 — via the accurate atan-based `asin_pos`.
        let s = asin_pos(x.abs(), atan_dd);
        let m = if x.is_sign_negative() {
            FRAC_PI_2 + s
        } else {
            FRAC_PI_2 + neg(s)
        };
        m.high + m.low
    })
}

/// Magnitude of `atan2(y, x)` in `[0, π]` for finite nonzero `a = |x|`, `b = |y|`.
#[inline]
fn atan2_mag(a: f64, b: f64, x_negative: bool) -> f64 {
    let (big, small, swapped) = if a >= b { (a, b, false) } else { (b, a, true) };

    let theta = |cell: fn(DoubleDouble, DoubleDouble) -> DoubleDouble| {
        // φ = atan(small/big) ∈ [0, π/4], or π/2 − atan(small/big) when `swapped`.
        let q = small / big;
        let inner = if q < 9.094947017729282e-13 {
            // Tiny ratio: atan(q) = q far below ½ ulp, and the *unscaled* IEEE
            // quotient `small/big` is correctly rounded down into the subnormals.
            DoubleDouble { high: q, low: 0.0 }
        } else {
            // Scale both legs so the larger lands in [1, 2): exact and
            // ratio-preserving, keeping `small − c·big` / `big + c·small` clear of
            // overflow and the small leg out of the subnormals.
            let (_, exp) = super::frexp(big);
            let big = super::ldexp(big, 1 - exp);
            let small = super::ldexp(small, 1 - exp);

            // Cell reduction without forming small/big as a double-double: with
            // ratio = small/big, `u = (ratio − c)/(1 + ratio·c) = (small − c·big)/(big
            // + c·small)`.  `k = round(8·ratio)` reuses the `q` already in hand
            // (scaling preserves the ratio exactly), so the leg spends only that one
            // `q` division plus this `recip` — two, versus the four of the
            // `from_quotient` path (the `q` test, the two-division quotient, the cell
            // `recip`).  `small − c·big` is exact (c·big ≈ small in-cell, `from_product`
            // exact), so `u` is at least as accurate, and `|u| ≤ 1/16` as before.
            let k = (q * 8.0).round_ties_even();
            let c = k * 0.125;
            let table = ATAN_TABLE[k as usize];

            let num = DoubleDouble {
                high: small,
                low: 0.0,
            } + neg(DoubleDouble::from_product(c, big));
            let den = DoubleDouble {
                high: big,
                low: 0.0,
            } + DoubleDouble::from_product(c, small);
            let u = num * den.recip();

            cell(table, u)
        };

        let phi = if swapped {
            FRAC_PI_2 + neg(inner)
        } else {
            inner
        };
        if x_negative { PI + neg(phi) } else { phi }
    };

    ziv(theta(atan_cell_fast)).unwrap_or_else(|| {
        let m = theta(atan_cell);
        m.high + m.low
    })
}

/// Arctangent of `y / x`, using the signs of both to select the quadrant
///
/// The result is the angle in `(-π, π]` between the positive `x`-axis and the
/// point `(x, y)`, carrying the sign of `y`.
#[must_use]
#[inline]
pub fn atan2(y: f64, x: f64) -> f64 {
    use core::f64::consts::{FRAC_PI_2, FRAC_PI_4, PI};

    /// Correctly-rounded `f64` of 3π/4.
    const THREE_PI_4: f64 = 2.356194490192345;

    if x.is_nan() || y.is_nan() {
        return f64::NAN;
    }

    if x.is_infinite() || y.is_infinite() {
        let magnitude = match (x.is_infinite(), y.is_infinite()) {
            (true, true) if x.is_sign_positive() => FRAC_PI_4,
            (true, true) => THREE_PI_4,
            (true, false) if x.is_sign_positive() => 0.0,
            (true, false) => PI,
            (false, true) => FRAC_PI_2,
            (false, false) => unreachable!(),
        };
        return magnitude.copysign(y);
    }

    if y == 0.0 {
        return if x.is_sign_positive() { 0.0 } else { PI }.copysign(y);
    }
    if x == 0.0 {
        return FRAC_PI_2.copysign(y);
    }

    atan2_mag(x.abs(), y.abs(), x.is_sign_negative()).copysign(y)
}

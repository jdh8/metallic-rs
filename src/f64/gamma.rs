//! binary exponent so it never overflows even for very negative `z`.  A lean
//! lower-degree fast leg is Ziv-gated against the ≈2⁻¹¹⁰ accurate path; there is
//! no f64 oracle, so correctness is verified against MPFR (`tests/cases`).
//!
//! Constants below were generated by `tools/gen_gamma_f64.py`.
//! Do not edit by hand; re-run the generator instead.

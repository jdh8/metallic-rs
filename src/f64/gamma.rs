/// `Γ(z)` overflows to `+∞` at and above this `z`
const TGAMMA_OVERFLOW: f64 = 171.6243769563027;

/// Below this `|z|`, the pole `Γ(z) ≈ 1/z` overflows to `±∞`
const TGAMMA_TINY: f64 = 5.562684646268003e-309;

/// At or below this `z`, every `Γ(z)` hump rounds to a signed zero
const TGAMMA_UNDERFLOW: f64 = -179.5;
// checks: Γ(overflow)≈1.798e+308 (MAX=1.798e+308); Γ(tiny)≈inf; |Γ(underflow)|≈0.000e+00

/// Keep the divisor product's high word below this (rescale by `2⁵¹²`, tracking a
/// binary exponent) so the long negative-`z` product never overflows `f64`.
const PRODUCT_RESCALE: f64 = crate::exp2i(512);

/// Ziv gate for the tgamma fast leg, relative to the result.
///
/// The lean [`TGAMMA_FAST`] minimax is ≈2⁻⁷² (the recurrence's exact factors add
/// only ≈2⁻⁹⁸); `2⁻⁶⁶` keeps a ~60× margin.
const TGAMMA_ZIV_EPS: f64 = 1.3552527156068805e-20; // 2^-66

/// `Γ(z)` over the recurrence range as `(value, e2)` with `Γ(z) = value · 2`<sup>`e2`</sup>
///
/// Reduce `z` into `[2.375, 3.375]`, evaluate `Γ(2.875 + d)` with `coeffs`, then
/// walk the recurrence.  Upward (`i > 0`) the partial products stay below the
/// final `Γ(z)`, so no scaling is needed; downward (`i < 0`) the divisor product
/// is rescaled by `2⁵¹²` whenever it grows large, with the total folded into `e2`.
#[inline]
fn tgamma_kernel(z: f64, coeffs: &[DoubleDouble]) -> (DoubleDouble, i64) {
    let i = (z - TGAMMA_CENTER).round_ties_even();
    // The reduced argument `d = z − (2.875 + i)` must be exact: a plain-f64
    // `z − 2.875 − i` loses `z`'s low bits when `z ≪ 2.875` (the small-`z` pole).
    // `2.875 + i` is exact for any integer `i`, so `from_sum` captures `d` in full.
    let d = DoubleDouble::from_sum(z, -(TGAMMA_CENTER + i));
    let value = poly_dd(d, coeffs);

    // SAFETY-free: `|i|` is a small integer (`z` is finite and bounded by the
    // overflow/underflow guards), so the casts below are exact.
    let steps = i.abs() as i64;

    if i > 0.0 {
        // Γ(z) = Γ(z−i)·(z−1)(z−2)…(z−i); every factor is exact and > 1.
        let mut value = value;
        let mut k = 0.0;
        for _ in 0..steps {
            k += 1.0;
            value = value * DoubleDouble::from_sum(z, -k);
        }
        (value, 0)
    } else if i < 0.0 {
        // Γ(z) = Γ(z−i)/[z(z+1)…(z+|i|−1)], the product carrying a binary exponent.
        let mut product = DoubleDouble { high: z, low: 0.0 };
        let mut e2: i64 = 0;
        let mut k = 0.0;
        for _ in 1..steps {
            k += 1.0;
            product = product * DoubleDouble::from_sum(z, k);
            if product.high.abs() > PRODUCT_RESCALE {
                product = DoubleDouble {
                    high: fast_ldexp(product.high, -512),
                    low: fast_ldexp(product.low, -512),
                };
                e2 += 512;
            }
        }
        (value * product.recip(), -e2)
    } else {
        (value, 0)
    }
}

/// The gamma function
#[must_use]
#[inline]
pub fn tgamma(z: f64) -> f64 {
    if z.is_nan() {
        return z;
    }
    if z == f64::INFINITY {
        return f64::INFINITY;
    }

    // Γ(±0) = ±∞, and Γ(z) ≈ 1/z overflows for |z| below `TGAMMA_TINY`.
    if z.abs() < TGAMMA_TINY {
        return f64::INFINITY.copysign(z);
    }

    // Γ exceeds `f64::MAX` past `TGAMMA_OVERFLOW`; bail before the recurrence loop.
    if z >= TGAMMA_OVERFLOW {
        return f64::INFINITY;
    }

    // Non-positive integers are poles; below `TGAMMA_UNDERFLOW` every hump rounds
    // to a signed zero (sign alternating with each pole).
    if z < 0.0 {
        if z == z.floor() {
            return f64::NAN;
        }
        if z <= TGAMMA_UNDERFLOW {
            return if (z.floor() as i64) & 1 == 0 {
                0.0
            } else {
                -0.0
            };
        }
    }

    // Ziv two-step: the lean leg is correctly rounded for a comfortably-normal
    // result unless it straddles a boundary, where the double-double path resolves
    // it.  Scaled (`e2 ≠ 0`) and near-subnormal results go straight to the accurate
    // path, whose `round_general_signed64` handles the subnormal grid.
    let (value, e2) = tgamma_kernel(z, &TGAMMA_FAST);
    if e2 == 0 {
        let err = value.high.abs() * TGAMMA_ZIV_EPS;
        let lo = value.high + (value.low - err);
        let hi = value.high + (value.low + err);
        if lo == hi && lo.abs() >= f64::MIN_POSITIVE * 2.0 {
            return lo;
        }
    }

    let (value, e2) = tgamma_kernel(z, &TGAMMA_DD);
    round_general_signed64(value, e2)
}

//! Error function family: `erf`, `erfc`.
//!
//! `erf(x) = x·P(x²)` for `|x| < 0.4375`; otherwise `erfc(x) = t·exp(Q(t) − x²)`
//! with `t = 2/(2+x)`, `Q` a per-segment double-double minimax (see
//! `tools/gen_erf_f64.py`), and `x²` formed exactly so the Gaussian decay is
//! subtracted without loss.  `erf` is odd; for `|x| ∈ [0.4375, 6.25]` it skips
//! the `erfc` bridge entirely, reading `erf(x) = P_i(x − i/8)` from a per-cell
//! table ([`ERF_TABLE`], no `exp`) and Ziv-gating against the bridge.  Each
//! kernel has a lean lower-degree double-double fast leg (a plain-f64 polynomial
//! cannot gate, since erfc's relative error equals `Q`'s *absolute* error)
//! accepted by a Ziv test, falling back to the ≈2⁻¹⁰⁰ accurate path on a
//! rounding-boundary straddle — past `f64` correct-rounding hardness.
//!
//! Constants below were generated by `tools/gen_erf_f64.py`.
//! Do not edit by hand; re-run the generator instead.

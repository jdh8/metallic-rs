/// Ziv gate for the erfc / erf-bridge fast leg, as an absolute bound on the
/// double-double mantissa (erfc) or result (1 − erfc, 2 − erfc).
///
/// The lean leg (prefix `Q` ≈2⁻⁷² plus [`exp_dd_of_dd_fast`] ≈2⁻⁶⁸) is good to
/// ≈2⁻⁶⁷; `2⁻⁶²` keeps a ~30× margin.
const ERFC_ZIV_EPS: f64 = 1.084_202_172_485_504_4e-19; // 2^-62

/// Ziv gate for the `erf_small` fast leg, relative (its result ≈ `x` can be tiny).
const ERF_SMALL_ZIV_EPS: f64 = 1.355_252_715_606_88e-20; // 2^-66

/// Ziv gate for the table-driven `erf` fast leg, relative (`erf ∈ [0.46, 1)`).
///
/// The cell polynomial is good to ≈2⁻⁶⁷ (degree-11 minimax ≈2⁻⁷¹ plus the `f64`
/// tail's ≈2⁻⁶⁷); `2⁻⁶²` keeps a ~30× margin.
const ERF_TABLE_ZIV_EPS: f64 = 1.084_202_172_485_504_4e-19; // 2^-62

/// Negate a double-double.
#[inline]
fn neg(a: DoubleDouble) -> DoubleDouble {
    DoubleDouble {
        high: -a.high,
        low: -a.low,
    }
}

/// `value · 2`<sup>`q`</sup> as a double-double at true magnitude.
///
/// Used to bring an `erfc` mantissa back to its actual value for the benign
/// subtractions `1 − erfc` (erf) and `2 − erfc` (erfc of a negative argument),
/// where `q ≤ 0` keeps the scaling exact and the result normal.
#[inline]
const fn scale_dd(value: DoubleDouble, q: i64) -> DoubleDouble {
    DoubleDouble {
        high: fast_ldexp(value.high, q),
        low: fast_ldexp(value.low, q),
    }
}

/// Double-double prefix length for the mixed-precision fast-leg evaluator.
///
/// The first `SPLIT` coefficients are kept in double-double; the rest become a
/// plain-`f64` tail.  A power of two so [`poly_dd_split`] reaches `vᵏ` by repeated
/// squaring.  `|v| ≤ 0.154` here, so the first dropped term `c·v^SPLIT` is ≲2⁻¹⁰
/// of `Q` and the whole tail's `f64` slip stays well under the fast leg's 2⁻⁶²
/// Ziv budget — confirmed by the fast-leg fallback rate being unchanged from the
/// all-double-double evaluation.
const SPLIT: usize = 4;

/// Fast-leg `Q(v) = Σ coeffs[k]·vᵏ` with the high-degree tail in plain `f64`.
///
/// The tail terms (degree `≥ SPLIT`) are a small fraction of `Q` (see [`SPLIT`]),
/// so evaluating them in `f64` instead of double-double costs no extra Ziv
/// fallbacks while doing roughly half the double-double work.  The double-double
/// prefix, the `f64` tail, and `vᵏ` are independent, so the critical path is
/// shallow.
///
/// Only for the Ziv-gated *fast* legs; the accurate path stays full double-double
/// (it is what guarantees correct rounding).  `coeffs.len()` must exceed `SPLIT`.
#[inline]
fn poly_dd_split(v: DoubleDouble, coeffs: &[DoubleDouble]) -> DoubleDouble {
    // Tail Σ coeffs[SPLIT+d].high · v.high^d in plain-f64 Horner (the low words and
    // v.low are dropped — harmless, the tail is a small fraction of `Q`).
    let mut tail = 0.0_f64;
    for c in coeffs[SPLIT..].iter().rev() {
        tail = crate::fast_mul_add(tail, v.high, c.high);
    }

    // vᵏ = v^SPLIT by repeated squaring (SPLIT is a power of two).
    let mut vk = v;
    let mut e = 1;
    while e < SPLIT {
        vk = vk * vk;
        e *= 2;
    }

    // Q = prefix(v) + v^SPLIT · tail; the three parts are computed independently.
    poly_dd(v, &coeffs[..SPLIT]) + vk * tail
}

/// `erf(x) = x·P(x²)` as a double-double for `|x| < 0.4375`
///
/// `coeffs` is the full [`ERF_SMALL_DD`] for the accurate path or
/// [`ERF_SMALL_FAST`] for the fast leg.  Forming `x²` exactly and multiplying by
/// `x` last keeps the through-origin zero and the leading `2/√π` behaviour exact.
/// `split` routes the fast leg through [`poly_dd_split`] (mixed precision).
#[inline]
fn erf_small_eval(x: f64, coeffs: &[DoubleDouble], split: bool) -> DoubleDouble {
    let u = DoubleDouble::from_product(x, x);
    let p = if split {
        poly_dd_split(u, coeffs)
    } else {
        poly_dd(u, coeffs)
    };
    p * x
}

/// `erf(ax)` as a double-double for `ax ∈ [0.4375, 6.25]`, straight from
/// [`ERF_TABLE`] — the fast leg that sidesteps the `erfc` bridge's `exp`.
///
/// `i = round(8·ax)` picks the cell (`xi = i/8`); `h = ax − xi` is exact
/// (Sterbenz, `|h| ≤ 1/16`).  The `c3..c11` tail is summed in `f64`, then the
/// `c2`/`c1`/`c0` leads fold in double-double — a few double-double FMAs versus
/// the bridge's reciprocal + `Q` polynomial + `exp`.
#[inline]
fn erf_table_eval(ax: f64) -> DoubleDouble {
    let fi = (ax * 8.0).round_ties_even();
    // SAFETY: ax ∈ [0.4375, 6.25] ⇒ 8·ax ∈ [3.5, 50] ⇒ fi ∈ [4, 50].
    let cell = &ERF_TABLE[unsafe { fi.to_int_unchecked::<usize>() } - 4];
    let h = ax - fi * 0.125;

    // P(h) = c0 + h·(c1 + h·(c2 + h·tail)), tail = c3 + c4·h + … in f64.
    let tail = crate::poly(h, &cell.tail);
    let acc = cell.c2
        + DoubleDouble {
            high: h * tail,
            low: 0.0,
        };
    let acc = cell.c1 + acc * h;
    cell.c0 + acc * h
}

/// Select the `erfc` segment for `x ≥ 0.4375`: its anchor `t`, the accurate `Q`
/// coefficients, and the lower-degree fast-leg `Q` coefficients.
#[inline]
fn erfc_segment(x: f64) -> (f64, &'static [DoubleDouble], &'static [DoubleDouble]) {
    let i = if x <= ERFC_BREAKS[0] {
        0
    } else if x <= ERFC_BREAKS[1] {
        1
    } else if x <= ERFC_BREAKS[2] {
        2
    } else if x <= ERFC_BREAKS[3] {
        3
    } else {
        4
    };
    // Return the slices by `match` rather than indexing a freshly-built array of
    // fat pointers (which the optimizer would materialize on the stack each call).
    let (accurate, fast): (&[DoubleDouble], &[DoubleDouble]) = match i {
        0 => (&ERFC_Q0, &ERFC_QF0),
        1 => (&ERFC_Q1, &ERFC_QF1),
        2 => (&ERFC_Q2, &ERFC_QF2),
        3 => (&ERFC_Q3, &ERFC_QF3),
        _ => (&ERFC_Q4, &ERFC_QF4),
    };
    (ERFC_ANCHORS[i], accurate, fast)
}

/// `erfc(x)` for `x ∈ [0.4375, 27.226…]` as `(mantissa ∈ [1, 2), q)`, i.e.
/// `erfc(x) = mantissa · 2`<sup>`q`</sup>
///
/// `erfc(x) = t·exp(Q(t) − x²)`, `t = 2/(2+x)`: `Q(t)` from the per-segment
/// double-double minimax in `v = t − anchor`, `x²` exact, the exponent `W = Q − x²`
/// carried in double-double, and the `t` factor folded into the mantissa before
/// renormalizing into `[1, 2)`.  `coeffs` selects accuracy; `fast` picks both the
/// mixed-precision `Q` ([`poly_dd_split`]) and the matching `exp` leg.
#[inline]
fn erfc_eval(x: f64, anchor: f64, coeffs: &[DoubleDouble], fast: bool) -> (DoubleDouble, i64) {
    // t = 2/(2+x) to ≈2⁻¹⁰⁶: `2 + x` must be exact (a plain `2.0 + x` would round
    // first, injecting a ≈2⁻⁵³ error into both the t-factor and the Q variable).
    let t = DoubleDouble::from_sum(2.0, x).recip() * 2.0;
    let v = t + DoubleDouble {
        high: -anchor,
        low: 0.0,
    };
    let q = if fast {
        poly_dd_split(v, coeffs)
    } else {
        poly_dd(v, coeffs)
    };

    // W = Q(t) − x², with x² exact and the difference in double-double.
    let w = q + neg(DoubleDouble::from_product(x, x));

    // exp(W) = m · 2^qe, then erfc = t·m·2^qe renormalized so the high word ∈ [1, 2).
    let (m, qe) = if fast {
        exp_dd_of_dd_fast(w)
    } else {
        exp_dd_of_dd(w)
    };
    let prod = t * m;
    let e2 = (prod.high.to_bits() >> super::EXP_SHIFT) as i64 - 1023;
    let mantissa = DoubleDouble {
        high: fast_ldexp(prod.high, -e2),
        low: fast_ldexp(prod.low, -e2),
    };
    (mantissa, qe + e2)
}

/// Below this `|x|`, `x²` underflows to zero and the result needs subnormal-safe
/// rounding (its ulp drops below the double-double low word in the first binade).
const ERF_TINY: f64 = crate::exp2i(-1000);

/// `erf(x) = x·(2/√π)` correctly rounded for tiny `|x|` (below [`ERF_TINY`])
///
/// There `x²` underflows to zero, so every higher term of `erf(x) = x·P(x²)`
/// vanishes and `erf(x) = x·(2/√π)` exactly.  A plain `x·c` would round near the
/// subnormal grid first and lose bits, so the product is formed at normal
/// magnitude and finished once with [`round_general64`].
#[cold]
fn erf_tiny(x: f64) -> f64 {
    // Normalize `|x|` to `mant ∈ [1, 2) · 2^ex` (×2⁵⁴ first so a subnormal is normal).
    let scaled = (x.abs() * crate::exp2i(54)).to_bits();
    let ex = (scaled >> super::EXP_SHIFT) as i64 - 1023 - 54;
    let mant = f64::from_bits((scaled & 0x000f_ffff_ffff_ffff) | 0x3ff0_0000_0000_0000);

    let p = ERF_SMALL_DD[0] * mant; // (2/√π)·mant ∈ [1.128, 2.256)
    let (m, q) = if p.high >= 2.0 {
        (p * 0.5, ex + 1)
    } else {
        (p, ex)
    };
    round_general64(m, q).copysign(x)
}

/// The error function
#[must_use]
#[inline]
pub fn erf(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }

    let ax = x.abs();

    if ax < 0.4375 {
        if ax < ERF_TINY {
            return erf_tiny(x);
        }
        // Fast leg: a lower-degree double-double minimax, accepted unless its
        // relative error interval straddles a rounding boundary.
        let e = erf_small_eval(x, &ERF_SMALL_FAST, true);
        let eps = e.high.abs() * ERF_SMALL_ZIV_EPS;
        let lo = e.high + (e.low - eps);
        let hi = e.high + (e.low + eps);
        if lo == hi {
            return lo;
        }
        let e = erf_small_eval(x, &ERF_SMALL_DD, false);
        return e.high + e.low;
    }

    // erf rounds to ±1 (covering ±∞) once erfc drops below ½ ulp.
    if ax > ERF_ONE_THRESHOLD {
        return 1.0_f64.copysign(x);
    }

    // Table-driven fast leg: erf(ax) = P_i(ax − i/8) directly, no `exp`.  Accepted
    // unless its relative error interval straddles a rounding boundary.
    let e = erf_table_eval(ax);
    let eps = e.high.abs() * ERF_TABLE_ZIV_EPS;
    let lo = e.high + (e.low - eps);
    let hi = e.high + (e.low + eps);
    if lo == hi {
        return lo.copysign(x);
    }

    // Accurate fallback: erf(x) = sign(x)·(1 − erfc(|x|)); erfc ∈ (0, 0.536] here,
    // so 1 − erfc ∈ [0.46, 1) — no cancellation, and the result is always normal.
    let (anchor, accurate, _) = erfc_segment(ax);
    let (m, q) = erfc_eval(ax, anchor, accurate, false);
    let r = ONE + neg(scale_dd(m, q));
    (r.high + r.low).copysign(x)
}

/// The complementary error function `1 − erf(x)`
#[must_use]
#[inline]
pub fn erfc(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }

    // erfc → 2 for very negative x (covering −∞) and → +0 for large x (covering +∞).
    if x < -ERF_ONE_THRESHOLD {
        return 2.0;
    }
    if x >= ERFC_ZERO_THRESHOLD {
        return 0.0;
    }

    let ax = x.abs();

    if ax < 0.4375 {
        // erfc(x) = 1 − erf(x); the result is ≈ 1, so carry 1 − erf in double-double
        // (the accurate small kernel — this regime is cheap and not the hot path).
        let r = ONE + neg(erf_small_eval(x, &ERF_SMALL_DD, false));
        return r.high + r.low;
    }

    let (anchor, accurate, fast) = erfc_segment(ax);

    // Fast leg, Ziv-gated against the accurate path.
    let (m, q) = erfc_eval(ax, anchor, fast, true);

    if x > 0.0 {
        // erfc spans the full underflow range; gate the mantissa, keeping the
        // normal/subnormal transition (`q < −1021`) on the accurate path.
        if q >= -1021 {
            let lo = m.high + (m.low - ERFC_ZIV_EPS);
            let hi = m.high + (m.low + ERFC_ZIV_EPS);
            if lo == hi {
                return fast_ldexp(lo, q);
            }
        }
        let (m, q) = erfc_eval(ax, anchor, accurate, false);
        round_general64(m, q)
    } else {
        // erfc(−|x|) = 2 − erfc(|x|); erfc(|x|) ∈ (0, 0.536], normal, so 2 − it ∈ [1.46, 2).
        let r = TWO + neg(scale_dd(m, q));
        let lo = r.high + (r.low - ERFC_ZIV_EPS);
        let hi = r.high + (r.low + ERFC_ZIV_EPS);
        if lo == hi {
            return lo;
        }
        let (m, q) = erfc_eval(ax, anchor, accurate, false);
        let r = TWO + neg(scale_dd(m, q));
        r.high + r.low
    }
}

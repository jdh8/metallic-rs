/// One base's cell data for [`log_lookup`]: the logarithm of 2 and of each
/// [`LOG2F_R`] reciprocal in that base, split against a `2⁻⁴⁵` grid, plus a
/// degree-6 minimax of `log_b(1+d)/d` on `|d| ≤ 2⁻⁷`.
///
/// Every `hi` word (and `exp_hi`) is a multiple of `2⁻⁴⁵`, so
/// `e·exp_hi + hi[j]` — at most `2⁷` in magnitude over the promoted-`f32`
/// exponent range in every base — spans at most 52 bits and is **exact**
/// whether or not the multiply-add fuses.  Base conversion therefore costs
/// no extra rounding: every base gets the same two closing roundings.
/// The `lo` words (≤ 2⁻⁴⁶) ride the polynomial's addend.
///
/// Table values are mathematical constants computed independently with
/// mpmath (200-bit): `hi = nint(v·2⁴⁵)/2⁴⁵`, `lo = RN(v − hi)` for
/// `v = −log_b r` (and `log_b 2` for the exponent pair).  The polynomials
/// (relative error ≈ 2⁻⁵⁸) come from
/// `ratapprox --function="<log2(1+x)/x | log(1+x)/x | log(1+x)/(x*log(10))>"
///   --dom="[-0.0078125,0.0078125]" --num="[1,x,...,x^6]" --den="[1]"
///   --numF="[D]"`.

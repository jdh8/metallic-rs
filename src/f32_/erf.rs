/// `erf(x)` for `|x| < 0.4375` as `x·P(x²)`
///
/// The minimax coefficients (from CORE-MATH) and this evaluation order are
/// chosen so that the single `f64` product rounds correctly to `f32`; `c[0]` is
/// the correctly-rounded `2/√π`, keeping the tiny-argument regime exact.
#[inline]
fn erf_small(x: f64) -> f64 {
    const C: [f64; 8] = [
        1.128_379_167_095_512_6,
        -0.376_126_389_031_781_8,
        0.112_837_916_703_424_2,
        -0.026_866_170_388_309_935,
        0.005_223_972_335_150_932_5,
        -0.000_854_773_440_605_154_9,
        0.000_120_184_475_094_822_11,
        -1.372_114_526_702_553_9e-5,
    ];

    let z2 = x * x;
    let z4 = z2 * z2;
    let z8 = z4 * z4;
    let c0 = crate::fast_mul_add(
        z4,
        crate::fast_mul_add(z2, C[3], C[2]),
        crate::fast_mul_add(z2, C[1], C[0]),
    );
    let c4 = crate::fast_mul_add(
        z4,
        crate::fast_mul_add(z2, C[7], C[6]),
        crate::fast_mul_add(z2, C[5], C[4]),
    );

    x * crate::fast_mul_add(z8, c4, c0)
}

/// `erfc(x)` as a double-double for finite `x` in `[0.4375, 0x1.41bbf8p+3]`
///
/// Uses `erfc(x) = (2/(2+x))·exp(Q(t) - x²)` with `t = 2/(2+x)`, where the
/// degree-22 polynomial `Q(t)` approximates `x² + ln(erfc(x)·(2+x)/2)` — a
/// smooth, `O(1)` function.  `x²` is formed exactly and the exponent is carried
/// in double-double so the single-rounding error of `exp` dominates.
///
/// `Q(t)` was generated with
/// `ratapprox --function="(2/x-2)^2 + log(erfc(2/x-2)) - log(x)"
///  --dom="[0.16,0.8205]" --num="[1,x,...,x^22]" --den="[1]" --weight=1`.
fn erfc_dd(x: f64) -> DoubleDouble {
    const Q: [f64; 23] = [
        -1.265_512_122_089_828_2,
        0.999_999_909_841_198_7,
        0.375_002_743_471_048_67,
        0.083_281_051_140_198_57,
        -0.085_237_288_049_587_05,
        -0.150_760_071_598_243_3,
        -0.037_328_341_350_081_02,
        -0.307_000_710_902_394_2,
        1.813_760_492_069_090_2,
        -6.732_827_419_146_119,
        22.932_196_277_953_373,
        -63.486_057_493_716_345,
        143.005_106_419_187_14,
        -264.328_775_383_285_2,
        394.457_961_771_325_7,
        -465.717_326_957_287_7,
        428.276_437_921_645_1,
        -302.337_694_534_648_9,
        160.625_086_292_286_43,
        -62.167_646_608_866_96,
        16.552_127_045_415_844,
        -2.710_346_863_587_057_3,
        0.205_553_868_706_903_5,
    ];

    let t = DoubleDouble::from_quotient(2.0, 2.0 + x);
    let q = crate::poly(t.high, &Q);

    // exponent W = Q(t) - x², with x² exact and the difference in double-double
    let x2 = DoubleDouble::from_product(x, x);
    let w = DoubleDouble { high: q, low: 0.0 }
        + DoubleDouble {
            high: -x2.high,
            low: -x2.low,
        };

    // exp(W) = exp(W.high)·exp(W.low) ≈ exp(W.high)·(1 + W.low)
    t * (finite_exp(w.high) * (1.0 + w.low))
}

/// Relative gate on the direct erfc table, including binary64 evaluation.
/// The generator's interpolation/rounding bound is below half this gate;
/// `ziv_soundness` also measures all three evaluated and reflected legs.
const ERFC_TABLE_EPS: f64 = crate::exp2i(-38);

/// Covers the subtraction rounding in `1 - erfc(x)` and `2 - erfc(x)`.
const REFLECT_EPS: f64 = crate::exp2i(-51);

/// Direct erfc in a centered 1/16-wide cell. Both the scaled input and the
/// residual are exact: the caller promotes a finite f32 in [0.4375, 10.055].
#[inline]
fn erfc_table(x: f64) -> f64 {
    let a = 16.0 * x;
    let n = a.round_ties_even();
    // SAFETY: the caller's interval gives 7 <= n <= 161.
    let index = unsafe { n.to_int_unchecked::<usize>() } - 7;
    crate::poly(a - n, &ERFC_F32_TABLE[index])
}

#[inline]
fn erf_fast(x: f64) -> (f64, f64) {
    let e = erfc_table(x);
    (1.0 - e, crate::fast_mul_add(e, ERFC_TABLE_EPS, REFLECT_EPS))
}

#[inline]
fn erfc_fast(x: f64) -> (f64, f64) {
    let e = erfc_table(x.abs());
    let negative = f64::from(x.is_sign_negative());
    // Sign insertion and the 0/2 offset implement erfc(-x) = 2 - erfc(x)
    // without a data-dependent branch over the table evaluation.
    (
        crate::fast_mul_add(2.0, negative, e.copysign(x)),
        crate::fast_mul_add(e, ERFC_TABLE_EPS, negative * REFLECT_EPS),
    )
}

/// The error function
#[must_use]
#[inline]
pub fn erff(x: f32) -> f32 {
    if x.is_nan() {
        return x;
    }

    let ax = x.abs();

    if ax < 0.437_5 {
        return erf_small(x.into()) as f32;
    }

    // erfc(4) < 2^-25, so erf(4) rounds to 1. Monotonicity gives the same
    // result for every larger magnitude, including infinity. Clamping keeps
    // saturation on the table path without a magnitude-dependent branch.
    let ax = ax.min(4.0);
    let (r, eps) = erf_fast(ax.into());
    let lower = (r - eps) as f32;
    if lower == (r + eps) as f32 {
        return lower.copysign(x);
    }

    let e = erfc_dd(ax.into());
    round(
        DoubleDouble {
            high: 1.0,
            low: 0.0,
        } + DoubleDouble {
            high: -e.high,
            low: -e.low,
        },
    )
    .copysign(x)
}

/// The complementary error function `1 - erf(x)`
#[must_use]
#[inline]
pub fn erfcf(x: f32) -> f32 {
    if x.is_nan() {
        return x;
    }

    let ax = x.abs();

    if ax < 0.437_5 {
        // Lone hard-to-round case in this regime (found by exhaustive sweep):
        // erfc(-0x1.d93ec4p-17) sits a hair past an f32 midpoint.
        if x.to_bits() == 0xb76c_9f62 {
            return f32::from_bits(0x3f80_0085);
        }
        return (1.0 - erf_small(x.into())) as f32;
    }

    // erfc underflows to 0 for large x; the reflection 2 - erfc tends to 2
    if ax >= f32::from_bits(0x4120_ddfc) {
        return if x.is_sign_positive() { 0.0 } else { 2.0 };
    }

    let (r, eps) = erfc_fast(x.into());
    let lower = (r - eps) as f32;
    if lower == (r + eps) as f32 {
        return lower;
    }

    let e = erfc_dd(ax.into());

    if x.is_sign_positive() {
        round_general(e)
    } else {
        round_general(
            DoubleDouble {
                high: 2.0,
                low: 0.0,
            } + DoubleDouble {
                high: -e.high,
                low: -e.low,
            },
        )
    }
}

#[cfg(all(test, feature = "mpfr"))]
mod ziv_soundness {
    use super::*;
    use rug::Float;

    fn check(got: (f64, f64), truth: &Float, x: f64, worst: &mut (f64, f64)) {
        let error = (Float::with_val(192, got.0) - truth).abs().to_f64();
        let ratio = error / got.1;
        if ratio > worst.0 {
            *worst = (ratio, x);
        }
    }

    /// Exercise every cell on a dense grid, including both neighbors of every
    /// breakpoint. Certify the actual evaluated/reflected legs and their gates,
    /// with the input rounded to f32 exactly as in the public entry points.
    #[test]
    fn direct_erfc_legs_are_sound() {
        // Monotonicity proves the clamped tail once this endpoint clears the
        // midpoint below 1. The entire fast-leg error interval clears it too.
        assert!(Float::with_val(192, 4.0).erfc() < crate::exp2i(-25));
        let (r, eps) = erf_fast(4.0);
        assert_eq!((r - eps) as f32, 1.0);
        assert_eq!((r + eps) as f32, 1.0);
        let mut worst_erf = (0.0, 0.0);
        let mut worst_positive = (0.0, 0.0);
        let mut worst_negative = (0.0, 0.0);
        for cell in 7..=161 {
            for j in 0..=1024 {
                let center = ((f64::from(cell) + f64::from(j) / 1024.0 - 0.5) / 16.0) as f32;
                for bits in [center.to_bits() - 1, center.to_bits(), center.to_bits() + 1] {
                    let x = f32::from_bits(bits);
                    if !(0.4375..f32::from_bits(0x4120_ddfc)).contains(&x) {
                        continue;
                    }
                    let x = f64::from(x);
                    let truth = Float::with_val(192, x).erfc();
                    check(erfc_fast(x), &truth, x, &mut worst_positive);
                    let reflected = Float::with_val(192, 2.0) - &truth;
                    check(erfc_fast(-x), &reflected, -x, &mut worst_negative);
                    if x <= 4.0 {
                        let truth = Float::with_val(192, 1.0) - &truth;
                        check(erf_fast(x), &truth, x, &mut worst_erf);
                    }
                }
            }
        }
        for (name, (worst, x)) in [
            ("erf", worst_erf),
            ("erfc positive", worst_positive),
            ("erfc negative", worst_negative),
        ] {
            println!("{name} direct table: worst |err|/gate = {worst:.6} at x={x:e}");
            assert!(worst < 0.5, "{name} gate has less than 2x margin at {x:e}");
        }
    }
}


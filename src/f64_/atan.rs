/// Relative half-width of the `atan`/`atan2` fast-path Ziv gate.  Over a dense
/// sweep of the active band the fast kernel's relative error peaks well below
/// 2⁻⁶⁸; the gate at 2⁻⁶³ keeps a comfortable margin and defers the rest to the
/// double-double kernel, which stays the correctly-rounded reference.
const ATAN_ZIV_EPS: f64 = 1.0842021724855044e-19; // 2⁻⁶³

/// The `asin`/`acos` fast-path Ziv gate is *correction-scaled* rather than a
/// fixed relative width: `eps = |z|·(C·|r| + F) + G`, where `z` is the kernel
/// multiplier (the argument, or the reflection's `√t`) and `r` the in-cell
/// offset.  Every error source of [`asin_tail`] is proportional to the
/// correction `z·r` (polynomial evaluation rounding, fit truncation) or to `z`
/// alone (table-lead rounding, the `√t` low word, product cross terms), plus
/// the absolute offset-fold rounding of `acos`'s π/2 and π folds — so the gate
/// tracks the true error profile and defers ~0.5% to the accurate fallback,
/// versus ~2% for the old fixed `2⁻⁵⁹` relative gate.
///
/// Constants calibrated by `tools/gen_inv_f64.py`, which simulates the exact
/// `f64` operation sequence of [`asin_tail`] over dense sweeps of all five
/// branch/offset cases (worst requirement C ≥ 2⁻⁵³·¹, F ≥ 2⁻⁷⁸·⁷, G ≥ 2⁻¹⁰⁵·³;
/// a denser 3.6-million-point sweep peaks at C ≥ 2⁻⁵²·⁹⁶, leaving a 3.9×
/// margin).
const ASIN_EPS_R: f64 = 4.440892098500626e-16; // C = 2⁻⁵¹
/// Per-`z` floor of the `asin`/`acos` gate; see [`ASIN_EPS_R`].
const ASIN_EPS_Z: f64 = 1.3234889800848443e-23; // F = 2⁻⁷⁶
/// Absolute floor of the `asin`/`acos` gate; see [`ASIN_EPS_R`].
const ASIN_EPS_ABS: f64 = 7.888609052210118e-31; // G = 2⁻¹⁰⁰

/// Relative half-width of the *second-tier* Ziv gate on the double-double accurate
/// fallback.  That fallback (`asin_pos`∘`atan_dd`) is ~2⁻⁹⁸ accurate — correctly
/// rounded everywhere except a handful of hard-to-round points (~2⁻¹¹¹ from a
/// midpoint).  This gate at 2⁻⁹⁰ (well above the dd error) passes the
/// double-double result directly for all but those points, which alone escalate
/// to the slow triple-double [`asin_direct_td`] — so the ~770 ns triple-double
/// path runs ~2⁻³⁷ of the time, not on every fast-leg miss.
const ASIN_DD_ZIV_EPS: f64 = 8.077935669463161e-28; // 2⁻⁹⁰

/// Negate a double-double.
#[inline]
fn neg(v: DoubleDouble) -> DoubleDouble {
    DoubleDouble {
        high: -v.high,
        low: -v.low,
    }
}

/// Ziv gate: round `v` to `f64` when both ends of its `±eps_rel·|v|` (relative)
/// error interval agree, else `None` to fall back to the accurate kernel.
#[inline]
fn ziv_at(v: DoubleDouble, eps_rel: f64) -> Option<f64> {
    let eps = v.high.abs() * eps_rel;
    let lo = v.high + (v.low - eps);
    let hi = v.high + (v.low + eps);
    (lo == hi).then_some(lo)
}

/// [`ziv_at`] at the `atan`/`atan2` gate width.
#[inline]
fn ziv(v: DoubleDouble) -> Option<f64> {
    ziv_at(v, ATAN_ZIV_EPS)
}

/// Arctangent of a double-double `q ∈ [0, 1]`, as a double-double.
#[inline]
fn atan_dd(q: DoubleDouble) -> DoubleDouble {
    // For `q < 2⁻⁴⁰`, `atan(q) = q − q³/3 + …` agrees with `q` far below ½ ulp, so
    // the correctly-rounded `q.high` is the answer; dropping the low word also
    // protects against a `from_quotient` residual that underflowed to subnormal.
    if q.high < 9.094947017729282e-13 {
        return DoubleDouble {
            high: q.high,
            low: 0.0,
        };
    }

    let k = (q.high * 8.0).round_ties_even();
    let c = k * 0.125;
    let table = ATAN_TABLE[k as usize];

    // u = (q − c) / (1 + q·c), |u| ≤ 1/16 (c is an exact power-of-two multiple).
    let denom = q * c
        + DoubleDouble {
            high: 1.0,
            low: 0.0,
        };
    let u = (q + DoubleDouble { high: -c, low: 0.0 }) * denom.recip();

    atan_cell(table, u)
}

/// Accurate counterpart of [`atan_cell_fast`]: finish from a reduced cell via the
/// full double-double series `atan(k/8 + …) = table + u·Σ(−1)ᵏu²ᵏ/(2k+1)`.
///
/// `table = atan(k/8)` and `|u| ≤ 1/16`.  Shared by [`atan_dd`] and the fused
/// `atan2` reduction, which differ only in how they form `u`.
#[inline]
fn atan_cell(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    table + u * poly_dd(u * u, &ATAN_COEFFS)
}

/// Finish a reduced cell in double-double: `atan(k/8 + …) = table + u·(1 − u²/3 + …)`.
///
/// `table = atan(k/8)` and `u` is the cell-reduced argument (`|u| ≤ 1/16`).  The
/// `atan2` fast path's only cell finisher (the standalone `atan` fast path lives
/// in [`atan_fast`], a separate CORE-MATH-style fine-table kernel).
#[inline]
fn atan_cell_fast(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    let w = u * u;
    let wh = w.high;
    let w2 = wh * wh;
    // 1 − w/3 in double-double (ATAN_COEFFS[1] = −1/3); tail w²·(1/5 − w/7 + …).
    // Ordered Fast2Sum folds: `|w| ≤ 2⁻⁸` keeps every addend far under its lead,
    // and the final `table ⊕ u·bracket` orders for `k ≥ 1` (`atan(1/8) ≥ 2·…`,
    // see `fold_ordering`) while `k = 0` makes `table` zero, where Fast2Sum is
    // exact regardless.
    let bracket = ONE
        .add_ordered(w * ATAN_COEFFS[1])
        .add_ordered(DoubleDouble {
            high: w2 * crate::poly(wh, &ATAN_TAIL),
            low: 0.0,
        });
    table.add_ordered(u * bracket)
}

/// Shared Ziv-gated fast-path tail of [`asin`] and [`acos`]:
/// `v = off + B(j/128 + r)·(z + zl)`, returning the rounded `f64` when the
/// gate accepts and `None` to defer to the accurate fallback.
///
/// Both functions' branches only *set up* `(off, z, zl, r, j)` — like
/// CORE-MATH's asin, the table lookup, polynomial, product, offset fold, and
/// gate are one straight-line tail, so the magnitude branch stays short and
/// the sign needs no post-hoc `copysign` (it rides in `z` and `off`).
///
/// The lead multiplies `(z, zl)` via one exact product plus fused folds, and
/// the per-cell correction `d = r·P(r)` enters pre-scaled as `P(r)·(r·z)` —
/// the polynomial is the longest dependency chain, so it lands in the *last*
/// fold instead of serializing behind a `lead.low + d` add as before.
///
/// The gate width is the correction-scaled `|z|·(C·|r| + F) + G` — see
/// [`ASIN_EPS_R`] — computed off the critical path from the early-known `z`
/// and `r`.
#[inline]
fn asin_tail(off: DoubleDouble, z: f64, zl: f64, r: f64, j: usize) -> Option<f64> {
    let cell = &ASIN_CELLS[j];
    let p = DoubleDouble::from_product(cell.lead.high, z);
    let low = crate::fma(cell.lead.high, zl, p.low);
    let low = crate::fma(cell.lead.low, z, low);
    let low = crate::fma(crate::poly(r, &cell.poly), r * z, low);
    // |off| ≥ |p| (`fold_ordering::asin_offsets`), or `off = 0` where Fast2Sum
    // is exact unconditionally.
    let v = off.add_ordered(DoubleDouble { high: p.high, low });

    let eps = crate::fast_mul_add(
        crate::fast_mul_add(ASIN_EPS_R, r.abs(), ASIN_EPS_Z),
        z.abs(),
        ASIN_EPS_ABS,
    );
    let lo = v.high + (v.low - eps);
    let hi = v.high + (v.low + eps);
    (lo == hi).then_some(lo)
}

/// A triple-`f64` value `high + mid + low`, used only by the rare accurate
/// fallback to round the few `f64` `asin`/`acos` arguments beyond double-double's
/// ~2⁻¹⁰⁶ reach (the worst, `acos`'s, lands ~2⁻¹¹¹ from a midpoint).  Normalized
/// forms are non-overlapping: `|mid| ≤ ½ulp(high)`, `|low| ≤ ½ulp(mid)`.
#[derive(Clone, Copy)]
struct TripleDouble {
    high: f64,
    mid: f64,
    low: f64,
}

/// 2Sum: the exact `a + b` as `(sum, error)`.
#[inline]
fn two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let bb = s - a;
    (s, (a - (s - bb)) + (b - bb))
}

/// Renormalize the exact sum `a + b + c` into a non-overlapping triple-double.
#[inline]
fn renorm3(a: f64, b: f64, c: f64) -> TripleDouble {
    let (s, t1) = two_sum(b, c);
    let (high, t2) = two_sum(a, s);
    let (mid, low) = two_sum(t2, t1);
    TripleDouble { high, mid, low }
}

/// Add an `f64` into a triple-double, dropping only the 4th-order residual
/// (~2⁻²¹²·|t|).
#[inline]
fn td_add_f64(t: TripleDouble, x: f64) -> TripleDouble {
    let (s0, e0) = two_sum(t.high, x);
    let (s1, e1) = two_sum(t.mid, e0);
    renorm3(s0, s1, t.low + e1)
}

/// Add two triple-doubles (fold the addend's limbs in, high-first).
#[inline]
fn td_add(a: TripleDouble, b: TripleDouble) -> TripleDouble {
    td_add_f64(td_add_f64(td_add_f64(a, b.high), b.mid), b.low)
}

/// Negate a triple-double.
#[inline]
fn td_neg(t: TripleDouble) -> TripleDouble {
    TripleDouble {
        high: -t.high,
        mid: -t.mid,
        low: -t.low,
    }
}

/// Multiply a triple-double by an exact `f64`.
#[inline]
fn td_mul_f64(t: TripleDouble, x: f64) -> TripleDouble {
    let p0 = DoubleDouble::from_product(x, t.high);
    let p1 = DoubleDouble::from_product(x, t.mid);
    let mut acc = TripleDouble {
        high: p0.high,
        mid: 0.0,
        low: 0.0,
    };
    for term in [p1.high, p0.low, p1.low, x * t.low] {
        acc = td_add_f64(acc, term);
    }
    acc
}

/// Multiply a double-double by a triple-double.
#[inline]
fn dd_mul_td(d: DoubleDouble, t: TripleDouble) -> TripleDouble {
    let q0 = DoubleDouble::from_product(d.high, t.high);
    let q1 = DoubleDouble::from_product(d.high, t.mid);
    let q2 = DoubleDouble::from_product(d.low, t.high);
    let mut acc = TripleDouble {
        high: q0.high,
        mid: 0.0,
        low: 0.0,
    };
    for term in [
        q1.high,
        q2.high,
        q0.low,
        q1.low,
        q2.low,
        d.high * t.low,
        d.low * t.mid,
    ] {
        acc = td_add_f64(acc, term);
    }
    acc
}

/// Round a normalized triple-double to the nearest `f64`.  Round-to-odd of the
/// low pair `mid + low` (so its dropped tail survives as a sticky bit) followed
/// by one `high + ·` add yields the correctly-rounded result with no
/// double-rounding.
#[inline]
fn td_round(t: TripleDouble) -> f64 {
    let (s, e) = two_sum(t.mid, t.low);
    let s = if e != 0.0 && s.to_bits() & 1 == 0 {
        let bits = s.to_bits();
        f64::from_bits(if (s >= 0.0) == (e > 0.0) {
            bits + 1
        } else {
            bits - 1
        })
    } else {
        s
    };
    t.high + s
}

/// `B(u) = asin(√u)/√u = Σ aₖ uᵏ` as a triple-double, for `u ∈ [0, ¼]`.  The
/// slowly-decaying tail `a₉..a₆₀` runs double-double Horner, then `a₈..a₁`
/// (carried to a third limb in [`ASIN_ACC`]/[`ASIN_ACC_LO`]) finish in
/// triple-double — reaching ~2⁻¹³⁰, enough to round the hard `asin`/`acos`
/// points the double-double path misses (the worst ~2⁻¹¹¹ from a midpoint).
/// Shared by the direct leg [`asin_direct_td`] (`u = a²`) and `acos`'s
/// reflection leg ([`acos_accurate`], `u = (1−|x|)/2` exact).
fn asin_b_td(u: DoubleDouble) -> TripleDouble {
    let mut p = ASIN_ACC[59];
    let mut idx = 59;
    while idx > 8 {
        idx -= 1;
        p = p * u + ASIN_ACC[idx];
    }

    let mut t = TripleDouble {
        high: p.high,
        mid: p.low,
        low: 0.0,
    };
    for i in (0..8).rev() {
        t = dd_mul_td(u, t);
        t = td_add(
            t,
            TripleDouble {
                high: ASIN_ACC[i].high,
                mid: ASIN_ACC[i].low,
                low: ASIN_ACC_LO[i],
            },
        );
    }

    // B = 1 + u·t.
    td_add_f64(dd_mul_td(u, t), 1.0)
}

/// `asin(a)` for `a ∈ [0, ½]` as a triple-double, via the direct series
/// `asin(a) = a·B(a²)`.  The accurate fallback's direct leg.
fn asin_direct_td(a: f64) -> TripleDouble {
    td_mul_f64(asin_b_td(DoubleDouble::from_product(a, a)), a)
}

/// `√u` as a triple-double, for an exact non-negative `f64` `u`.
///
/// One Newton step `s + (u − s²)/(2s)` from the double-double seed `sqrt_dd(u)`
/// lifts ~2⁻¹⁰⁵ to ~2⁻¹⁵⁰: `s²` is assembled in triple-double (`high²` exact,
/// the `2·hi·lo` cross term, and `lo²`), the residual `u − s²` is tiny, and the
/// correction `÷2s` only needs the seed's high word.
fn sqrt_td(u: f64) -> TripleDouble {
    let s = sqrt_dd(DoubleDouble { high: u, low: 0.0 });

    // s² = high² + 2·high·lo + lo², in triple-double.
    let hh = DoubleDouble::from_product(s.high, s.high);
    let hl = DoubleDouble::from_product(s.high, s.low); // exact high·lo
    let mut sq = renorm3(hh.high, hh.low, 2.0 * hl.high);
    for term in [2.0 * hl.low, s.low * s.low] {
        sq = td_add_f64(sq, term);
    }

    // s ← s + (u − s²)/(2s).
    let residual = td_add_f64(td_neg(sq), u);
    let correction = td_mul_f64(residual, 0.5 / s.high);
    td_add(
        TripleDouble {
            high: s.high,
            mid: s.low,
            low: 0.0,
        },
        correction,
    )
}

/// `asin(|x|)` for `a = |x| ∈ [0, 1]`, as a double-double in `[0, π/2]`.
///
/// `asin(a) = atan(a/√(1−a²))`; the branch keeps the `atan` argument in `[0, 1]`.
#[inline]
fn asin_pos<K: Fn(DoubleDouble) -> DoubleDouble>(a: f64, kernel: K) -> DoubleDouble {
    if a == 1.0 {
        return FRAC_PI_2;
    }

    // c = √(1 − a²) as a double-double (a² exact, so the cancellation near a = 1
    // is captured).
    let c = sqrt_dd(ONE + neg(DoubleDouble::from_product(a, a)));

    if a <= c.high {
        kernel(DoubleDouble { high: a, low: 0.0 } * c.recip())
    } else {
        // a/c > 1 ⇒ atan(a/c) = π/2 − atan(c/a)
        FRAC_PI_2 + neg(kernel(c / a))
    }
}


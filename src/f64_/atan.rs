/// Horner evaluation of a `Dint` Taylor polynomial in `u`, low-degree first
/// (mirrors `trig::poly_dint`).
#[inline]
fn poly_dint(u: &Dint, coeffs: &[Dint]) -> Dint {
    let mut acc = coeffs[coeffs.len() - 1];
    for c in coeffs[..coeffs.len() - 1].iter().rev() {
        acc = c.add(&u.mul(&acc));
    }
    acc
}

/// `1 / c` as a `Dint`, two Newton steps `y·(2 − c·y)` from the `f64` seed `1/c`
/// (mirrors `trig::recip_dint`).  The cell denominator `1 + q·c ∈ [1, 1.13]` and
/// the `atan2` denominator `big + c·small ≥ big` are both well away from zero, so
/// two steps reach the `Dint` arithmetic floor.
#[inline]
fn recip_dint(c: &Dint) -> Dint {
    let mut y = Dint::from_f64(1.0 / c.to_f64());
    for _ in 0..2 {
        y = y.mul(&TWO_DINT.add(&neg_dint(c.mul(&y))));
    }
    y
}

/// Finish from a reduced cell in `Dint`: `atan(k/8 + …) = table + u·Σ(−1)ᵏu²ᵏ/(2k+1)`.
///
/// The `Dint` counterpart of [`atan_cell`]: `table = atan(k/8)` and `|u| ≤ 1/16`.
#[inline]
fn atan_cell_dint(table: &Dint, u: &Dint) -> Dint {
    table.add(&u.mul(&poly_dint(&u.mul(u), &ATAN_COEFFS_DINT)))
}

/// `atan(q)` for a `Dint` `q ∈ [0, 1]` via the cell reduction
/// `u = (q − c)/(1 + q·c)`, `c = k/8`, `k = round(8q)` — the `Dint` counterpart
/// of [`atan_dd`]'s reduction.  Used by both the `atan` reflection (where `q` is
/// a `Dint` reciprocal `1/a`) and the direct branch (`q = a` exact).
#[inline]
fn atan_reduce_dint(q: &Dint) -> Dint {
    let qf = q.to_f64();
    // k = round(8q); q ∈ [0, 1] puts k in 0..=8.
    let k = (qf * 8.0).round_ties_even();
    let kc = k as i64;
    let c = k * 0.125; // exact (power-of-two multiple of 1/8)
    let cd = Dint::from_f64(c);

    // u = (q − c) / (1 + q·c); c = 0 (k = 0) makes the numerator q and the
    // denominator 1, so `u = q` — handled uniformly by the general formula.
    let num = q.add(&neg_dint(cd));
    let den = ONE_DINT.add(&q.mul(&cd));
    let u = num.mul(&recip_dint(&den));

    atan_cell_dint(&ATAN_TABLE_DINT[kc as usize], &u)
}

/// `1` as a `Dint`, for the cell denominator `1 + q·c`.
const ONE_DINT: Dint = Dint {
    sgn: false,
    ex: 0,
    m: 0x80000000000000000000000000000000,
};

/// Magnitude of `atan(|x|)` in `[0, π/2]` as a `Dint` — the accurate fallback,
/// mirroring the (now-`Dint`) reflection the double-double path used.  For
/// `a > 1` reflect `π/2 − atan(1/a)` with `1/a` formed to `Dint` precision
/// (`recip_dint`); otherwise reduce `a` directly.
#[inline]
fn atan_dint_mag(a: f64) -> Dint {
    if a > 1.0 {
        let recip = recip_dint(&Dint::from_f64(a));
        PIO2_DINT.add(&neg_dint(atan_reduce_dint(&recip)))
    } else {
        atan_reduce_dint(&Dint::from_f64(a))
    }
}


/// `atan2`'s magnitude in `[0, π]` for finite nonzero `a = |x|`, `b = |y|`, as a
/// correctly-rounded `f64`.  The 192-bit accurate fallback, mirroring CORE-MATH's
/// `atan2_accurate` for the non-degenerate finite case (the NaN/∞/zero/axis and
/// underflow special cases are already handled upstream by [`atan2`]/[`atan2_mag`]
/// before the Ziv gate escalates here).
#[cold]
#[inline(never)]
fn atan2_tint_mag(a: f64, b: f64, x_negative: bool) -> f64 {
    // inv = |y| > |x| (CORE-MATH's `inv`), i.e. metallic's `swapped`.  In either
    // case z = small/big ∈ [0, 1].
    let inv = b > a;
    let (num, den) = if inv { (a, b) } else { (b, a) };
    let mut z = Tint::div_d(num, den);

    // Tiny ratio with the larger leg as x (inv = 0): atan(z) rounds to z perturbed
    // a hair toward zero — match CORE-MATH's `z->l -= 2; … tint_tod(z, 1)`.
    if !inv && z.ex <= -96 {
        let (lo, borrow) = z.lo.overflowing_sub(2);
        z.lo = lo;
        z.hi = z.hi.wrapping_sub(u128::from(borrow));
        return z.to_f64(1);
    }

    // z·P(z)/Q(z), the [29, 29] rational approximation of atan on [0, 1].
    let mut p = P_TINT[29];
    let mut q = Q_TINT[29];
    for i in (0..29).rev() {
        p = p.mul(&z);
        q = q.mul(&z);
        p = p.add(&P_TINT[i]);
        q = q.add(&Q_TINT[i]);
    }
    p = p.mul(&z); // p ← z·P(z)
    let mut z = Tint::div(&p, &q); // z ← atan(small/big) ∈ [0, π/4]

    // φ = atan(small/big), or π/2 − atan(small/big) when swapped (`inv`); then
    // x < 0 ⇒ opposite quadrant θ = π − φ.  Since a, b ≥ 0, z ≥ 0, the magnitude
    // stays non-negative throughout.  `err` is the ulp bound CORE-MATH attaches to
    // the *last* applied fold (z·P/Q: 662, +π/2: 524, +π: 266).
    if inv {
        z = PI2_TINT.add(&z.neg());
    }
    if x_negative {
        z = PI_TINT.add(&z.neg());
    }
    let err = if x_negative {
        266
    } else if inv {
        524
    } else {
        662
    };

    z.to_f64(err)
}

/// The Fast2Sum-based folds of [`atan_cell_fast`] need `|a| ≥ |b|`; prove the
/// orderings from coefficient-magnitude bounds at the cell edge `|u| ≤ 1/16`
/// (cf. the same-named modules in `erf.rs` and `trig.rs`).
#[cfg(test)]
mod fold_ordering {
    use super::*;

    #[test]
    fn atan_cell() {
        // Slack for the rounding of u (one lean division) and w = u·u.
        let umax = 0.0625 * 1.0001;
        let wmax = umax * umax;
        let tail_mag = ATAN_TAIL
            .iter()
            .rev()
            .fold(0.0, |acc, c| crate::fast_mul_add(acc, wmax, c.abs()));

        // bracket = 1 ⊕ w·(−1/3) ⊕ w²·tail
        let c1_mag = ATAN_COEFFS[1].high.abs() + ATAN_COEFFS[1].low.abs();
        assert!(wmax * c1_mag <= 0.5);
        let lead_min = 1.0 - wmax * c1_mag;
        assert!(wmax * wmax * tail_mag <= 0.5 * lead_min);

        // table ⊕ u·bracket for k ≥ 1 (k = 0 has table = 0, where Fast2Sum is
        // exact by itself); the k = 1 cell is the tightest at 0.504.
        let bracket_mag = crate::fast_mul_add(wmax * wmax, tail_mag, 1.0 + wmax * c1_mag);
        for cell in &ATAN_TABLE[1..] {
            assert!(umax * bracket_mag <= 0.55 * cell.high.abs());
        }
    }

    /// [`asin_tail`]'s `off ⊕ p` fold: `|off| ≥ |p.high|` for every nonzero
    /// offset (`off = 0`, asin's direct branch, is exact unconditionally).
    /// `|p.high| ≤ Bmax·|z|·(1 + ε)` with `Bmax = B(¼)` the largest table lead;
    /// `|z| ≤ 1` in the reflections (`√t ≤ 1`) and `|z| ≤ ½` in acos's direct
    /// branch.
    #[test]
    fn asin_offsets() {
        let bmax = ASIN_CELLS
            .iter()
            .map(|cell| cell.lead.high)
            .fold(0.0, f64::max)
            * 1.0001;

        // Reflections: off = ±π/2 (asin) or π (acos, x < −½) vs |p| ≤ Bmax.
        assert!(bmax <= 0.7 * FRAC_PI_2.high);
        assert!(bmax <= 0.35 * PI.high);
        // acos direct: off = π/2 vs |p| ≤ Bmax/2.
        assert!(0.5 * bmax <= 0.35 * FRAC_PI_2.high);
    }
}

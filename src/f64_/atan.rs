/// One cache line of the table-driven `asin`/`acos` fast path: `B(u_j)` as a
/// double-double lead plus six per-cell correction coefficients — exactly 64
/// bytes, so a lookup touches a single line (the former split
/// `ASIN_LEAD`/`ASIN_POLY` arrays spread one lookup over two arrays and up to
/// three lines).
///
/// `B(u_j) = asin(t)/t` at the grid points `u_j = t² = j/128` (`j = 0..=32`,
/// covering `u ∈ [0, ¼]`); `poly` is a Chebyshev interpolant of
/// `(B(u_j + r) − B(u_j))/r` over the cell `|r| ≤ 2⁻⁸` (half-cells at the
/// edges `j = 0` and `j = 32`), low-degree first.  Near-minimax fitting pushes
/// the cell-edge truncation (the dominant term of a Taylor expansion, ~2⁻⁵²
/// per unit `r` at degree 5) below the `f64` evaluation rounding (sup error
/// ~2⁻⁵⁵ per unit `r`), which is what lets the Ziv gate scale purely with the
/// correction term — see [`ASIN_EPS_R`].  Generated by `tools/gen_inv_f64.py`.
#[repr(C, align(64))]
struct AsinCell {
    /// `B(u_j)` to ~2⁻¹⁰⁶.
    lead: DoubleDouble,
    /// Per-cell Chebyshev correction `P(r) ≈ (B(u_j + r) − B(u_j))/r`.
    poly: [f64; 6],
}


//! Inverse trigonometric functions: `asin`, `acos`, `atan`, `atan2`.
//!
//! `atan`/`atan2` use one double-double `atan` kernel: `atan_dd` reduces
//! `q ∈ [0, 1]` into a width-1/8 cell (`ATAN_TABLE` holds `atan(k/8)`) and
//! evaluates the odd series on `|u| ≤ 1/16`.  `asin`/`acos` share the
//! table-driven [`asin_tail`] fast path, which tabulates `asin(t)/t` on a grid
//! `u = t² = j/128` plus a per-cell `f64` correction in `r = u − j/128`, one
//! cache line per cell ([`ASIN_CELLS`]); the reflection `s = √((1−|x|)/2)` for
//! `|x| ≥ ½` keeps `u ≤ ¼`, and there `u` is exact so only the multiplier
//! `√t = 2s` carries a low word (no double-double `sqrt`).  Both fall back, via
//! a correction-scaled Ziv gate ([`ASIN_EPS_R`]), to the accurate
//! `asin(x) = atan(x/√(1−x²))` (`asin_pos`).
//!
//! Constants below were generated by `tools/gen_atan_f64.py` and
//! `tools/gen_inv_f64.py`.

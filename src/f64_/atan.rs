/// π/2 as a double-double.
const FRAC_PI_2: DoubleDouble = DoubleDouble {
    high: 1.5707963267948966,
    low: 6.123233995736766e-17,
};

/// π as a double-double.
const PI: DoubleDouble = DoubleDouble {
    high: 3.141592653589793,
    low: 1.2246467991473532e-16,
};

/// One as a double-double.
const ONE: DoubleDouble = DoubleDouble {
    high: 1.0,
    low: 0.0,
};

/// Zero as a double-double.
const ZERO: DoubleDouble = DoubleDouble {
    high: 0.0,
    low: 0.0,
};

/// Relative half-width of the `atan`/`atan2` fast-path Ziv gate.  Over a dense
/// sweep of the active band the fast kernel's relative error peaks well below
/// 2⁻⁶⁸; the gate at 2⁻⁶³ keeps a comfortable margin and defers the rest to the
/// double-double kernel, which stays the correctly-rounded reference.
const ATAN_ZIV_EPS: f64 = 1.0842021724855044e-19; // 2⁻⁶³

/// The `asin`/`acos` fast-path Ziv gate is *correction-scaled* rather than a
/// fixed relative width: `eps = |z|·(C·|r| + F) + G`, where `z` is the kernel
/// multiplier (the argument, or the reflection's `√t`) and `r` the in-cell
/// offset.  Every error source of [`asin_tail`] is proportional to the
/// correction `z·r` (polynomial evaluation rounding, fit truncation) or to `z`
/// alone (table-lead rounding, the `√t` low word, product cross terms), plus
/// the absolute offset-fold rounding of `acos`'s π/2 and π folds — so the gate
/// tracks the true error profile and defers ~0.5% to the accurate fallback,
/// versus ~2% for the old fixed `2⁻⁵⁹` relative gate.
///
/// Constants calibrated by `tools/gen_inv_f64.py`, which simulates the exact
/// `f64` operation sequence of [`asin_tail`] over dense sweeps of all five
/// branch/offset cases (worst requirement C ≥ 2⁻⁵³·¹, F ≥ 2⁻⁷⁸·⁷, G ≥ 2⁻¹⁰⁵·³;
/// a denser 3.6-million-point sweep peaks at C ≥ 2⁻⁵²·⁹⁶, leaving a 3.9×
/// margin).
const ASIN_EPS_R: f64 = 4.440892098500626e-16; // C = 2⁻⁵¹
/// Per-`z` floor of the `asin`/`acos` gate; see [`ASIN_EPS_R`].
const ASIN_EPS_Z: f64 = 1.3234889800848443e-23; // F = 2⁻⁷⁶
/// Absolute floor of the `asin`/`acos` gate; see [`ASIN_EPS_R`].
const ASIN_EPS_ABS: f64 = 7.888609052210118e-31; // G = 2⁻¹⁰⁰

/// Relative half-width of the *second-tier* Ziv gate on the double-double accurate
/// fallback.  That fallback (`asin_pos`∘`atan_dd`) is ~2⁻⁹⁸ accurate — correctly
/// rounded everywhere except a handful of hard-to-round points (~2⁻¹¹¹ from a
/// midpoint).  This gate at 2⁻⁹⁰ (well above the dd error) passes the
/// double-double result directly for all but those points, which alone escalate
/// to the slow triple-double [`asin_direct_td`] — so the ~770 ns triple-double
/// path runs ~2⁻³⁷ of the time, not on every fast-leg miss.
const ASIN_DD_ZIV_EPS: f64 = 8.077935669463161e-28; // 2⁻⁹⁰

/// Negate a double-double.
#[inline]
fn neg(v: DoubleDouble) -> DoubleDouble {
    DoubleDouble {
        high: -v.high,
        low: -v.low,
    }
}

/// Ziv gate: round `v` to `f64` when both ends of its `±eps_rel·|v|` (relative)
/// error interval agree, else `None` to fall back to the accurate kernel.
#[inline]
fn ziv_at(v: DoubleDouble, eps_rel: f64) -> Option<f64> {
    let eps = v.high.abs() * eps_rel;
    let lo = v.high + (v.low - eps);
    let hi = v.high + (v.low + eps);
    (lo == hi).then_some(lo)
}

/// [`ziv_at`] at the `atan`/`atan2` gate width.
#[inline]
fn ziv(v: DoubleDouble) -> Option<f64> {
    ziv_at(v, ATAN_ZIV_EPS)
}

/// Arctangent of a double-double `q ∈ [0, 1]`, as a double-double.
#[inline]
fn atan_dd(q: DoubleDouble) -> DoubleDouble {
    // For `q < 2⁻⁴⁰`, `atan(q) = q − q³/3 + …` agrees with `q` far below ½ ulp, so
    // the correctly-rounded `q.high` is the answer; dropping the low word also
    // protects against a `from_quotient` residual that underflowed to subnormal.
    if q.high < 9.094947017729282e-13 {
        return DoubleDouble {
            high: q.high,
            low: 0.0,
        };
    }

    let k = (q.high * 8.0).round_ties_even();
    let c = k * 0.125;
    let table = ATAN_TABLE[k as usize];

    // u = (q − c) / (1 + q·c), |u| ≤ 1/16 (c is an exact power-of-two multiple).
    let denom = q * c
        + DoubleDouble {
            high: 1.0,
            low: 0.0,
        };
    let u = (q + DoubleDouble { high: -c, low: 0.0 }) * denom.recip();

    atan_cell(table, u)
}

/// Accurate counterpart of [`atan_cell_fast`]: finish from a reduced cell via the
/// full double-double series `atan(k/8 + …) = table + u·Σ(−1)ᵏu²ᵏ/(2k+1)`.
///
/// `table = atan(k/8)` and `|u| ≤ 1/16`.  Shared by [`atan_dd`] and the fused
/// `atan2` reduction, which differ only in how they form `u`.
#[inline]
fn atan_cell(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    table + u * poly_dd(u * u, &ATAN_COEFFS)
}

/// Lean counterpart of [`atan_dd`], the inverse-trig functions' fast path.
///
/// The cell reduction is identical, but `atan(u)/u = 1 − w/3 + w²·(…)` peels the
/// two leading terms into double-double (`w = u²`, `1/3` carried as a
/// double-double coefficient) and evaluates only the tiny tail ([`ATAN_TAIL`])
/// in plain `f64`, replacing the 16-term double-double Horner.  A [`ziv`] gate on
/// the reconstructed result accepts it or defers to [`atan_dd`].
#[inline]
fn atan_dd_fast(q: DoubleDouble) -> DoubleDouble {
    if q.high < 9.094947017729282e-13 {
        return DoubleDouble {
            high: q.high,
            low: 0.0,
        };
    }

    let k = (q.high * 8.0).round_ties_even();
    let c = k * 0.125;
    // SAFETY: q ∈ [0, 1] puts k in 0..=8; a plain `as` cast would pay a
    // saturation cmov chain right in front of the table load.
    let table = ATAN_TABLE[unsafe { k.to_int_unchecked::<i64>() } as usize];

    // `q.high − c` is Sterbenz-exact: `k = round(8·q.high)` puts `q.high` in
    // `[c − 1/16, c + 1/16] ⊂ [c/2, 2c]` (for `k ≥ 1`; ties-even keeps
    // `q.high > 1/16` whenever `k ≥ 1`, and `k = 0` means `c = 0`).  `1 ≥ q·c`
    // orders the denominator fold, and the lean quotient replaces
    // `denom.recip()`'s Newton step plus a double-double multiply.
    let num = DoubleDouble {
        high: q.high - c,
        low: q.low,
    };
    let u = num.div_fast(ONE.add_ordered(q * c));

    atan_cell_fast(table, u)
}

/// Finish the fast path from a reduced cell: `atan(k/8 + …) = table + u·(1 − u²/3 + …)`.
///
/// `table = atan(k/8)` and `u` is the cell-reduced argument (`|u| ≤ 1/16`).  Shared
/// by [`atan_dd_fast`] and [`atan_recip_fast`], which differ only in how they form `u`.
#[inline]
fn atan_cell_fast(table: DoubleDouble, u: DoubleDouble) -> DoubleDouble {
    let w = u * u;
    let wh = w.high;
    let w2 = wh * wh;
    // 1 − w/3 in double-double (ATAN_COEFFS[1] = −1/3); tail w²·(1/5 − w/7 + …).
    // Ordered Fast2Sum folds: `|w| ≤ 2⁻⁸` keeps every addend far under its lead,
    // and the final `table ⊕ u·bracket` orders for `k ≥ 1` (`atan(1/8) ≥ 2·…`,
    // see `fold_ordering`) while `k = 0` makes `table` zero, where Fast2Sum is
    // exact regardless.
    let bracket = ONE
        .add_ordered(w * ATAN_COEFFS[1])
        .add_ordered(DoubleDouble {
            high: w2 * crate::poly(wh, &ATAN_TAIL),
            low: 0.0,
        });
    table.add_ordered(u * bracket)
}

/// `atan(1/a)` for `a > 1`, the fast path's reflection leg, without ever forming
/// `1/a` as a double-double.
///
/// With `v = 1/a`, the cell reduction `u = (v − c)/(1 + v·c)` becomes
/// `u = (1 − a·c)/(a + c)` after multiplying through by `a`.  So the leg spends one
/// `1/a` (a plain `f64`, only to pick the cell `k = round(8/a)`) plus the cell's own
/// `recip` — **two** divisions, versus the **three** of `atan_dd_fast(ONE / a)`, whose
/// `DoubleDouble / f64` reciprocal alone costs two.  `1 − a·c` is exact (`a·c ≈ 1`
/// inside the cell and `from_product` is exact), so `u` is at least as accurate as
/// the original, and `|u| ≤ 1/16` exactly as in [`atan_dd_fast`].
#[inline]
fn atan_recip_fast(a: f64) -> DoubleDouble {
    let inv = 1.0 / a;

    // a > 1.1e12: atan(1/a) = 1/a to far below ½ ulp (matches `atan_dd_fast`'s guard,
    // since `(ONE / a).high == 1.0 / a`).
    if inv < 9.094947017729282e-13 {
        return DoubleDouble {
            high: inv,
            low: 0.0,
        };
    }

    let k = (inv * 8.0).round_ties_even();
    let c = k * 0.125;
    // SAFETY: inv ∈ (0, 1] puts k in 0..=8 (see `atan_dd_fast`).
    let table = ATAN_TABLE[unsafe { k.to_int_unchecked::<i64>() } as usize];

    // u = (1 − a·c)/(a + c).  `a·c ∈ (2/3, 2 + ε)` inside a cell (`k ≥ 1`; `k = 0`
    // makes the product zero), so `1 − p.high` is exact (`x − 1` is exact for any
    // `x ∈ [0.5, 4]`) — no double-double `Add` needed — and the lean quotient
    // replaces `den.recip()`'s Newton step plus a double-double multiply.
    let p = DoubleDouble::from_product(a, c);
    let num = DoubleDouble {
        high: 1.0 - p.high,
        low: -p.low,
    };
    let den = DoubleDouble::from_sum(a, c);
    let u = num.div_fast(den);

    atan_cell_fast(table, u)
}

/// Shared Ziv-gated fast-path tail of [`asin`] and [`acos`]:
/// `v = off + B(j/128 + r)·(z + zl)`, returning the rounded `f64` when the
/// gate accepts and `None` to defer to the accurate fallback.
///
/// Both functions' branches only *set up* `(off, z, zl, r, j)` — like
/// CORE-MATH's asin, the table lookup, polynomial, product, offset fold, and
/// gate are one straight-line tail, so the magnitude branch stays short and
/// the sign needs no post-hoc `copysign` (it rides in `z` and `off`).
///
/// The lead multiplies `(z, zl)` via one exact product plus fused folds, and
/// the per-cell correction `d = r·P(r)` enters pre-scaled as `P(r)·(r·z)` —
/// the polynomial is the longest dependency chain, so it lands in the *last*
/// fold instead of serializing behind a `lead.low + d` add as before.
///
/// The gate width is the correction-scaled `|z|·(C·|r| + F) + G` — see
/// [`ASIN_EPS_R`] — computed off the critical path from the early-known `z`
/// and `r`.
#[inline]
fn asin_tail(off: DoubleDouble, z: f64, zl: f64, r: f64, j: usize) -> Option<f64> {
    let cell = &ASIN_CELLS[j];
    let p = DoubleDouble::from_product(cell.lead.high, z);
    let low = crate::fma(cell.lead.high, zl, p.low);
    let low = crate::fma(cell.lead.low, z, low);
    let low = crate::fma(crate::poly(r, &cell.poly), r * z, low);
    // |off| ≥ |p| (`fold_ordering::asin_offsets`), or `off = 0` where Fast2Sum
    // is exact unconditionally.
    let v = off.add_ordered(DoubleDouble { high: p.high, low });

    let eps = crate::fast_mul_add(
        crate::fast_mul_add(ASIN_EPS_R, r.abs(), ASIN_EPS_Z),
        z.abs(),
        ASIN_EPS_ABS,
    );
    let lo = v.high + (v.low - eps);
    let hi = v.high + (v.low + eps);
    (lo == hi).then_some(lo)
}

/// A triple-`f64` value `high + mid + low`, used only by the rare accurate
/// fallback to round the few `f64` `asin`/`acos` arguments beyond double-double's
/// ~2⁻¹⁰⁶ reach (the worst, `acos`'s, lands ~2⁻¹¹¹ from a midpoint).  Normalized
/// forms are non-overlapping: `|mid| ≤ ½ulp(high)`, `|low| ≤ ½ulp(mid)`.
#[derive(Clone, Copy)]
struct TripleDouble {
    high: f64,
    mid: f64,
    low: f64,
}

/// 2Sum: the exact `a + b` as `(sum, error)`.
#[inline]
fn two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let bb = s - a;
    (s, (a - (s - bb)) + (b - bb))
}

/// Renormalize the exact sum `a + b + c` into a non-overlapping triple-double.
#[inline]
fn renorm3(a: f64, b: f64, c: f64) -> TripleDouble {
    let (s, t1) = two_sum(b, c);
    let (high, t2) = two_sum(a, s);
    let (mid, low) = two_sum(t2, t1);
    TripleDouble { high, mid, low }
}

/// Add an `f64` into a triple-double, dropping only the 4th-order residual
/// (~2⁻²¹²·|t|).
#[inline]
fn td_add_f64(t: TripleDouble, x: f64) -> TripleDouble {
    let (s0, e0) = two_sum(t.high, x);
    let (s1, e1) = two_sum(t.mid, e0);
    renorm3(s0, s1, t.low + e1)
}

/// Add two triple-doubles (fold the addend's limbs in, high-first).
#[inline]
fn td_add(a: TripleDouble, b: TripleDouble) -> TripleDouble {
    td_add_f64(td_add_f64(td_add_f64(a, b.high), b.mid), b.low)
}

/// Negate a triple-double.
#[inline]
fn td_neg(t: TripleDouble) -> TripleDouble {
    TripleDouble {
        high: -t.high,
        mid: -t.mid,
        low: -t.low,
    }
}

/// Multiply a triple-double by an exact `f64`.
#[inline]
fn td_mul_f64(t: TripleDouble, x: f64) -> TripleDouble {
    let p0 = DoubleDouble::from_product(x, t.high);
    let p1 = DoubleDouble::from_product(x, t.mid);
    let mut acc = TripleDouble {
        high: p0.high,
        mid: 0.0,
        low: 0.0,
    };
    for term in [p1.high, p0.low, p1.low, x * t.low] {
        acc = td_add_f64(acc, term);
    }
    acc
}

/// Multiply a double-double by a triple-double.
#[inline]
fn dd_mul_td(d: DoubleDouble, t: TripleDouble) -> TripleDouble {
    let q0 = DoubleDouble::from_product(d.high, t.high);
    let q1 = DoubleDouble::from_product(d.high, t.mid);
    let q2 = DoubleDouble::from_product(d.low, t.high);
    let mut acc = TripleDouble {
        high: q0.high,
        mid: 0.0,
        low: 0.0,
    };
    for term in [
        q1.high,
        q2.high,
        q0.low,
        q1.low,
        q2.low,
        d.high * t.low,
        d.low * t.mid,
    ] {
        acc = td_add_f64(acc, term);
    }
    acc
}

/// Round a normalized triple-double to the nearest `f64`.  Round-to-odd of the
/// low pair `mid + low` (so its dropped tail survives as a sticky bit) followed
/// by one `high + ·` add yields the correctly-rounded result with no
/// double-rounding.
#[inline]
fn td_round(t: TripleDouble) -> f64 {
    let (s, e) = two_sum(t.mid, t.low);
    let s = if e != 0.0 && s.to_bits() & 1 == 0 {
        let bits = s.to_bits();
        f64::from_bits(if (s >= 0.0) == (e > 0.0) {
            bits + 1
        } else {
            bits - 1
        })
    } else {
        s
    };
    t.high + s
}

/// `asin(a)` for `a ∈ [0, ½)` as a triple-double, via the direct series
/// `asin(a) = a·B(a²)`, `B(u) = Σ aₖ uᵏ`.  The accurate fallback's direct leg:
/// the slowly-decaying tail `a₉..a₆₀` runs double-double Horner, then `a₈..a₁`
/// (carried to a third limb in [`ASIN_ACC`]/[`ASIN_ACC_LO`]) finish in
/// triple-double — reaching ~2⁻¹³⁰, enough to round the hard `acos` points the
/// double-double path misses (the worst ~2⁻¹¹¹ from a midpoint).
fn asin_direct_td(a: f64) -> TripleDouble {
    let u = DoubleDouble::from_product(a, a); // exact a²

    let mut p = ASIN_ACC[59];
    let mut idx = 59;
    while idx > 8 {
        idx -= 1;
        p = p * u + ASIN_ACC[idx];
    }

    let mut t = TripleDouble {
        high: p.high,
        mid: p.low,
        low: 0.0,
    };
    for i in (0..8).rev() {
        t = dd_mul_td(u, t);
        t = td_add(
            t,
            TripleDouble {
                high: ASIN_ACC[i].high,
                mid: ASIN_ACC[i].low,
                low: ASIN_ACC_LO[i],
            },
        );
    }

    // B = 1 + u·t,  asin(a) = a·B.
    let b = td_add_f64(dd_mul_td(u, t), 1.0);
    td_mul_f64(b, a)
}

/// `asin(|x|)` for `a = |x| ∈ [0, 1]`, as a double-double in `[0, π/2]`.
///
/// `asin(a) = atan(a/√(1−a²))`; the branch keeps the `atan` argument in `[0, 1]`.
#[inline]
fn asin_pos<K: Fn(DoubleDouble) -> DoubleDouble>(a: f64, kernel: K) -> DoubleDouble {
    if a == 1.0 {
        return FRAC_PI_2;
    }

    // c = √(1 − a²) as a double-double (a² exact, so the cancellation near a = 1
    // is captured).
    let c = sqrt_dd(ONE + neg(DoubleDouble::from_product(a, a)));

    if a <= c.high {
        kernel(DoubleDouble { high: a, low: 0.0 } * c.recip())
    } else {
        // a/c > 1 ⇒ atan(a/c) = π/2 − atan(c/a)
        FRAC_PI_2 + neg(kernel(c / a))
    }
}

/// Magnitude of `atan(|x|)` in `[0, π/2]`, as a double-double, via `kernel`.
#[inline]
fn atan_mag<K: Fn(DoubleDouble) -> DoubleDouble>(a: f64, kernel: K) -> DoubleDouble {
    if a > 1.0 {
        // atan(a) = π/2 − atan(1/a)
        FRAC_PI_2 + neg(kernel(ONE / a))
    } else {
        kernel(DoubleDouble { high: a, low: 0.0 })
    }
}

/// Arctangent
#[must_use]
#[inline]
pub fn atan(x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }

    let a = x.abs();
    if a.is_infinite() {
        return core::f64::consts::FRAC_PI_2.copysign(x);
    }

    // Fast path: for |x| > 1 reflect via atan(a) = π/2 − atan(1/a) using the
    // division-frugal [`atan_recip_fast`]; otherwise the direct cell kernel.  The
    // accurate fallback keeps the shared [`atan_mag`] reflection.
    let fast = if a > 1.0 {
        FRAC_PI_2 + neg(atan_recip_fast(a))
    } else {
        atan_dd_fast(DoubleDouble { high: a, low: 0.0 })
    };
    let magnitude = ziv(fast).unwrap_or_else(|| {
        let m = atan_mag(a, atan_dd);
        m.high + m.low
    });
    magnitude.copysign(x)
}

/// Correctly-rounded `asin(a)` for `a = |x| ∈ [0, 1]`, the accurate fallback.
///
/// Two tiers: the double-double `asin(a) = atan(a/√(1−a²))` (`asin_pos`) handles
/// the bulk of fast-leg misses cheaply, and a second Ziv gate escalates only the
/// hard-to-round direct-branch points to the slow triple-double series
/// [`asin_direct_td`].  Cold and never inlined so the rare-miss bulk stays out of
/// [`asin`]'s hot path.
#[cold]
#[inline(never)]
fn asin_accurate(a: f64) -> f64 {
    let m = asin_pos(a, atan_dd);
    ziv_at(m, ASIN_DD_ZIV_EPS).unwrap_or_else(|| {
        if a < 0.5 {
            td_round(asin_direct_td(a))
        } else {
            m.high + m.low
        }
    })
}

/// Correctly-rounded `acos(x)`, the accurate fallback.  `acos(x) = π/2 − asin(x)`:
/// `π/2 − asin(|x|)` for `x ≥ 0`, `π/2 + asin(|x|)` for `x < 0`.  Same two-tier
/// scheme as [`asin_accurate`]: a double-double result, with a second Ziv gate
/// escalating the hard-to-round direct-branch points (where the `π/2 − asin`
/// subtraction needs the extra limb) to triple-double.
#[cold]
#[inline(never)]
fn acos_accurate(x: f64) -> f64 {
    let a = x.abs();
    let s = asin_pos(a, atan_dd);
    let m = if x.is_sign_negative() {
        FRAC_PI_2 + s
    } else {
        FRAC_PI_2 + neg(s)
    };
    ziv_at(m, ASIN_DD_ZIV_EPS).unwrap_or_else(|| {
        if a < 0.5 {
            let std = asin_direct_td(a);
            let mt = if x.is_sign_negative() {
                td_add(FRAC_PI_2_TD, std)
            } else {
                td_add(FRAC_PI_2_TD, td_neg(std))
            };
            td_round(mt)
        } else {
            m.high + m.low
        }
    })
}

/// Arcsine
#[must_use]
#[inline]
pub fn asin(x: f64) -> f64 {
    let a = x.abs();

    let (off, z, zl, r, j) = if a < 0.5 {
        // For |x| < 0x1.7137449123ef6p-26, `asin(x) − x = x³/6 + …` stays below
        // half an ulp of the result, so x is the correctly-rounded answer (and
        // ±0 keeps its sign without touching the offset fold).
        if a < 2.149119332890821e-8 {
            return x;
        }
        // asin(x) = x·B(x²): the sign rides in z, no offset.
        let jf = (128.0 * (x * x)).round_ties_even();
        let r = crate::fma(x, x, -(jf * 0.0078125)); // x² − j/128, exact-product residual
        // SAFETY: x² < ¼ puts jf in 0..=32; a plain `as` cast would pay a
        // saturation cmov chain right in front of the table load.
        (ZERO, x, 0.0, r, unsafe { jf.to_int_unchecked::<i64>() }
            as usize)
    } else {
        // Route the domain edge and NaN here so the direct branch costs a
        // single compare.
        if !(a < 1.0) {
            if a == 1.0 {
                // asin(±1) = ±π/2 (and avoids √0 → 0/0 in the reflection).
                return core::f64::consts::FRAC_PI_2.copysign(x);
            }
            return f64::NAN; // |x| > 1 or NaN
        }
        // asin(x) = sign(x)·(π/2 − √t·B(u)) with t = 2 − 2|x| and u = ¼t both
        // exact (Sterbenz), so only the multiplier √t = 2s needs a low word
        // (one division), avoiding the double-double `sqrt`.  The sign rides in
        // z = −√t·sign(x) and off = ±π/2.
        let t = 2.0 * (1.0 - a);
        let z = -t.sqrt().copysign(x);
        let zl = crate::fma(z, z, -t) * ((-0.5 / t) * z);
        let u = 0.25 * t;
        let jf = (128.0 * u).round_ties_even();
        let r = u - jf * 0.0078125; // exact
        let off = DoubleDouble {
            high: FRAC_PI_2.high.copysign(x),
            low: FRAC_PI_2.low.copysign(x),
        };
        // SAFETY: u = ¼t ≤ ¼ puts jf in 0..=32 (see the direct branch).
        (off, z, zl, r, unsafe { jf.to_int_unchecked::<i64>() }
            as usize)
    };

    asin_tail(off, z, zl, r, j).unwrap_or_else(|| asin_accurate(a).copysign(x))
}

/// Arccosine
#[must_use]
#[inline]
pub fn acos(x: f64) -> f64 {
    let a = x.abs();

    let (off, z, zl, r, j) = if a < 0.5 {
        // acos(x) = π/2 + (−x)·B(x²)
        let jf = (128.0 * (x * x)).round_ties_even();
        let r = crate::fma(x, x, -(jf * 0.0078125));
        // SAFETY: x² < ¼ puts jf in 0..=32 (see `asin`).
        (
            FRAC_PI_2,
            -x,
            0.0,
            r,
            unsafe { jf.to_int_unchecked::<i64>() } as usize,
        )
    } else {
        // Route the domain edge and NaN here so the direct branch costs a
        // single compare.
        if !(a < 1.0) {
            if a == 1.0 {
                // acos(1) = 0, acos(−1) = π (and avoids √0 → 0/0 below).
                return if x.is_sign_negative() {
                    core::f64::consts::PI
                } else {
                    0.0
                };
            }
            return f64::NAN; // |x| > 1 or NaN
        }
        // acos(x) = √t·B(u) for x ≥ ½, π − √t·B(u) for x ≤ −½: the sign rides
        // in z = √t·sign(x), and the offset is the branchless (and
        // componentwise-exact) `π/2 − copysign(π/2, x)` — 0 for x > 0 and
        // π = 2·(π/2) for x < 0.  A sign branch (or a 2-entry table, which
        // LLVM lowers back to one) mispredicts on a quarter of random inputs.
        let t = 2.0 * (1.0 - a);
        let z = t.sqrt().copysign(x);
        let zl = crate::fma(z, z, -t) * ((-0.5 / t) * z);
        let u = 0.25 * t;
        let jf = (128.0 * u).round_ties_even();
        let r = u - jf * 0.0078125; // exact
        let off = DoubleDouble {
            high: FRAC_PI_2.high - FRAC_PI_2.high.copysign(x),
            low: FRAC_PI_2.low - FRAC_PI_2.low.copysign(x),
        };
        // SAFETY: u = ¼t ≤ ¼ puts jf in 0..=32 (see the direct branch).
        (off, z, zl, r, unsafe { jf.to_int_unchecked::<i64>() }
            as usize)
    };

    asin_tail(off, z, zl, r, j).unwrap_or_else(|| acos_accurate(x))
}

/// Magnitude of `atan2(y, x)` in `[0, π]` for finite nonzero `a = |x|`, `b = |y|`.
#[inline]
fn atan2_mag(a: f64, b: f64, x_negative: bool) -> f64 {
    let (big, small, swapped) = if a >= b { (a, b, false) } else { (b, a, true) };

    let theta = |cell: fn(DoubleDouble, DoubleDouble) -> DoubleDouble| {
        // φ = atan(small/big) ∈ [0, π/4], or π/2 − atan(small/big) when `swapped`.
        let q = small / big;
        let inner = if q < 9.094947017729282e-13 {
            // Tiny ratio: atan(q) = q far below ½ ulp, and the *unscaled* IEEE
            // quotient `small/big` is correctly rounded down into the subnormals.
            DoubleDouble { high: q, low: 0.0 }
        } else {
            // Scale both legs so the larger lands in [1, 2): exact and
            // ratio-preserving, keeping `small − c·big` / `big + c·small` clear of
            // overflow and the small leg out of the subnormals.
            let (_, exp) = super::frexp(big);
            let big = super::ldexp(big, 1 - exp);
            let small = super::ldexp(small, 1 - exp);

            // Cell reduction without forming small/big as a double-double: with
            // ratio = small/big, `u = (ratio − c)/(1 + ratio·c) = (small − c·big)/(big
            // + c·small)`.  `k = round(8·ratio)` reuses the `q` already in hand
            // (scaling preserves the ratio exactly), so the leg spends only that one
            // `q` division plus this `recip` — two, versus the four of the
            // `from_quotient` path (the `q` test, the two-division quotient, the cell
            // `recip`).  `small − c·big` is exact (c·big ≈ small in-cell, `from_product`
            // exact), so `u` is at least as accurate, and `|u| ≤ 1/16` as before.
            let k = (q * 8.0).round_ties_even();
            let c = k * 0.125;
            // SAFETY: q = small/big ∈ [0, 1] puts k in 0..=8 (see `atan_dd_fast`).
            let table = ATAN_TABLE[unsafe { k.to_int_unchecked::<i64>() } as usize];

            let num = DoubleDouble {
                high: small,
                low: 0.0,
            } + neg(DoubleDouble::from_product(c, big));
            let den = DoubleDouble {
                high: big,
                low: 0.0,
            } + DoubleDouble::from_product(c, small);
            let u = num * den.recip();

            cell(table, u)
        };

        let phi = if swapped {
            FRAC_PI_2 + neg(inner)
        } else {
            inner
        };
        if x_negative { PI + neg(phi) } else { phi }
    };

    ziv(theta(atan_cell_fast)).unwrap_or_else(|| {
        let m = theta(atan_cell);
        m.high + m.low
    })
}

/// Arctangent of `y / x`, using the signs of both to select the quadrant
///
/// The result is the angle in `(-π, π]` between the positive `x`-axis and the
/// point `(x, y)`, carrying the sign of `y`.
#[must_use]
#[inline]
pub fn atan2(y: f64, x: f64) -> f64 {
    use core::f64::consts::{FRAC_PI_2, FRAC_PI_4, PI};

    /// Correctly-rounded `f64` of 3π/4.
    const THREE_PI_4: f64 = 2.356194490192345;

    if x.is_nan() || y.is_nan() {
        return f64::NAN;
    }

    if x.is_infinite() || y.is_infinite() {
        let magnitude = match (x.is_infinite(), y.is_infinite()) {
            (true, true) if x.is_sign_positive() => FRAC_PI_4,
            (true, true) => THREE_PI_4,
            (true, false) if x.is_sign_positive() => 0.0,
            (true, false) => PI,
            (false, true) => FRAC_PI_2,
            (false, false) => unreachable!(),
        };
        return magnitude.copysign(y);
    }

    if y == 0.0 {
        return if x.is_sign_positive() { 0.0 } else { PI }.copysign(y);
    }
    if x == 0.0 {
        return FRAC_PI_2.copysign(y);
    }

    atan2_mag(x.abs(), y.abs(), x.is_sign_negative()).copysign(y)
}

/// The Fast2Sum-based folds of [`atan_cell_fast`] need `|a| ≥ |b|`; prove the
/// orderings from coefficient-magnitude bounds at the cell edge `|u| ≤ 1/16`
/// (cf. the same-named modules in `erf.rs` and `trig.rs`).
#[cfg(test)]
mod fold_ordering {
    use super::*;

    #[test]
    fn atan_cell() {
        // Slack for the rounding of u (one lean division) and w = u·u.
        let umax = 0.0625 * 1.0001;
        let wmax = umax * umax;
        let tail_mag = ATAN_TAIL
            .iter()
            .rev()
            .fold(0.0, |acc, c| crate::fast_mul_add(acc, wmax, c.abs()));

        // bracket = 1 ⊕ w·(−1/3) ⊕ w²·tail
        let c1_mag = ATAN_COEFFS[1].high.abs() + ATAN_COEFFS[1].low.abs();
        assert!(wmax * c1_mag <= 0.5);
        let lead_min = 1.0 - wmax * c1_mag;
        assert!(wmax * wmax * tail_mag <= 0.5 * lead_min);

        // table ⊕ u·bracket for k ≥ 1 (k = 0 has table = 0, where Fast2Sum is
        // exact by itself); the k = 1 cell is the tightest at 0.504.
        let bracket_mag = crate::fast_mul_add(wmax * wmax, tail_mag, 1.0 + wmax * c1_mag);
        for cell in &ATAN_TABLE[1..] {
            assert!(umax * bracket_mag <= 0.55 * cell.high.abs());
        }
    }

    /// [`asin_tail`]'s `off ⊕ p` fold: `|off| ≥ |p.high|` for every nonzero
    /// offset (`off = 0`, asin's direct branch, is exact unconditionally).
    /// `|p.high| ≤ Bmax·|z|·(1 + ε)` with `Bmax = B(¼)` the largest table lead;
    /// `|z| ≤ 1` in the reflections (`√t ≤ 1`) and `|z| ≤ ½` in acos's direct
    /// branch.
    #[test]
    fn asin_offsets() {
        let bmax = ASIN_CELLS
            .iter()
            .map(|cell| cell.lead.high)
            .fold(0.0, f64::max)
            * 1.0001;

        // Reflections: off = ±π/2 (asin) or π (acos, x < −½) vs |p| ≤ Bmax.
        assert!(bmax <= 0.7 * FRAC_PI_2.high);
        assert!(bmax <= 0.35 * PI.high);
        // acos direct: off = π/2 vs |p| ≤ Bmax/2.
        assert!(0.5 * bmax <= 0.35 * FRAC_PI_2.high);
    }
}

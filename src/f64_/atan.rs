impl Tint {
    /// `true` if `self` is zero.
    #[inline]
    const fn is_zero(&self) -> bool {
        self.hi == 0
    }

    /// Negate (flip the sign bit).
    #[inline]
    const fn neg(self) -> Self {
        Self {
            sgn: !self.sgn,
            ..self
        }
    }

    /// Compare magnitudes: `Less`/`Equal`/`Greater` like `cmp_tint_abs`.
    #[inline]
    fn cmp_abs(&self, other: &Self) -> core::cmp::Ordering {
        use core::cmp::Ordering;
        if self.is_zero() {
            return if other.is_zero() {
                Ordering::Equal
            } else {
                Ordering::Less
            };
        }
        if other.is_zero() {
            return Ordering::Greater;
        }
        self.ex
            .cmp(&other.ex)
            .then_with(|| self.hi.cmp(&other.hi))
            .then_with(|| self.lo.cmp(&other.lo))
    }

    /// Significand `(hi, lo)` shifted right by `k` bits (port of `rshift`).
    #[inline]
    const fn rshift(&self, k: u32) -> (u128, u64) {
        if k == 0 {
            (self.hi, self.lo)
        } else if k < 64 {
            let hi = self.hi >> k;
            let lo = ((self.hi << (64 - k)) as u64) | (self.lo >> k);
            (hi, lo)
        } else if k == 64 {
            (self.hi >> 64, self.hi as u64)
        } else if k < 128 {
            (self.hi >> k, (self.hi >> (k - 64)) as u64)
        } else if k < 192 {
            (0, (self.hi >> (k - 64)) as u64)
        } else {
            (0, 0)
        }
    }

    /// Significand `(hi, lo)` shifted left by `k` bits (port of `lshift`).
    #[inline]
    fn lshift(&self, k: u32) -> (u128, u64) {
        if k == 0 {
            (self.hi, self.lo)
        } else if k < 64 {
            let hi = (self.hi << k) | u128::from(self.lo >> (64 - k));
            let lo = self.lo << k;
            (hi, lo)
        } else if k == 64 {
            ((self.hi << 64) | u128::from(self.lo), 0)
        } else if k < 128 {
            ((self.hi << k) | (u128::from(self.lo) << (k - 64)), 0)
        } else if k < 192 {
            (u128::from(self.lo) << (k - 64), 0)
        } else {
            (0, 0)
        }
    }

    /// Leading-zero count of the 192-bit significand `(hi, lo)`.
    #[inline]
    const fn clz192(hi: u128, lo: u64) -> u32 {
        if hi != 0 {
            hi.leading_zeros()
        } else {
            128 + lo.leading_zeros()
        }
    }

    /// Round-to-nearest product, error < 10 ulp / 2⁻¹⁸⁷·⁶⁷·|r| (port of `mul_tint`).
    #[inline]
    fn mul(&self, other: &Self) -> Self {
        let ah = u128::from((self.hi >> 64) as u64);
        let am = u128::from(self.hi as u64);
        let al = u128::from(self.lo);
        let bh = u128::from((other.hi >> 64) as u64);
        let bm = u128::from(other.hi as u64);
        let bl = u128::from(other.lo);

        let rh = ah * bh;
        let rm1 = ah * bm;
        let rm2 = am * bh;
        let rl1 = ah * bl;
        let rl2 = am * bm;
        let rl3 = al * bh;

        let mut r_h = (rh >> 64) as u64;
        let mut r_m = rh as u64;
        let mut r_l = rm1 as u64;

        // accumulate rm1
        let h = (rm1 >> 64) as u64;
        let (nm, c) = r_m.overflowing_add(h);
        r_m = nm;
        r_h = r_h.wrapping_add(u64::from(c));
        // accumulate rm2
        let l = rm2 as u64;
        let h = (rm2 >> 64) as u64;
        let (nl, c0) = r_l.overflowing_add(l);
        r_l = nl;
        let mut cm = u64::from(c0);
        let (nm, c) = r_m.overflowing_add(h);
        r_m = nm;
        r_h = r_h.wrapping_add(u64::from(c));
        // accumulate rl1 + rl2 + rl3 (high words)
        let rl = (rl1 >> 64) + (rl2 >> 64) + (rl3 >> 64);
        let l = rl as u64;
        cm = cm.wrapping_add((rl >> 64) as u64);
        let (nl, c0) = r_l.overflowing_add(l);
        r_l = nl;
        cm = cm.wrapping_add(u64::from(c0));
        // accumulate cm
        let (nm, c) = r_m.overflowing_add(cm);
        r_m = nm;
        r_h = r_h.wrapping_add(u64::from(c));

        let mut hi = (u128::from(r_h) << 64) | u128::from(r_m);
        let mut lo = r_l;
        let mut ex = self.ex + other.ex;

        // normalize so bit 127 is set (unless zero)
        if hi >> 127 == 0 {
            hi = (hi << 1) | u128::from(lo >> 63);
            lo <<= 1;
            ex -= 1;
        }

        Self {
            sgn: self.sgn ^ other.sgn,
            ex,
            hi,
            lo,
        }
    }

    /// Round-to-nearest sum, error ≤ 2 ulp (port of `add_tint`).
    #[inline]
    fn add(&self, other: &Self) -> Self {
        use core::cmp::Ordering;
        let (a, b) = match self.cmp_abs(other) {
            Ordering::Equal => {
                // |a| = |b|: return 0 (opposite signs) or 2·a (same sign), exact.
                if self.sgn != other.sgn {
                    return ZERO_TINT;
                }
                return Self {
                    ex: self.ex + 1,
                    ..*self
                };
            }
            Ordering::Less => (other, self),
            Ordering::Greater => (self, other),
        };

        // |a| > |b|, so a.ex >= b.ex.
        let sh = (a.ex - b.ex) as u32;
        let (t_hi, t_lo) = b.rshift(sh);

        if a.sgn != b.sgn {
            // opposite signs: subtraction a - (shifted b)
            let (l, borrow0) = a.lo.overflowing_sub(t_lo);
            let h = a.hi.wrapping_sub(t_hi).wrapping_sub(u128::from(borrow0));
            let ex = Self::clz192(h, l);
            if ex <= 1 || sh == 0 {
                let tmp = Self {
                    sgn: false,
                    ex: 0,
                    hi: h,
                    lo: l,
                };
                let (rhi, rlo) = tmp.lshift(ex);
                Self {
                    sgn: a.sgn,
                    ex: a.ex - i64::from(ex),
                    hi: rhi,
                    lo: rlo,
                }
            } else {
                // ex >= 2 and sh >= 1: re-do the subtraction with no neglected
                // bits of b (shift both a and b left by `ex`).
                let (tb_hi, tb_lo) = b.lshift(ex - sh);
                let (ra_hi, ra_lo) = a.lshift(ex);
                let (l2, borrow) = ra_lo.overflowing_sub(tb_lo);
                let h2 = ra_hi.wrapping_sub(tb_hi).wrapping_sub(u128::from(borrow));
                let ex1 = Self::clz192(h2, l2);
                let tmp = Self {
                    sgn: false,
                    ex: 0,
                    hi: h2,
                    lo: l2,
                };
                let (rhi, rlo) = tmp.lshift(ex1);
                Self {
                    sgn: a.sgn,
                    ex: a.ex - i64::from(ex + ex1),
                    hi: rhi,
                    lo: rlo,
                }
            }
        } else {
            // same signs: addition
            let (l, cl) = a.lo.overflowing_add(t_lo);
            let (mut h, ch0) = a.hi.overflowing_add(t_hi);
            let mut ch = u128::from(ch0);
            let (h2, ch1) = h.overflowing_add(u128::from(cl));
            h = h2;
            ch += u128::from(ch1);
            if ch != 0 {
                // carry out of bit 127: shift right one, restoring the carry bit.
                let lo = ((h as u64) << 63) | (l >> 1);
                let hi = (ch << 127) | (h >> 1);
                Self {
                    sgn: a.sgn,
                    ex: a.ex + 1,
                    hi,
                    lo,
                }
            } else {
                Self {
                    sgn: a.sgn,
                    ex: a.ex,
                    hi: h,
                    lo: l,
                }
            }
        }
    }

    /// Convert a finite nonzero `f64` to a `Tint`, exactly (port of `tint_fromd`).
    #[inline]
    fn from_f64(x: f64) -> Self {
        let u = x.to_bits();
        let sgn = u >> 63 == 1;
        let ax = u & 0x7fff_ffff_ffff_ffff;
        let e = (ax >> 52) as i64;
        let (ex, h) = if e != 0 {
            // normal: 1 has e = 0x3ff
            (e - 0x3fe, (1u64 << 63) | (ax << 11))
        } else {
            // subnormal: 2^-1074 has ax = 1
            let lz = ax.leading_zeros();
            (-0x3f2 - i64::from(lz), ax << lz)
        };
        Self {
            sgn,
            ex,
            hi: u128::from(h) << 64,
            lo: 0,
        }
    }

    /// Convert to `f64` with correct rounding (port of `tint_tod`).
    ///
    /// `err` is a bound in ulps (of 2⁻¹⁹²) on the error of `lo`; `err == 0` means
    /// an exact value.  `atan2` magnitudes fed here are in `[0, π]` but can be
    /// subnormal in the first-quadrant `atan(small/big)` corner, so the subnormal
    /// (and the extreme-underflow) branches do fire and are ported faithfully;
    /// the overflow branch cannot but is kept for completeness.
    #[inline]
    #[allow(clippy::wrong_self_convention)] // `Tint` is `Copy`; `&self` avoids a move (cf. `Dint::to_f64`)
    fn to_f64(&self, err: u64) -> f64 {
        if self.ex >= 1025 {
            return if self.sgn {
                f64::NEG_INFINITY
            } else {
                f64::INFINITY
            };
        }
        if self.ex <= -1074 {
            if self.ex < -1074 {
                return (if self.sgn { -1.0 } else { 1.0 })
                    * f64::from_bits(0x0000_0000_0000_0001)
                    * 0.5;
            }
            let mid = self.hi == (1u128 << 127) && self.lo == 0;
            return (if self.sgn { -1.0 } else { 1.0 })
                * f64::from_bits(0x0000_0000_0000_0001)
                * if mid { 0.5 } else { 0.75 };
        }

        let mut hh = (self.hi >> 64) as u64;
        let mut mm = self.hi as u64;
        let mut ll = self.lo;
        let mut ex = self.ex;
        let mut low = hh & 0x7ff;

        if ex <= -1022 {
            // subnormal result: shift the significand right by `sh`.
            let sh = (-1021 - ex) as u32; // 1..=52
            ll = (mm << (64 - sh)) | (ll >> sh) | u64::from(ll > 0);
            mm = (hh << (64 - sh)) | (mm >> sh);
            hh >>= sh;
            low = hh & 0x7ff;
            ex += i64::from(sh);
        }

        let h_top = (hh >> 11) as f64; // top 53 bits
        let l = if err == 0 {
            0.0
        } else if low < 0x400 {
            0.25 // round toward zero
        } else if low > 0x400 {
            0.75 // round away
        } else if mm == 0 && ll == 0 {
            0.5 // exact midpoint
        } else {
            0.75 // round away
        };

        let s = if self.sgn { -1.0 } else { 1.0 };
        let mut h = crate::fma(l, s, s * h_top);
        h *= f64::from_bits(0x3cb0_0000_0000_0000); // 2^-52
        // -1021 <= ex <= 1024, so 2^(ex-1) neither under- nor overflows.
        h * super::ldexp(1.0, (ex - 1) as i32)
    }

    /// Approximate `1/self`, relative error ≤ 2⁻¹⁰³·⁹ (port of `inv_tint`).
    #[inline]
    fn inv(&self) -> Self {
        let a = self.to_f64(0); // exact
        let subnormal = a.abs() < f64::MIN_POSITIVE;
        let a = if subnormal {
            a * f64::from_bits(0x4350_0000_0000_0000) // 2^53
        } else {
            a
        };
        let mut r = Self::from_f64(1.0 / a);
        if subnormal {
            r.ex += 53;
        }
        // Newton: r ← r + r·(1 − a·r).
        let mut q = self.mul(&r);
        q.sgn = !q.sgn; // -a·r
        q = ONE_TINT.add(&q); // 1 - a·r
        q = r.mul(&q); // r·(1 - a·r)
        r.add(&q)
    }

    /// Approximate `b/self` (= `b/a`), relative error ≤ 2⁻¹⁸⁵·⁵³ (port of `div_tint`).
    #[inline]
    fn div(b: &Self, a: &Self) -> Self {
        let y = a.inv(); // |y - 1/a| small
        let mut r = y.mul(b); // r ≈ b/a
        // Karp–Markstein: r ← r + y·(b − a·r).
        let mut z = a.mul(&r); // a·r
        z.sgn = !z.sgn; // -a·r
        z = b.add(&z); // b - a·r
        z = y.mul(&z); // y·(b - a·r)
        r = r.add(&z);
        r
    }

    /// `b / a` for `f64` inputs (port of `div_tint_d`).
    #[inline]
    fn div_d(b: f64, a: f64) -> Self {
        Self::div(&Self::from_f64(b), &Self::from_f64(a))
    }
}


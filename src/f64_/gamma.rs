//! Gamma functions: `tgamma`, `lgamma`.
//!
//! `tgamma` reduces `z` into `[2.375, 3.375]` (centre 2.875), evaluates
//! `Γ(2.875 + d)`, then walks the recurrence `Γ(z) = Γ(z−i)·∏(z−k)` upward or
//! `Γ(z) = Γ(z−i)/∏(z+k)` downward.  Every factor is formed exactly
//! (`from_sum(z, k)`) and the products run on four parallel lanes; a deep downward
//! divisor carries a binary exponent so it never overflows even for very negative
//! `z`.  A table-driven fast leg (per-cell minimax of `Γ(2.875 + d)`) is Ziv-gated
//! against a triple-double accurate path (degree-38 minimax walked through a
//! triple-double recurrence, ≈2⁻¹³⁵) that clears the corpus's hardest near-ties.
//!
//! `lgamma = ln|Γ|` reads a central per-cell minimax of `ln Γ(2.875 + d)` for
//! `½ ≤ y < 8` (reducing into `[2.375, 3.375]` by `i = round(y − 2.875)` and adding
//! `± ln ∏` of the ≤ 5 recurrence factors), and applies direct Stirling for
//! `y ≥ 8`; for `z < ½` it reflects through `ln π − ln|sin(πz)| − ln Γ(1−z)`, with
//! `|sin(πz)|` from `trig::abs_sinpi_dd`.  A lean leg (`ln_fast` + the table or an
//! `f64` Stirling tail) is Ziv-gated against the double-double accurate path, which
//! shares the same central table.
//!
//! Neither has an f64 oracle in `core-math`, so correctness is verified against
//! MPFR (`tests/cases`).
//!
//! Constants below were generated by `tools/gen_gamma_f64.py`.
//! Do not edit by hand; re-run the generator instead.
#![allow(clippy::unreadable_literal, clippy::excessive_precision)]

use super::double::{DoubleDouble, fast_ldexp};

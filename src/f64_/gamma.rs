/// Absolute error bound for the Stirling [`lgamma_fast`] Ziv leg (`|z| ≥ 8`)
///
/// The leg's sub-double-double slack is the `f64` tail (≲2⁻⁶⁰ absolute) plus
/// `ln_fast`'s <2⁻⁶⁶-absolute error scaled by the largest log multiplier `t − ½`.
/// Keeping `|z|` below [`LGAMMA_FAST_BOUND`] keeps `t ≲ 256`, so that scaled term
/// stays ≲2⁻⁵⁸ and the total below `2⁻⁵⁶` with a comfortable margin.  Being
/// absolute, the gate also forces the accurate fallback whenever the result
/// cancels toward zero (lgamma's zeros at `z = 1, 2` and on `z < 0`), where `2⁻⁵⁶`
/// spans many ulps.
const LGAMMA_FAST_ERR: f64 = 1.3877787807814457e-17; // 2^-56

/// Absolute error bound for the central-table [`lgamma_fast`] Ziv leg (`½ ≤ z < 8`,
/// and the reflection's `ln Γ(1−z)` when `1−z < 8`)
///
/// The table leg has no Stirling tail: it is the per-cell minimax (worst 2⁻⁷⁸, the
/// `f64` cell tail and dropped `h.low` landing ≈2⁻⁶⁹) plus one `ln_fast` of the
/// ≤ 5 recurrence factors (<2⁻⁶⁶), so ≈2⁻⁶⁵·⁷ overall — far tighter than the
/// Stirling leg.  `2⁻⁶²` certifies it with a ~14× margin, and being ~16× tighter than
/// [`LGAMMA_FAST_ERR`] it straddles (defers) far less where `ln Γ` is O(1), which is
/// exactly this moderate band.
const LGAMMA_TABLE_ERR: f64 = 2.168404344971009e-19; // 2^-62

/// `|z|` ceiling for the [`lgamma_fast`] Ziv leg
///
/// Above it the largest log multiplier `t` would push `ln_fast`'s absolute slack
/// past [`LGAMMA_FAST_ERR`], so the gate could no longer certify the leg; such
/// `z` (rare, and far outside any benchmark) go straight to the accurate path.
/// (1024 under the old double-double reduction; the exact-`z` `ln_fast` trades
/// its looser <2⁻⁶⁶ bound for speed, so the certifiable band is `t·2⁻⁶⁶ ≤ 2⁻⁵⁸`.)
const LGAMMA_FAST_BOUND: f64 = 256.0;

/// Keep the divisor product's high word below this (rescale by `2⁵¹²`, tracking a
/// binary exponent) so the long negative-`z` product never overflows `f64`.
const PRODUCT_RESCALE: f64 = crate::exp2i(512);

/// Ziv gate for the tgamma fast leg, relative to the result.
///
/// The [`TGAMMA_TABLE`] leg is ≈2⁻⁶⁸: worst-cell minimax 2⁻⁷⁵, the `f64` tail
/// (≤ 2⁻¹⁹ of Γ) lands near 2⁻⁷¹, and the dropped `h.low` in the innermost fold
/// adds ≈2⁻⁶⁹; the recurrence's exact factors only ≈2⁻⁹⁸.  `2⁻⁶²` keeps a ~60×
/// margin, deferring ≈0.1% of inputs to the accurate [`TGAMMA_TD`] path.
const TGAMMA_ZIV_EPS: f64 = 2.168404344971009e-19; // 2^-62

/// Max downward recurrence length for the rescale-free parallel divisor product
///
/// With at most this many factors, every parallel lane (≤ ⌈n/4⌉ factors, each
/// `|z + k| ≤ |z| ≈ n`) stays well under `f64::MAX`, and so does their product, so
/// no binary-exponent rescaling is needed.  Deeper (more negative `z`) products
/// would overflow and take the serial rescaling path instead.
const TGAMMA_DOWNWARD_DIRECT: i64 = 100;

/// `∏_{m=0}^{n−1} (z + first + step·m)` as a double-double, on four parallel lanes
///
/// The `tgamma` recurrence products: upward `(z−1)(z−2)…(z−n)` is `first = step =
/// −1`, downward `z(z+1)…(z+n−1)` is `first = 0`, `step = 1`.  Each factor
/// `from_sum(z, …)` is exact (one 2Sum, `z` being a plain `f64`); four lanes cut
/// the dependency chain from `n` to `≈n/4` double-double multiplies, the
/// long-latency cost of the far-from-centre range.  The caller keeps `n` small
/// enough (all factors > 1 upward; [`TGAMMA_DOWNWARD_DIRECT`] downward) that the
/// product cannot overflow.
#[inline]
fn recurrence_product_z(z: f64, first: i64, step: i64, n: i64) -> DoubleDouble {
    let factor = |m: i64| DoubleDouble::from_sum(z, (first + step * m) as f64);

    let mut p = [ONE; 4];
    let mut m = 0;
    while m + 4 <= n {
        p[0] = p[0] * factor(m);
        p[1] = p[1] * factor(m + 1);
        p[2] = p[2] * factor(m + 2);
        p[3] = p[3] * factor(m + 3);
        m += 4;
    }
    while m < n {
        p[0] = p[0] * factor(m);
        m += 1;
    }
    (p[0] * p[1]) * (p[2] * p[3])
}

/// Reduce `z` for the recurrence: `(i, d)` with `d = z − (2.875 + i)`, `d ∈ [−½, ½]`
#[inline]
fn tgamma_reduce(z: f64) -> (f64, DoubleDouble) {
    let i = (z - TGAMMA_CENTER).round_ties_even();
    // The reduced argument `d = z − (2.875 + i)` must be exact: a plain-f64
    // `z − 2.875 − i` loses `z`'s low bits when `z ≪ 2.875` (the small-`z` pole).
    // `2.875 + i` is exact for any integer `i`, so `from_sum` captures `d` in full.
    (i, DoubleDouble::from_sum(z, -(TGAMMA_CENTER + i)))
}

/// A per-cell minimax `f(2.875 + d)` for `d ∈ [−½, ½]` straight from a 9-cell
/// `table` — the fast-leg evaluator shared by `Γ` ([`TGAMMA_TABLE`]) and `ln Γ`
/// ([`LGAMMA_TABLE`]).
///
/// `fi = round(8·d)` picks the cell; the high-word subtraction `d.high − fi/8` is
/// Sterbenz-exact and `d.low` rides along, so `h` is exact.  The `c4..c11` tail
/// sums in `f64` (small relative to the result), then the `c3..c0` leads fold in
/// double-double — a few double-double FMAs versus the accurate polynomial.  `h`
/// keeps its low word through the leads: `c1·d.low` alone can reach 2⁻⁵⁴, far above
/// the leg's budget.
#[inline]
fn cell_eval(table: &[GammaCell; 9], d: DoubleDouble) -> DoubleDouble {
    let fi = (d.high * 8.0).round_ties_even();
    // SAFETY: d.high ∈ [−½, ½] ⇒ fi ∈ [−4, 4].
    let cell = &table[(unsafe { fi.to_int_unchecked::<i64>() } + 4) as usize];
    let h = DoubleDouble {
        high: d.high - fi * 0.125,
        low: d.low,
    };

    // P(h) = c0 + h·(c1 + h·(c2 + h·(c3 + h·tail))), tail = c4 + c5·h + … in f64.
    let tail = crate::poly(h.high, &cell.tail);
    let acc = cell.c3
        + DoubleDouble {
            high: h.high * tail,
            low: 0.0,
        };
    let acc = cell.c2 + acc * h;
    let acc = cell.c1 + acc * h;
    cell.c0 + acc * h
}

/// `Γ(2.875 + d)` for `d ∈ [−½, ½]` straight from [`TGAMMA_TABLE`] — the fast leg
#[inline]
fn tgamma_table_eval(d: DoubleDouble) -> DoubleDouble {
    cell_eval(&TGAMMA_TABLE, d)
}

/// Walk the recurrence from `value = Γ(z − i)` to `(value, e2)` with
/// `Γ(z) = value · 2`<sup>`e2`</sup>
///
/// Both products run on the parallel-lane [`recurrence_product_z`].  Upward
/// (`i > 0`) the partial products stay below the final `Γ(z)`, so no scaling is
/// needed; downward (`i < 0`) a short divisor (≤ [`TGAMMA_DOWNWARD_DIRECT`]) also
/// fits, while a deep one is accumulated serially and rescaled by `2⁵¹²` whenever
/// it grows large, with the total folded into `e2`.
#[inline]
fn tgamma_recurrence(z: f64, i: f64, value: DoubleDouble) -> (DoubleDouble, i64) {
    // SAFETY-free: `|i|` is a small integer (`z` is finite and bounded by the
    // overflow/underflow guards), so the casts below are exact.
    let steps = i.abs() as i64;

    if i > 0.0 {
        // Γ(z) = Γ(z−i)·(z−1)(z−2)…(z−i); every factor `from_sum(z, −k)` is exact
        // and > 1, so the product never overflows and needs no rescaling.
        (value * recurrence_product_z(z, -1, -1, steps), 0)
    } else if i < 0.0 && steps <= TGAMMA_DOWNWARD_DIRECT {
        // Γ(z) = Γ(z−i)/[z(z+1)…(z+|i|−1)].  Short divisor: no overflow, so form it
        // on parallel lanes and divide.
        (value * recurrence_product_z(z, 0, 1, steps).recip(), 0)
    } else if i < 0.0 {
        // Deep negative z: the long divisor product would overflow, so accumulate
        // it serially, carrying a binary exponent folded into the result scale.
        let mut product = DoubleDouble { high: z, low: 0.0 };
        let mut e2: i64 = 0;
        let mut k = 0.0;
        for _ in 1..steps {
            k += 1.0;
            product = product * DoubleDouble::from_sum(z, k);
            if product.high.abs() > PRODUCT_RESCALE {
                product = DoubleDouble {
                    high: fast_ldexp(product.high, -512),
                    low: fast_ldexp(product.low, -512),
                };
                e2 += 512;
            }
        }
        (value * product.recip(), -e2)
    } else {
        (value, 0)
    }
}

/// Walk the recurrence in **triple-double** from `value = Γ(z − i)` to
/// `(value, e2)` with `Γ(z) = value · 2`<sup>`e2`</sup> — the lifted accurate
/// path's analogue of [`tgamma_recurrence`].
///
/// Same three cases (upward product, short downward divide, deep downward serial
/// rescale), each in triple-double via [`recurrence_product_z_td`] / [`td_recip`].
#[inline]
fn tgamma_recurrence_td(z: f64, i: f64, value: TripleDouble) -> (TripleDouble, i64) {
    let steps = i.abs() as i64;

    if i > 0.0 {
        (td_mul(value, recurrence_product_z_td(z, -1, -1, steps)), 0)
    } else if i < 0.0 && steps <= TGAMMA_DOWNWARD_DIRECT {
        (
            td_mul(value, td_recip(recurrence_product_z_td(z, 0, 1, steps))),
            0,
        )
    } else if i < 0.0 {
        let mut product = TripleDouble {
            high: z,
            mid: 0.0,
            low: 0.0,
        };
        let mut e2: i64 = 0;
        let mut k = 0.0;
        for _ in 1..steps {
            k += 1.0;
            product = dd_mul_td(DoubleDouble::from_sum(z, k), product);
            if product.high.abs() > PRODUCT_RESCALE {
                product = TripleDouble {
                    high: fast_ldexp(product.high, -512),
                    mid: fast_ldexp(product.mid, -512),
                    low: fast_ldexp(product.low, -512),
                };
                e2 += 512;
            }
        }
        (td_mul(value, td_recip(product)), -e2)
    } else {
        (value, 0)
    }
}

/// The gamma function
#[must_use]
#[inline]
pub fn tgamma(z: f64) -> f64 {
    if z.is_nan() {
        return z;
    }
    if z == f64::INFINITY {
        return f64::INFINITY;
    }

    // Γ(±0) = ±∞, and Γ(z) ≈ 1/z overflows for |z| at or below `TGAMMA_TINY`
    // (= 2⁻¹⁰²⁴): Γ(±2⁻¹⁰²⁴) ≈ 2¹⁰²⁴ rounds to ±∞, while the next subnormal up is
    // finite (≈f64::MAX).  Must be `<=`, not `<`: the boundary itself overflows,
    // and falling through to the recurrence there returned a bogus `2.0`.
    if z.abs() <= TGAMMA_TINY {
        return f64::INFINITY.copysign(z);
    }

    // Γ exceeds `f64::MAX` past `TGAMMA_OVERFLOW`; bail before the recurrence loop.
    if z >= TGAMMA_OVERFLOW {
        return f64::INFINITY;
    }

    // Non-positive integers are poles; below `TGAMMA_UNDERFLOW` every hump rounds
    // to a signed zero (sign alternating with each pole).
    if z < 0.0 {
        if z == z.floor() {
            return f64::NAN;
        }
        if z <= TGAMMA_UNDERFLOW {
            return if (z.floor() as i64) & 1 == 0 {
                0.0
            } else {
                -0.0
            };
        }
    }

    // Reduce once into `[2.375, 3.375]`; both legs share the recurrence.
    let (i, d) = tgamma_reduce(z);

    // Ziv two-step: the table leg is correctly rounded for a comfortably-normal
    // result unless it straddles a boundary, where the double-double path resolves
    // it.  Scaled (`e2 ≠ 0`) and near-subnormal results go straight to the accurate
    // path, whose `round_general_signed64` handles the subnormal grid.
    let (value, e2) = tgamma_recurrence(z, i, tgamma_table_eval(d));
    if e2 == 0 {
        let err = value.high.abs() * TGAMMA_ZIV_EPS;
        let lo = value.high + (value.low - err);
        let hi = value.high + (value.low + err);
        if lo == hi && lo.abs() >= f64::MIN_POSITIVE * 2.0 {
            return lo;
        }
    }

    tgamma_accurate(z, i, d)
}

/// The accurate **triple-double** leg of [`tgamma`], reached only when the table
/// leg's Ziv test fails to certify a correctly-rounded result.  Outlined as
/// `#[cold] #[inline(never)]` — the degree-38 [`TGAMMA_TD`] evaluation through
/// [`poly_td`] plus the triple-double recurrence is bulky and almost never taken,
/// so inlining it would only bloat the hot path.
///
/// Lifted from double-double to triple-double (≈2⁻¹³⁵) because the double-double
/// recurrence degraded to ≈2⁻⁹⁹, straddling the corpus's ≈2⁻⁶⁰ near-ties (see the
/// triple-double section); the lift clears them all with a > 70-bit margin.
#[cold]
#[inline(never)]
fn tgamma_accurate(z: f64, i: f64, d: DoubleDouble) -> f64 {
    let (value, e2) = tgamma_recurrence_td(z, i, poly_td(dd_to_td(d), &TGAMMA_TD));
    round_td_signed64(value, e2)
}

/// Natural logarithm of a positive double-double, as a double-double.
///
/// `ln(s) = ln(s.high) + ln(1 + s.low/s.high) ≈ ln_dd(s.high) + s.low/s.high`.
#[inline]
fn ln_sum(s: DoubleDouble) -> DoubleDouble {
    crate::f64_::ln_dd(s.high)
        + DoubleDouble {
            high: s.low / s.high,
            low: 0.0,
        }
}

/// [`ln_sum`] with the lean `ln_fast` (<2⁻⁶⁶ absolute) — the Ziv fast leg's log.
#[inline]
fn ln_fast_sum(s: DoubleDouble) -> DoubleDouble {
    crate::f64_::ln_fast(s.high)
        + DoubleDouble {
            high: s.low / s.high,
            low: 0.0,
        }
}

/// `∏_{j=0}^{n−1}(y + j)` as a double-double, on four parallel lanes (`n ≥ 1`)
///
/// Each factor `y + j` is formed by a double-double add so it is exact even when
/// `y.high + j` rounds (`y.high ≈ 1`, `j ≈ 40`: the bottom bits of `y.high` fall
/// off the high word and are caught in the low word — exactly what the serial
/// `t + 1` recurrence preserved).  The only added error is the reassociation
/// across lanes, a few `2⁻¹⁰⁵` ulps.  Four lanes cut the dependency chain from `n`
/// to `≈n/4` double-double multiplies, the long-latency cost that dominates the
/// reduced `lgamma` range; the same trick as `f32`'s `recurrence_product`.
#[inline]
fn recurrence_product_dd(y: DoubleDouble, n: i64) -> DoubleDouble {
    let factor = |j: i64| {
        y + DoubleDouble {
            high: j as f64,
            low: 0.0,
        }
    };

    let mut p = [ONE; 4];
    let mut j = 0;
    while j + 4 <= n {
        p[0] = p[0] * factor(j);
        p[1] = p[1] * factor(j + 1);
        p[2] = p[2] * factor(j + 2);
        p[3] = p[3] * factor(j + 3);
        j += 4;
    }
    while j < n {
        p[0] = p[0] * factor(j);
        j += 1;
    }
    (p[0] * p[1]) * (p[2] * p[3])
}

/// Reduce positive `y` (with `y.high < LGAMMA_FAST_CUTOFF`) onto the central cell:
/// `(i, d)` with `d = y − (LGAMMA_CENTER + i)` exact, `|d.high| ≤ ½`
///
/// `i = round(y.high − 2.875) ∈ [−2, 5]`.  `2.875 + i` is exact, and
/// `|y.high − (2.875+i)| ≤ ½ ≪ y.high`, so the double-double subtract loses nothing
/// (the high word is Sterbenz-exact, `y.low` folds into the normalized low).
#[inline]
fn lgamma_center_reduce(y: DoubleDouble) -> (i64, DoubleDouble) {
    let fi = (y.high - LGAMMA_CENTER).round_ties_even();
    // SAFETY: y.high ∈ [½, 8) ⇒ y.high − 2.875 ∈ [−2.375, 5.125) ⇒ fi ∈ [−2, 5].
    let i = unsafe { fi.to_int_unchecked::<i64>() };
    let d = y + DoubleDouble {
        high: -(LGAMMA_CENTER + fi),
        low: 0.0,
    };
    (i, d)
}

/// `ln ∏` of the recurrence factors that carry the central cell back to `y`
///
/// `i > 0` reduces `y` down to `y − i ∈ [2.375, 3.375]`, contributing
/// `+ ln ∏_{j=0}^{i−1}(y−i+j)`; `i < 0` reduces up, contributing `− ln ∏_{j=0}^{|i|−1}(y+j)`.
/// All `|i| ≤ 5` factors are positive (≥ 0.5), so the product cannot overflow and
/// its logarithm is real.  `ln_of` is [`ln_fast_sum`] (fast leg) or [`ln_sum`]
/// (accurate); `i = 0` (already central) contributes nothing.
#[inline]
fn lgamma_recurrence_log(
    y: DoubleDouble,
    i: i64,
    ln_of: impl Fn(DoubleDouble) -> DoubleDouble,
) -> DoubleDouble {
    if i > 0 {
        let yc = y + DoubleDouble {
            high: -(i as f64),
            low: 0.0,
        };
        ln_of(recurrence_product_dd(yc, i))
    } else if i < 0 {
        neg(ln_of(recurrence_product_dd(y, -i)))
    } else {
        ZERO
    }
}

/// `ln Γ(y)` for positive `y` with `y.high < LGAMMA_FAST_CUTOFF`, the central-table
/// fast leg: `ln Γ(2.875 + d)` from [`LGAMMA_TABLE`] plus the recurrence's `ln ∏`
#[inline]
fn lgamma_table_fast(y: DoubleDouble) -> DoubleDouble {
    let (i, d) = lgamma_center_reduce(y);
    cell_eval(&LGAMMA_TABLE, d) + lgamma_recurrence_log(y, i, ln_fast_sum)
}

/// `ln Γ(y)` for positive `y` with `y.high < LGAMMA_FAST_CUTOFF`, the accurate
/// central-table leg: the degree-30 [`LGAMMA_DD`] minimax plus the recurrence's `ln ∏`
#[inline]
fn lgamma_table_dd(y: DoubleDouble) -> DoubleDouble {
    let (i, d) = lgamma_center_reduce(y);
    poly_dd(d, &LGAMMA_DD) + lgamma_recurrence_log(y, i, ln_sum)
}

/// Direct Stirling `ln Γ(y)` for a positive double-double `y` with `y.high ≥ 8`,
/// the lean fast leg (`steps = 0`): the reflection's `ln Γ(1−z)` once `1−z` clears
/// the cutoff
#[inline]
fn lgamma_stirling_dd(y: DoubleDouble) -> DoubleDouble {
    let inv_t = 1.0 / y.high;
    let u = inv_t * inv_t;
    let tail = crate::poly(u, &LGAMMA_TAIL_F64) * inv_t;

    ln_fast_sum(y)
        * (y + DoubleDouble {
            high: -0.5,
            low: 0.0,
        })
        + neg(y)
        + HALF_LN_2PI
        + DoubleDouble {
            high: tail,
            low: 0.0,
        }
}

/// `ln Γ(y)` as a double-double for a positive double-double `y`
///
/// For `y.high < LGAMMA_FAST_CUTOFF` the accurate central table ([`lgamma_table_dd`])
/// reduces in ≤ 5 steps; above it, reduce `y` upward to [`LGAMMA_CUTOFF`] via
/// `ln Γ(y) = ln Γ(t) − ln ∏(y+j)` (the product exact in double-double), then apply
/// Stirling `(t−½)·ln t − t + ½ln(2π) + tail(1/t²)`.  The cutoff is high enough that
/// the Bernoulli tail stays short and well-conditioned (see [`LGAMMA_TAIL_DD`]).
#[inline]
fn lgamma_pos_dd(y: DoubleDouble) -> DoubleDouble {
    // Moderate `y`: the central table reduces in ≤ 5 steps instead of ~40, so the
    // fast leg's rare straddles (where `ln Γ` is O(1)) fall back cheaply.
    if y.high < LGAMMA_FAST_CUTOFF {
        return lgamma_table_dd(y);
    }

    // Number of upward steps to reach the Stirling region, in one shot.  An
    // off-by-one is harmless: the telescoping `ln Γ(t) − ln ∏(y+j) = ln Γ(y)` is
    // exact for *any* `steps` as long as `t = y + steps` is exact and `t.high`
    // clears the cutoff (the Bernoulli tail still converges a step early).
    let steps = (LGAMMA_CUTOFF - y.high).ceil().max(0.0) as i64;
    // `t = y + steps` exactly: the double-double add keeps the low bits a scalar
    // `y.high + steps` would round off once `t` crosses into a higher binade.
    let t = y + DoubleDouble {
        high: steps as f64,
        low: 0.0,
    };

    // tail = P(u)/t with u = 1/t², the Stirling asymptotic series past the leads.
    let inv_t = t.recip();
    let u = inv_t * inv_t;
    let tail = poly_dd(u, &LGAMMA_TAIL_DD) * inv_t;

    // lnΓ(t) = (t−½)·(ln t − 1) − ½ + ½ln(2π) + tail.  Folding the `−t` term into
    // the lead as `(t−½)·(ln t − 1)` keeps the dominant product at the *result*
    // magnitude; the separate `(t−½)·ln t ≈ result + t` would exceed `f64::MAX`
    // (→ ∞, then ∞−∞ = NaN) for `z ≳ 2.56e305`, even though lnΓ(z) is still finite.
    let stirling = (ln_sum(t)
        + DoubleDouble {
            high: -1.0,
            low: 0.0,
        })
        * (t + DoubleDouble {
            high: -0.5,
            low: 0.0,
        })
        + HALF_LN_2PI_M_HALF
        + tail;

    if steps > 0 {
        stirling + neg(ln_sum(recurrence_product_dd(y, steps)))
    } else {
        stirling
    }
}

/// `ln Γ(y)` for positive `y`, the Ziv fast leg, with its absolute error bound
///
/// Below [`LGAMMA_FAST_CUTOFF`] the central table ([`lgamma_table_fast`], ≈2⁻⁶⁷,
/// gate [`LGAMMA_TABLE_ERR`]); above it the lean direct Stirling
/// ([`lgamma_stirling_dd`], ≈2⁻⁵⁸, gate [`LGAMMA_FAST_ERR`]).  The reflection feeds
/// its `1−z` here, so the gate the caller applies tracks which leg ran.
#[inline]
fn lgamma_pos_fast(y: DoubleDouble) -> (DoubleDouble, f64) {
    if y.high < LGAMMA_FAST_CUTOFF {
        (lgamma_table_fast(y), LGAMMA_TABLE_ERR)
    } else {
        (lgamma_stirling_dd(y), LGAMMA_FAST_ERR)
    }
}

/// Direct Stirling `ln Γ(z)` (no recurrence) from a precomputed `f64` `tail`
///
/// The lean leg: `z` (hence `z − ½`) is an exact `f64`, so the big term is a plain
/// `ln_fast(z) · (z − ½)` — a double-double × scalar, no double-double argument add.
/// The caller picks the tail length by `z` (see [`lgamma_fast`]).
///
/// The three closing folds are ordered Fast2Sums ([`DoubleDouble::add_ordered`]):
/// for `z ≥ 8` the lead `(z−½)·ln z ≥ 15.6` dominates each later term (`−z`,
/// `½ln(2π)`, `tail`), and the running sum stays above the next term too — proven
/// in `fold_ordering::lgamma_stirling`.  Skipping the renormalizing `Add` shortens
/// the serial chain that follows `ln_fast` on this hot (`z ≥ 8`) path, where its
/// `≈2⁻¹⁰⁵` slack is far inside the [`LGAMMA_FAST_ERR`] gate.
#[inline]
fn lgamma_stirling_fast(z: f64, tail: f64) -> DoubleDouble {
    (crate::f64_::ln_fast(z) * (z - 0.5))
        .add_ordered(DoubleDouble { high: -z, low: 0.0 })
        .add_ordered(HALF_LN_2PI)
        .add_ordered(DoubleDouble {
            high: tail,
            low: 0.0,
        })
}

/// `ln|Γ(z)|` as a double-double via the lean Ziv fast leg, with its error bound
///
/// Reflects through `ln π − ln|sin πz| − ln Γ(1−z)` for `z < ½` (the gate comes from
/// the [`lgamma_pos_fast`] leg that handles `1−z`; the double-double `|sin πz|` and
/// its `ln_fast` add only <2⁻⁶⁶, well inside that gate).  `[½, 8)` reads the central
/// table; `[8, ∞)` takes the lean direct [`lgamma_stirling_fast`] with the ten-term
/// [`LGAMMA_TAIL_F64`] up to [`LGAMMA_CUTOFF`] = 40 and the cheaper six-term
/// [`LGAMMA_TAIL_F64_FAR`] on the hot `z ≥ 40` tail.  The caller restricts `|z|` to
/// below [`LGAMMA_FAST_BOUND`].
#[inline]
fn lgamma_fast(z: f64) -> (DoubleDouble, f64) {
    if z < 0.5 {
        let (pos, gate) = lgamma_pos_fast(DoubleDouble::from_sum(1.0, -z));
        return (LN_PI + neg(ln_fast_sum(abs_sinpi_dd(z)) + pos), gate);
    }
    if z < LGAMMA_FAST_CUTOFF {
        return (
            lgamma_table_fast(DoubleDouble { high: z, low: 0.0 }),
            LGAMMA_TABLE_ERR,
        );
    }

    let inv = 1.0 / z;
    let u = inv * inv;
    let tail = if z < LGAMMA_CUTOFF {
        crate::poly(u, &LGAMMA_TAIL_F64) * inv
    } else {
        crate::poly(u, &LGAMMA_TAIL_F64_FAR) * inv
    };
    (lgamma_stirling_fast(z, tail), LGAMMA_FAST_ERR)
}

/// `ln|Γ(z)|` as a double-double via the accurate path, the Ziv fallback.
///
/// `#[cold] #[inline(never)]` for the same reason as the f32 `lgamma_dd`: it is
/// the rarely-taken accurate leg, so keeping it out of line stops it from
/// bloating [`lgamma`]'s hot body.
#[cold]
#[inline(never)]
fn lgamma_dd(z: f64) -> DoubleDouble {
    if z < 0.5 {
        // Reflection ln|Γ(z)| = ln π − ln|sin(πz)| − ln Γ(1−z); `1 − z` is exact.
        LN_PI + neg(ln_sum(abs_sinpi_dd(z)) + lgamma_pos_dd(DoubleDouble::from_sum(1.0, -z)))
    } else {
        lgamma_pos_dd(DoubleDouble { high: z, low: 0.0 })
    }
}

/// The natural logarithm of the absolute value of the gamma function
#[must_use]
#[inline]
pub fn lgamma(z: f64) -> f64 {
    if z == 0.0 || z >= LGAMMA_OVERFLOW {
        return f64::INFINITY;
    }
    if z.is_nan() {
        return z;
    }

    // Non-positive integers are poles; Γ(1) = Γ(2) = 1 give the exact zeros.
    if z < 0.5 && z == z.floor() {
        return f64::INFINITY;
    }
    if z == 1.0 || z == 2.0 {
        return 0.0;
    }

    // Ziv two-step: a lean leg (central table or lean Stirling) gated against the
    // accurate double-double path.  The leg returns its own absolute error bound —
    // the tight [`LGAMMA_TABLE_ERR`] in the moderate band, the looser
    // [`LGAMMA_FAST_ERR`] for Stirling.  Restricted to `|z| < LGAMMA_FAST_BOUND`,
    // where those gates certify the leg; either gate also defers a result that
    // cancels toward zero (it then spans many ulps), to the accurate path.
    if z > -LGAMMA_FAST_BOUND && z < LGAMMA_FAST_BOUND {
        let (value, gate) = lgamma_fast(z);
        let lo = value.high + (value.low - gate);
        let hi = value.high + (value.low + gate);
        if lo == hi {
            return lo;
        }
    }

    let value = lgamma_dd(z);
    value.high + value.low
}

#[cfg(test)]
mod fold_ordering {
    use super::*;

    /// The three `add_ordered` folds of [`lgamma_stirling_fast`] each require the
    /// running sum to dominate the term being folded in.  The Stirling lead
    /// `(z−½)·ln z` and every partial sum grow monotonically for `z ≥ 8`, so the
    /// tightest case is the cutoff `z = 8`; sweeping `[8, 1024]` (a superset of
    /// the `[8, LGAMMA_FAST_BOUND]` fast-leg band) confirms it on the real
    /// arithmetic (`ln_fast`, the `f64` tail, the folds).
    #[test]
    fn lgamma_stirling() {
        // z = 8, 8.125, …, 1024 (8128 steps of 1/8 covering the fast-leg band).
        for k in 0..=8128 {
            let z = crate::fast_mul_add(f64::from(k), 0.125, LGAMMA_FAST_CUTOFF);
            let inv = 1.0 / z;
            let tail = crate::poly(inv * inv, &LGAMMA_TAIL_F64) * inv;

            // Fold 1: lead ⊕ (−z) needs |lead.high| ≥ |z|.
            let lead = crate::f64_::ln_fast(z) * (z - 0.5);
            assert!(lead.high.abs() >= z, "fold 1 at z = {z}");

            // Fold 2: (lead − z) ⊕ ½ln(2π) needs |·| ≥ |½ln(2π)|.
            let a1 = lead.add_ordered(DoubleDouble { high: -z, low: 0.0 });
            assert!(a1.high.abs() >= HALF_LN_2PI.high.abs(), "fold 2 at z = {z}");

            // Fold 3: (… + ½ln(2π)) ⊕ tail needs |·| ≥ |tail|.
            let a2 = a1.add_ordered(HALF_LN_2PI);
            assert!(a2.high.abs() >= tail.abs(), "fold 3 at z = {z}");
        }
    }
}

#[cfg(all(test, feature = "mpfr"))]
mod ziv_soundness {
    use super::*;
    use rug::Float;

    fn mix(i: u64) -> u64 {
        let mut z = i.wrapping_mul(0x2545_F491_4F6C_DD1D);
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// The exact double-double value the [`tgamma`] fast leg (table eval through
    /// the recurrence) certifies against [`TGAMMA_ZIV_EPS`], for `z` whose
    /// recurrence needs no rescaling (`e2 == 0` — the only inputs the gate runs on).
    fn fast_leg(z: f64) -> DoubleDouble {
        let (i, d) = tgamma_reduce(z);
        let (value, e2) = tgamma_recurrence(z, i, tgamma_table_eval(d));
        debug_assert_eq!(e2, 0, "fast-leg gate runs only on e2 == 0");
        value
    }

    /// The fast leg's Ziv gate must be *sound*: `TGAMMA_ZIV_EPS` has to exceed the
    /// fast leg's true worst-case relative error with margin, or a confident
    /// `lo == hi` could certify a value on the wrong side of a rounding boundary
    /// (exactly the erf bug this mirrors).  Sweep the active band `(−100, 171.6)`
    /// where the recurrence stays rescale-free (`e2 == 0`), skipping the poles and
    /// the tiny-`z` 1/z overflow corner, comparing the un-rounded fast-leg pair to
    /// a 250-bit MPFR `Γ`.
    #[test]
    fn tgamma_fast_leg_is_sound() {
        // Cover the whole rescale-free range with margin: `i = round(z − 2.875)`
        // and `|i| ≤ TGAMMA_DOWNWARD_DIRECT` downward keeps `e2 == 0`, i.e.
        // `z > 2.875 − 100`.  Stay just inside for safety.
        let (lo, hi) = ((-97.0f64).to_bits(), 171.6f64.to_bits());
        let mut worst = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..300_000u64 {
            let b = lo.wrapping_add(mix(k) % hi.wrapping_sub(lo));
            let z = f64::from_bits(b);
            // Skip non-positive integers (poles) and the near-pole / tiny-z humps
            // where Γ spans signed zeros or the 1/z corner overflows — those never
            // reach the gate (handled by the special-case ladder).
            if z <= 0.0 && (z - z.round()).abs() < 1.0 / 64.0 {
                continue;
            }
            if z.abs() < 1.0 / 1024.0 {
                continue;
            }
            let e = fast_leg(z);
            if !e.high.is_finite() || e.high == 0.0 {
                continue;
            }
            let got = Float::with_val(250, e.high) + Float::with_val(250, e.low);
            let truth = Float::with_val(250, z).gamma();
            if truth == 0.0 || !truth.is_finite() {
                continue;
            }
            let rel = (Float::with_val(250, &got - &truth).abs() / truth.abs()).to_f64();
            if rel > worst {
                worst = rel;
                worst_x = z;
            }
        }
        println!(
            "tgamma fast leg: worst rel error 2^{:.2} at z={worst_x:e}; eps = 2^{:.2}",
            worst.log2(),
            TGAMMA_ZIV_EPS.log2()
        );
        assert!(
            TGAMMA_ZIV_EPS > 2.0 * worst,
            "TGAMMA_ZIV_EPS = 2^{:.2} does not cover the fast leg's 2^{:.2}",
            TGAMMA_ZIV_EPS.log2(),
            worst.log2()
        );
    }
}

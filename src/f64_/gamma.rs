const TGAMMA_STIRLING_TAIL_REST: [f64; 13] = [
    -0.002777777777777778,
    0.0007936507936507937,
    -0.0005952380952380953,
    0.0008417508417508417,
    -0.0019175269175269176,
    0.00641025641025641,
    -0.029550653594771242,
    0.17964437236883057,
    -1.3924322169059011,
    13.402864044168393,
    -156.84828462600203,
    2193.1033333333335,
    -36108.77125372499,
];

/// `∏_{m=0}^{n−1} (z + first + step·m)` as a double-double, on four parallel lanes
///
/// The `tgamma` recurrence products: upward `(z−1)(z−2)…(z−n)` is `first = step =
/// −1`, downward `z(z+1)…(z+n−1)` is `first = 0`, `step = 1`.  Each factor
/// `from_sum(z, …)` is exact (one 2Sum, `z` being a plain `f64`); four lanes cut
/// the dependency chain from `n` to `≈n/4` double-double multiplies, the
/// long-latency cost of the far-from-centre range.  The caller keeps `n` small
/// enough (all factors > 1 upward; [`TGAMMA_DOWNWARD_DIRECT`] downward) that the
/// product cannot overflow.
#[inline]
fn recurrence_product_z(z: f64, first: i64, step: i64, n: i64) -> DoubleDouble {
    let factor = |m: i64| DoubleDouble::from_sum(z, (first + step * m) as f64);

    let mut p = [ONE; 4];
    let mut m = 0;
    while m + 4 <= n {
        p[0] = p[0] * factor(m);
        p[1] = p[1] * factor(m + 1);
        p[2] = p[2] * factor(m + 2);
        p[3] = p[3] * factor(m + 3);
        m += 4;
    }
    while m < n {
        p[0] = p[0] * factor(m);
        m += 1;
    }
    (p[0] * p[1]) * (p[2] * p[3])
}

/// Reduce `z` for the recurrence: `(i, zr)` with `zr = z − i` the absolute argument
/// the wide [`TGAMMA_TABLE`] evaluates and `Γ(z) = Γ(zr) · ∏`.
///
/// For `z ∈ [2, 8)` (the wide table's band — `z ≥ 8` already took the Stirling leg)
/// `i = 0` and `zr = z`, so [`tgamma_table_eval`] reads `Γ(z)` directly with **no
/// recurrence**.  Below `2` the recurrence reduces up by `i = round(z − 2.875) < 0`
/// to `zr = z − i ∈ [2.375, 3.375]`; `zr` is exact via `from_sum` (`−i = |i|` a
/// positive integer) so `z`'s low bits survive in `zr.low`.
#[inline]
fn tgamma_reduce(z: f64) -> (f64, DoubleDouble) {
    if (2.0..TGAMMA_TABLE_HI).contains(&z) {
        return (0.0, DoubleDouble { high: z, low: 0.0 });
    }
    // Below 2 the recurrence reduces up; a `z ≥ 8` that fell through the Stirling
    // Ziv gate (≈0.8% of that band) reduces down.  Either way land in `[2.375,
    // 3.375]` (still inside the wide table) by `i = round(z − 2.875)`, exact via
    // `from_sum` (`−i` an integer); `Γ(z) = Γ(z − i) · ∏` with the recurrence
    // running upward (`i > 0`, the `z ≥ 8` miss) or downward (`i < 0`, `z < 2`).
    let i = (z - TGAMMA_CENTER).round_ties_even();
    (i, DoubleDouble::from_sum(z, -i))
}

/// Per-cell minimax of a tabulated `Γ`/`ln Γ` at the cell-local argument
/// `h ∈ [−1/16, 1/16]` (`h.high` exact on the `1/8` grid, `h.low` the reduction's
/// surviving low word) — the evaluator shared by the wide `Γ` table
/// ([`tgamma_table_eval`]) and the `ln Γ` central table ([`cell_eval`]).
///
/// The `c4..c11` tail sums in `f64` (small relative to the result), then the
/// `c3..c0` leads fold in double-double — a few double-double FMAs versus the
/// accurate polynomial.  `h` keeps its low word through the leads: `c1·h.low`
/// alone can reach 2⁻⁵⁴, far above the leg's budget.
///
/// `h.low` correction: positive (non-reflection) inputs reduce exactly, so
/// `h.low = 0` and it vanishes — the whole `Γ` table path (`tgamma` over `[2, 8)`)
/// and the positive `ln Γ` band hit this branch, skipping the derivative entirely.
/// A reduced or reflection argument carries `h.low ≲ 2⁻⁵¹`, shifting `P` by
/// `P′(h)·h.low`.  `P′(h) ≈ c1 + h·(2c2 + 3h·c3)` in `f64` is ample — its rounding
/// rides `h.low` down to ≲2⁻⁶⁸, well inside the gate (the dropped `4c4·h³·h.low` is
/// ≲2⁻⁷⁰).  The branch is value-consistent within a magnitude band, so it predicts
/// perfectly.
#[inline]
fn eval_cell(cell: &GammaCell, h: DoubleDouble) -> DoubleDouble {
    // `z` is the cell-local argument, exact.  Carry it as a plain `f64`, so the
    // Horner leads fold with dd × f64 multiplies (CORE-MATH's `polydddfst`) rather
    // than the dd × dd a dd argument would force, and with the magnitude-ordered
    // Fast2Sum: each `|cₖ|` dominates its `acc·z` (|z| ≤ 1/16), the same ordering
    // the corpus certifies.
    let z = h.high;

    // P(z) = c0 + z·(c1 + z·(c2 + z·(c3 + z·tail))), tail = c4 + c5·z + … in f64.
    let tail = crate::poly(z, &cell.tail);
    let acc = cell.c3.add_ordered(DoubleDouble {
        high: z * tail,
        low: 0.0,
    });
    let acc = cell.c2.add_ordered(acc * z);
    let acc = cell.c1.add_ordered(acc * z);
    let value = cell.c0.add_ordered(acc * z);

    if h.low == 0.0 {
        return value;
    }
    let deriv = crate::fast_mul_add(
        z,
        crate::fast_mul_add(z, 3.0 * cell.c3.high, 2.0 * cell.c2.high),
        cell.c1.high,
    );
    DoubleDouble {
        high: value.high,
        low: crate::fast_mul_add(deriv, h.low, value.low),
    }
}

/// A per-cell minimax `ln Γ(2.875 + d)` for `d ∈ [−½, ½]` from the 9-cell `ln Γ`
/// central [`LGAMMA_TABLE`]: `fi = round(8·d)` picks the sub-cell, then
/// [`eval_cell`] evaluates it.  The sub-cell argument `d.high − fi/8` is
/// Sterbenz-exact and `d.low` rides along.
#[inline]
fn cell_eval(table: &[GammaCell; 9], d: DoubleDouble) -> DoubleDouble {
    let fi = (d.high * 8.0).round_ties_even();
    // SAFETY: d.high ∈ [−½, ½] ⇒ fi ∈ [−4, 4].
    let cell = &table[(unsafe { fi.to_int_unchecked::<i64>() } + 4) as usize];
    eval_cell(
        cell,
        DoubleDouble {
            high: d.high - fi * 0.125,
            low: d.low,
        },
    )
}

/// `Γ(z)` for `z ∈ [2, 8)` straight from the wide recurrence-free [`TGAMMA_TABLE`]
/// — the `Γ` fast leg.  `k = round(8·z)` indexes the cell centred at `k/8`; the
/// cell-local argument `z − k/8 ∈ [−1/16, 1/16]` is Sterbenz-exact (`z`, `k/8`
/// within `1/16`, both `≥ 2`), and `z`'s low word — nonzero only when the
/// recurrence fed a reduced argument — rides along in `zr.low`.
#[inline]
fn tgamma_table_eval(zr: DoubleDouble) -> DoubleDouble {
    let kf = (zr.high * 8.0).round_ties_even();
    // SAFETY: zr.high ∈ [2, 8) ⇒ 8·zr.high ∈ [16, 64] ⇒ k ∈ 16..=64.
    let k = unsafe { kf.to_int_unchecked::<i64>() };
    let cell = &TGAMMA_TABLE[(k - TGAMMA_TABLE_KLO) as usize];
    eval_cell(
        cell,
        DoubleDouble {
            high: zr.high - kf * 0.125,
            low: zr.low,
        },
    )
}

/// Walk the recurrence from `value = Γ(z − i)` to `(value, e2)` with
/// `Γ(z) = value · 2`<sup>`e2`</sup>
///
/// Both products run on the parallel-lane [`recurrence_product_z`].  Upward
/// (`i > 0`) the partial products stay below the final `Γ(z)`, so no scaling is
/// needed; downward (`i < 0`) a short divisor (≤ [`TGAMMA_DOWNWARD_DIRECT`]) also
/// fits, while a deep one is accumulated serially and rescaled by `2⁵¹²` whenever
/// it grows large, with the total folded into `e2`.
#[inline]
fn tgamma_recurrence(z: f64, i: f64, value: DoubleDouble) -> (DoubleDouble, i64) {
    // SAFETY-free: `|i|` is a small integer (`z` is finite and bounded by the
    // overflow/underflow guards), so the casts below are exact.
    let steps = i.abs() as i64;

    if i > 0.0 {
        // Γ(z) = Γ(z−i)·(z−1)(z−2)…(z−i); every factor `from_sum(z, −k)` is exact
        // and > 1, so the product never overflows and needs no rescaling.
        (value * recurrence_product_z(z, -1, -1, steps), 0)
    } else if i < 0.0 && steps <= TGAMMA_DOWNWARD_DIRECT {
        // Γ(z) = Γ(z−i)/[z(z+1)…(z+|i|−1)].  Short divisor: no overflow, so form it
        // on parallel lanes and divide.
        (value * recurrence_product_z(z, 0, 1, steps).recip(), 0)
    } else if i < 0.0 {
        // Deep negative z: the long divisor product would overflow, so accumulate
        // it serially, carrying a binary exponent folded into the result scale.
        let mut product = DoubleDouble { high: z, low: 0.0 };
        let mut e2: i64 = 0;
        let mut k = 0.0;
        for _ in 1..steps {
            k += 1.0;
            product = product * DoubleDouble::from_sum(z, k);
            if product.high.abs() > PRODUCT_RESCALE {
                product = DoubleDouble {
                    high: fast_ldexp(product.high, -512),
                    low: fast_ldexp(product.low, -512),
                };
                e2 += 512;
            }
        }
        (value * product.recip(), -e2)
    } else {
        (value, 0)
    }
}

/// Walk the recurrence in **triple-double** from `value = Γ(z − i)` to
/// `(value, e2)` with `Γ(z) = value · 2`<sup>`e2`</sup> — the lifted accurate
/// path's analogue of [`tgamma_recurrence`].
///
/// Same three cases (upward product, short downward divide, deep downward serial
/// rescale), each in triple-double via [`recurrence_product_z_td`] / [`td_recip`].
#[inline]
fn tgamma_recurrence_td(z: f64, i: f64, value: TripleDouble) -> (TripleDouble, i64) {
    let steps = i.abs() as i64;

    if i > 0.0 {
        (td_mul(value, recurrence_product_z_td(z, -1, -1, steps)), 0)
    } else if i < 0.0 && steps <= TGAMMA_DOWNWARD_DIRECT {
        (
            td_mul(value, td_recip(recurrence_product_z_td(z, 0, 1, steps))),
            0,
        )
    } else if i < 0.0 {
        let mut product = TripleDouble {
            high: z,
            mid: 0.0,
            low: 0.0,
        };
        let mut e2: i64 = 0;
        let mut k = 0.0;
        for _ in 1..steps {
            k += 1.0;
            product = dd_mul_td(DoubleDouble::from_sum(z, k), product);
            if product.high.abs() > PRODUCT_RESCALE {
                product = TripleDouble {
                    high: fast_ldexp(product.high, -512),
                    mid: fast_ldexp(product.mid, -512),
                    low: fast_ldexp(product.low, -512),
                };
                e2 += 512;
            }
        }
        (td_mul(value, td_recip(product)), -e2)
    } else {
        (value, 0)
    }
}

/// `lnΓ(z)` as a double-double for `z ≥ TGAMMA_STIRLING_CUTOFF`, the input to the
/// `Γ = exp(lnΓ)` fast leg.
///
/// The Stirling assembly `lnΓ = (z−½)·ln z − z + ½ln(2π) + tail(z)`, the same
/// shape as [`lgamma_stirling_fast`] (the lean [`ln_fast`], not the heavy accurate
/// `ln_dd`, keeps the leg fast).  Its absolute error is dominated by
/// `(z−½)·δ_ln ≤ (z−½)·2⁻⁶⁶` from `ln_fast`'s slack — `z`-dependent, which is why
/// the caller's gate ([`tgamma_stirling_ziv_rel`]) scales with `z`.  The one
/// refinement the `Γ` budget needs over `lgamma`'s leg is the leading tail term
/// `1/(12z)` in double-double ([`TWELFTH`] × the reciprocal): the only term large
/// enough (≈2⁻⁷ of the reduced argument) that its `f64` rounding (≈2⁻⁵⁹) would
/// otherwise dominate `ln_fast`'s contribution.  The remaining tail terms are
/// ≲2⁻¹⁷ of the result and round in `f64`.
///
/// The three closing folds are ordered Fast2Sums: for `z ≥ 8` the lead
/// `(z−½)·ln z ≥ 15.6` dominates `−z`, `½ln(2π)`, and `tail`, and each running sum
/// stays above the next term — the same ordering `fold_ordering::lgamma_stirling`
/// proves for the `lgamma` leg.
#[inline]
fn tgamma_lngamma_stirling(z: f64) -> DoubleDouble {
    let inv = DoubleDouble::from_quotient(1.0, z);
    let u = inv.high * inv.high;
    // tail = 1/(12z) + (1/z)·Σ_{k≥2} cₖ·u^(k−1).  Leading term in double-double,
    // the rest (≲2⁻¹⁷ of the result) in plain f64.
    let tail = (inv * TWELFTH).add_ordered(DoubleDouble {
        high: inv.high * (u * crate::poly(u, &TGAMMA_STIRLING_TAIL_REST)),
        low: 0.0,
    });

    (crate::f64_::ln_fast(z) * (z - 0.5))
        .add_ordered(DoubleDouble { high: -z, low: 0.0 })
        .add_ordered(HALF_LN_2PI)
        .add_ordered(tail)
}

/// `Γ(z) = exp(lnΓ(z))` for large positive `z`, the O(1) Stirling fast leg.
///
/// Returns the un-normalized mantissa pair (in `[1, 2)`) and binary exponent `q`
/// with `Γ(z) = mantissa · 2`<sup>`q`</sup>, for the caller's `z`-scaled Ziv gate
/// ([`tgamma_stirling_ziv_rel`]).  The relative error is `lnΓ`'s
/// `≈(z−½)·2⁻⁶⁶` absolute slack plus [`exp_dd_of_dd_fast`]'s ≈2⁻⁶⁸; on the rare
/// miss the caller falls through to the recurrence leg (not straight to the
/// triple-double accurate path).
#[inline]
fn tgamma_stirling_fast(z: f64) -> (DoubleDouble, i64) {
    super::exp::exp_dd_of_dd_fast(tgamma_lngamma_stirling(z))
}

/// The gamma function
#[must_use]
#[inline]
pub fn tgamma(z: f64) -> f64 {
    if z.is_nan() {
        return z;
    }
    if z == f64::INFINITY {
        return f64::INFINITY;
    }

    // Γ(±0) = ±∞, and Γ(z) ≈ 1/z overflows for |z| at or below `TGAMMA_TINY`
    // (= 2⁻¹⁰²⁴): Γ(±2⁻¹⁰²⁴) ≈ 2¹⁰²⁴ rounds to ±∞, while the next subnormal up is
    // finite (≈f64::MAX).  Must be `<=`, not `<`: the boundary itself overflows,
    // and falling through to the recurrence there returned a bogus `2.0`.
    if z.abs() <= TGAMMA_TINY {
        return f64::INFINITY.copysign(z);
    }

    // Γ exceeds `f64::MAX` past `TGAMMA_OVERFLOW`; bail before the recurrence loop.
    if z >= TGAMMA_OVERFLOW {
        return f64::INFINITY;
    }

    // Non-positive integers are poles; below `TGAMMA_UNDERFLOW` every hump rounds
    // to a signed zero (sign alternating with each pole).
    if z < 0.0 {
        if z == z.floor() {
            return f64::NAN;
        }
        if z <= TGAMMA_UNDERFLOW {
            return if (z.floor() as i64) & 1 == 0 {
                0.0
            } else {
                -0.0
            };
        }
    }

    // Large positive `z`: skip the O(z) recurrence for the O(1) Stirling leg
    // `Γ = exp(lnΓ)`.  The result is comfortably normal (`Γ(8) = 5040`), so no
    // subnormal handling is needed — just a `z`-scaled relative Ziv gate on the
    // `[1, 2)` mantissa, then an exact `2`<sup>`q`</sup> scale.  On the rare miss
    // (≈1%) the leg falls through to the recurrence path below, whose tighter
    // `2⁻⁶²` gate resolves nearly all of them at ≈O(z) cost — far cheaper than
    // jumping straight to the degree-38 triple-double [`tgamma_accurate`].
    if z >= TGAMMA_STIRLING_CUTOFF {
        let (m, q) = tgamma_stirling_fast(z);
        let err = m.high * tgamma_stirling_ziv_rel(z);
        let lo = m.high + (m.low - err);
        let hi = m.high + (m.low + err);
        if lo == hi {
            return fast_ldexp(lo, q);
        }
    }

    // Reduce once into `[2.375, 3.375]`; both legs share the recurrence.
    let (i, d) = tgamma_reduce(z);

    // Ziv two-step: the table leg is correctly rounded for a comfortably-normal
    // result unless it straddles a boundary, where the double-double path resolves
    // it.  Scaled (`e2 ≠ 0`) and near-subnormal results go straight to the accurate
    // path, whose `round_general_signed64` handles the subnormal grid.
    let (value, e2) = tgamma_recurrence(z, i, tgamma_table_eval(d));
    if e2 == 0 {
        let err = value.high.abs() * TGAMMA_ZIV_EPS;
        let lo = value.high + (value.low - err);
        let hi = value.high + (value.low + err);
        if lo == hi && lo.abs() >= f64::MIN_POSITIVE * 2.0 {
            return lo;
        }
    }

    tgamma_accurate(z)
}

/// The accurate **triple-double** leg of [`tgamma`], reached only when the table
/// leg's Ziv test fails to certify a correctly-rounded result.  Outlined as
/// `#[cold] #[inline(never)]` — the degree-38 [`TGAMMA_TD`] evaluation through
/// [`poly_td`] plus the triple-double recurrence is bulky and almost never taken,
/// so inlining it would only bloat the hot path.
///
/// Lifted from double-double to triple-double (≈2⁻¹³⁵) because the double-double
/// recurrence degraded to ≈2⁻⁹⁹, straddling the corpus's ≈2⁻⁶⁰ near-ties (see the
/// triple-double section); the lift clears them all with a > 70-bit margin.
#[cold]
#[inline(never)]
fn tgamma_accurate(z: f64) -> f64 {
    // The accurate path keeps the centred reduction: the degree-38 [`TGAMMA_TD`]
    // minimax is valid only on `[−½, ½]` about 2.875, so it cannot take the wide
    // table's absolute argument — it reduces `z` into `[2.375, 3.375]` and walks the
    // triple-double recurrence (which may run upward, `i > 0`, unlike the fast leg).
    let (i, d) = tgamma_reduce_center(z);
    let (value, e2) = tgamma_recurrence_td(z, i, poly_td(dd_to_td(d), &TGAMMA_TD));
    round_td_signed64(value, e2)
}

/// Reduce `z` into `[2.375, 3.375]` for the **accurate** path: `(i, d)` with
/// `d = z − (2.875 + i) ∈ [−½, ½]` the relative argument the degree-38
/// [`TGAMMA_TD`] minimax evaluates, and `Γ(z) = Γ(2.875 + d) · ∏`.  `d` is exact
/// via `from_sum` (`2.875 + i` is exact for any integer `i`).
#[inline]
fn tgamma_reduce_center(z: f64) -> (f64, DoubleDouble) {
    let i = (z - TGAMMA_CENTER).round_ties_even();
    (i, DoubleDouble::from_sum(z, -(TGAMMA_CENTER + i)))
}

/// Natural logarithm of a positive double-double, as a double-double.
///
/// `ln(s) = ln(s.high) + ln(1 + s.low/s.high) ≈ ln_fast(s.high) + s.low/s.high` —
/// the Ziv fast leg's log (the accurate path uses the triple-double [`ln_sum_td`]).
#[inline]
fn ln_fast_sum(s: DoubleDouble) -> DoubleDouble {
    crate::f64_::ln_fast(s.high)
        + DoubleDouble {
            high: s.low / s.high,
            low: 0.0,
        }
}

/// `∏_{j=0}^{n−1}(y + j)` as a double-double, on four parallel lanes (`n ≥ 1`)
///
/// Each factor `y + j` is formed by a double-double add so it is exact even when
/// `y.high + j` rounds (`y.high ≈ 1`, `j ≈ 40`: the bottom bits of `y.high` fall
/// off the high word and are caught in the low word — exactly what the serial
/// `t + 1` recurrence preserved).  The only added error is the reassociation
/// across lanes, a few `2⁻¹⁰⁵` ulps.  Four lanes cut the dependency chain from `n`
/// to `≈n/4` double-double multiplies, the long-latency cost that dominates the
/// reduced `lgamma` range; the same trick as `f32`'s `recurrence_product`.
#[inline]
fn recurrence_product_dd(y: DoubleDouble, n: i64) -> DoubleDouble {
    let factor = |j: i64| {
        y + DoubleDouble {
            high: j as f64,
            low: 0.0,
        }
    };

    let mut p = [ONE; 4];
    let mut j = 0;
    while j + 4 <= n {
        p[0] = p[0] * factor(j);
        p[1] = p[1] * factor(j + 1);
        p[2] = p[2] * factor(j + 2);
        p[3] = p[3] * factor(j + 3);
        j += 4;
    }
    while j < n {
        p[0] = p[0] * factor(j);
        j += 1;
    }
    (p[0] * p[1]) * (p[2] * p[3])
}

/// Reduce positive `y` (with `y.high < LGAMMA_FAST_CUTOFF`) onto the central cell:
/// `(i, d)` with `d = y − (LGAMMA_CENTER + i)` exact, `|d.high| ≤ ½`
///
/// `i = round(y.high − 2.875) ∈ [−2, 5]`.  `2.875 + i` is exact, and
/// `|y.high − (2.875+i)| ≤ ½ ≪ y.high`, so the double-double subtract loses nothing
/// (the high word is Sterbenz-exact, `y.low` folds into the normalized low).
#[inline]
fn lgamma_center_reduce(y: DoubleDouble) -> (i64, DoubleDouble) {
    let fi = (y.high - LGAMMA_CENTER).round_ties_even();
    // SAFETY: y.high ∈ [½, 8) ⇒ y.high − 2.875 ∈ [−2.375, 5.125) ⇒ fi ∈ [−2, 5].
    let i = unsafe { fi.to_int_unchecked::<i64>() };
    let d = y + DoubleDouble {
        high: -(LGAMMA_CENTER + fi),
        low: 0.0,
    };
    (i, d)
}

/// `ln ∏` of the recurrence factors that carry the central cell back to `y`
///
/// `i > 0` reduces `y` down to `y − i ∈ [2.375, 3.375]`, contributing
/// `+ ln ∏_{j=0}^{i−1}(y−i+j)`; `i < 0` reduces up, contributing `− ln ∏_{j=0}^{|i|−1}(y+j)`.
/// All `|i| ≤ 5` factors are positive (≥ 0.5), so the product cannot overflow and
/// its logarithm is real.  `ln_of` is [`ln_fast_sum`] (the fast leg's log); the
/// accurate path uses the triple-double [`lgamma_recurrence_log_td`].  `i = 0`
/// (already central) contributes nothing.
#[inline]
fn lgamma_recurrence_log(
    y: DoubleDouble,
    i: i64,
    ln_of: impl Fn(DoubleDouble) -> DoubleDouble,
) -> DoubleDouble {
    if i > 0 {
        let yc = y + DoubleDouble {
            high: -(i as f64),
            low: 0.0,
        };
        ln_of(recurrence_product_dd(yc, i))
    } else if i < 0 {
        neg(ln_of(recurrence_product_dd(y, -i)))
    } else {
        ZERO
    }
}

/// `ln Γ(y)` for positive `y` with `y.high < LGAMMA_FAST_CUTOFF`, the central-table
/// fast leg: `ln Γ(2.875 + d)` from [`LGAMMA_TABLE`] plus the recurrence's `ln ∏`
#[inline]
fn lgamma_table_fast(y: DoubleDouble) -> DoubleDouble {
    let (i, d) = lgamma_center_reduce(y);
    cell_eval(&LGAMMA_TABLE, d) + lgamma_recurrence_log(y, i, ln_fast_sum)
}

/// Relative + absolute Ziv slack for the [`lgamma_piecewise`] leg, CORE-MATH's
/// `fabs(fh)*8.3e-20 + 1e-24` (≈2⁻⁶³·⁵ relative, 2⁻⁷⁹·⁷ absolute).
const LGAMMA_PIECE_REL: f64 = 8.3e-20;
const LGAMMA_PIECE_ABS: f64 = 1e-24;

/// Ziv slack for the reflection leg's `ln|sin πz|` term: a relative part plus an
/// **absolute floor**.
///
/// [`ln_fast`](crate::f64_::ln_fast)'s error on `ln|sin πz|` is ≈2⁻⁶⁶ relative away
/// from 1, but near a half-integer `z` (where `sin πz → 1`) the result shrinks while
/// the *absolute* error stays ≈2⁻⁶⁶·⁹ — so a purely relative gate underbudgets it
/// there.  `|ln|sin πz||·2⁻⁶⁵` covers the relative regime and `LGAMMA_REFLECT_SIN_ABS`
/// the near-1 floor (each ≈2× the measured worst, negligible vs `ulp` of the result).
const LGAMMA_REFLECT_SIN_REL: f64 = crate::exp2i(-65);
const LGAMMA_REFLECT_SIN_ABS: f64 = crate::exp2i(-65);

/// Select the [`LGAMMA_PIECE_OFFS`] region for `ax ∈ [0.5, 8.29541]` — a 1:1 port of
/// CORE-MATH's quadratic hash on the exponent-and-top-mantissa key
/// `au = (|x|.to_bits() << 1) >> 38`, with the one-step boundary correction.
#[inline]
fn lgamma_piece_region(ax: f64) -> usize {
    let au = ((ax.to_bits() << 1) >> 38) as u32;
    let ou = au.wrapping_sub(LGAMMA_PIECE_BORDERS[0]);
    // The multiply `ou*0x150d` is a deliberate 32-bit wrap (matching C's `unsigned`),
    // then the rest of the hash runs in 64 bits.
    let t32 = ou.wrapping_mul(0x150d) as u64;
    let m = (0x1_57ce_d865_u64.wrapping_sub(t32))
        .wrapping_mul(u64::from(ou))
        .wrapping_add(0x1280_0000_0000)
        >> 45;
    let j = m as usize;
    j - usize::from(au < LGAMMA_PIECE_BORDERS[j])
}

/// `ln Γ(y)` for positive `y.high ∈ [0.5, 8)` straight from the **recurrence-free**
/// CORE-MATH piecewise table ([`LGAMMA_PIECE_CH`]/[`LGAMMA_PIECE_CL`]), with its
/// relative+absolute Ziv slack.
///
/// Replaces the central-cell table plus the `ln ∏` recurrence: a single degree-12
/// minimax per region (`c0..c4` double-double, `c5..c12` plain `f64`), with the
/// roots at `y = 1` (region 4) and `y = 2` (region 10) factored out as `(1 − y)`
/// resp. `(y − 2)` so the tiny value there carries no cancellation.  The argument's
/// low word (the reflection's `1 − z`) folds back through the polynomial derivative
/// (see the body) rather than into the cell-local `z` directly.
#[inline]
fn lgamma_piecewise(y: DoubleDouble) -> (DoubleDouble, f64) {
    let ax = y.high;
    let j = lgamma_piece_region(ax);
    let cell = &LGAMMA_PIECE_CH[j];
    // `ax − off` is Sterbenz-exact (`off` within the region).  CORE-MATH folds the
    // argument's low word straight into this plain `z`, but it only ever feeds an
    // exact `|x|`; metallic's reflection feeds a `1 − z` whose `y.low` (≲2⁻⁵³) can
    // exceed `ulp(z)`, so the plain fold would drop its low bits.  Keep `z` exact and
    // fold `y.low` back through the polynomial derivative `P′(z)·y.low` (a
    // renormalizing `DoubleDouble` add — the correction can dwarf the low word near a
    // root), the same first-order trick [`cell_eval`] uses.
    let z = ax - LGAMMA_PIECE_OFFS[j];
    let tail = z * crate::poly(z, &LGAMMA_PIECE_CL[j]);
    let (fh, fl) = c_polydddfst(z, cell, (tail, 0.0));
    let deriv = crate::fast_mul_add(
        z,
        crate::fast_mul_add(
            z,
            crate::fast_mul_add(z, 4.0 * cell[4].high, 3.0 * cell[3].high),
            2.0 * cell[2].high,
        ),
        cell[1].high,
    );
    let value = DoubleDouble { high: fh, low: fl }
        + DoubleDouble {
            high: deriv * y.low,
            low: 0.0,
        };
    // Roots at `y = 1` (region 4) / `y = 2` (region 10): factor the tiny value out as
    // the *double-double* `1 − y` / `y − 2` (whose low word carries the rest of the
    // reflection's `1 − z`) so it carries no cancellation.
    let value = if j == 4 {
        value * (ONE + neg(y))
    } else if j == 10 {
        value
            * (y + DoubleDouble {
                high: -2.0,
                low: 0.0,
            })
    } else {
        value
    };
    (
        value,
        crate::fast_mul_add(value.high.abs(), LGAMMA_PIECE_REL, LGAMMA_PIECE_ABS),
    )
}

/// Direct Stirling `ln Γ(y)` for a positive double-double `y` with `y.high ≥ 8`,
/// the lean fast leg (`steps = 0`): the reflection's `ln Γ(1−z)` once `1−z` clears
/// the cutoff
#[inline]
fn lgamma_stirling_dd(y: DoubleDouble, inv_t: f64) -> DoubleDouble {
    let u = inv_t * inv_t;
    let tail = crate::poly(u, &LGAMMA_TAIL_F64) * inv_t;

    // Lean Stirling on the `f64` high word (the positive leg's
    // [`lgamma_stirling_fast`] body: `ln_fast`, not `ln_fast_sum`'s division, and
    // `add_ordered` folds), then fold `y.low` back as a first-order
    // `lnΓ′(y)·y.low = digamma(y)·y.low` correction — `digamma(y) ≈ ln y − 1/(2y) −
    // 1/(12y²)` — instead of threading the double-double `y` through the log and the
    // renormalizing `Add`s.  The dropped `O(y.low²)` and `−1/(120y⁴)·y.low` terms are
    // ≲2⁻⁶⁰, inside the [`lgamma_stirling_ziv`] gate.
    let lw = crate::f64_::ln_fast(y.high);
    let base = (lw * (y.high - 0.5))
        .add_ordered(DoubleDouble {
            high: -y.high,
            low: 0.0,
        })
        .add_ordered(HALF_LN_2PI)
        .add_ordered(DoubleDouble {
            high: tail,
            low: 0.0,
        });
    let digamma = lw.high - inv_t * crate::fast_mul_add(u, 1.0 / 12.0, 0.5);
    DoubleDouble {
        high: base.high,
        low: crate::fast_mul_add(digamma, y.low, base.low),
    }
}

/// `ln Γ(y)` for positive `y`, the Ziv fast leg, with its absolute error bound
///
/// Below [`LGAMMA_FAST_CUTOFF`] the central table ([`lgamma_table_fast`], ≈2⁻⁶⁷,
/// gate [`LGAMMA_TABLE_ERR`]); above it the lean direct Stirling
/// ([`lgamma_stirling_dd`], `t`-scaled gate [`lgamma_stirling_ziv`]).  The
/// reflection feeds its `1−z` here, so the gate the caller applies tracks which
/// leg ran.
#[inline]
fn lgamma_pos_fast(y: DoubleDouble) -> (DoubleDouble, f64) {
    if y.high < LGAMMA_FAST_CUTOFF {
        (lgamma_table_fast(y), LGAMMA_TABLE_ERR)
    } else {
        let inv_t = 1.0 / y.high;
        (
            lgamma_stirling_dd(y, inv_t),
            lgamma_stirling_ziv(y.high, inv_t),
        )
    }
}

/// Direct Stirling `ln Γ(z)` (no recurrence) from a precomputed `f64` `tail`
///
/// The lean leg: `z` (hence `z − ½`) is an exact `f64`, so the big term is a plain
/// `ln_fast(z) · (z − ½)` — a double-double × scalar, no double-double argument add.
/// The caller picks the tail length by `z` (see [`lgamma_fast`]).
///
/// The three closing folds are ordered Fast2Sums ([`DoubleDouble::add_ordered`]):
/// for `z ≥ 8` the lead `(z−½)·ln z ≥ 15.6` dominates each later term (`−z`,
/// `½ln(2π)`, `tail`), and the running sum stays above the next term too — proven
/// in `fold_ordering::lgamma_stirling`.  Skipping the renormalizing `Add` shortens
/// the serial chain that follows `ln_fast` on this hot (`z ≥ 8`) path, where its
/// `≈2⁻¹⁰⁵` slack is far inside the [`lgamma_stirling_ziv`] gate.
#[inline]
fn lgamma_stirling_fast(z: f64, tail: f64) -> DoubleDouble {
    (crate::f64_::ln_fast(z) * (z - 0.5))
        .add_ordered(DoubleDouble { high: -z, low: 0.0 })
        .add_ordered(HALF_LN_2PI)
        .add_ordered(DoubleDouble {
            high: tail,
            low: 0.0,
        })
}

/// `ln Γ(z)` for `z` within [`LGAMMA_ROOT_WINDOW`] of a root (`z ≈ 1` or `z ≈ 2`),
/// the root-anchored fast leg with its *relative* Ziv gate; `None` off the windows
///
/// At the roots `ln Γ → 0`, so the central-table leg's *absolute*
/// [`LGAMMA_TABLE_ERR`] gate dwarfs the tiny result and never certifies — every
/// such input falls to the ~3700 ns triple-double path.  The result-anchored
/// series `ln Γ(1+x) = Σ cₖ xᵏ` (resp. `ln Γ(2+x)`) carries that small value with
/// no cancellation (the linear term dominates); evaluated in double-double it is
/// ≈2⁻¹⁰⁰ relative, so [`LGAMMA_ROOT_ZIV_REL`] times `|value|` certifies it.
/// `x = z − 1` (resp. `z − 2`) is exact by Sterbenz (`z ∈ [½, 2]` resp. `[1, 4]`,
/// supersets of the windows).  This is the same series and the same `⅛` windows
/// the accurate [`lgamma_pos_td`] uses, lifted down to the cheap dd tier.
#[inline]
fn lgamma_root_fast(z: f64) -> Option<(DoubleDouble, f64)> {
    let series = if (z - 1.0).abs() < LGAMMA_ROOT_WINDOW {
        poly_dd_of_td(
            DoubleDouble {
                high: z - 1.0,
                low: 0.0,
            },
            &LGAMMA_ROOT1_TD,
        )
    } else if (z - 2.0).abs() < LGAMMA_ROOT_WINDOW {
        poly_dd_of_td(
            DoubleDouble {
                high: z - 2.0,
                low: 0.0,
            },
            &LGAMMA_ROOT2_TD,
        )
    } else {
        return None;
    };
    Some((series, LGAMMA_ROOT_ZIV_REL * series.high.abs()))
}

/// `ln|Γ(z)|` as a double-double via the lean Ziv fast leg, with its error bound
///
/// Reflects through `ln π − ln|sin πz| − ln Γ(1−z)` for `z < ½` (the gate comes from
/// the [`lgamma_pos_fast`] leg that handles `1−z`; the double-double `|sin πz|` and
/// its `ln_fast` add only <2⁻⁶⁶, well inside that gate).  When `1−z` lands in the
/// central-table band its `ln Γ(1−z)` is a table value `cell_eval(d)` plus the
/// recurrence's `ln ∏`; that recurrence log is folded into the sine — one
/// `ln(|sin πz|·∏^±1)` replaces two separate `ln`s (CORE-MATH's `lgamma` reflection
/// does the same single combined log), the lone shared-kernel saving in this band.
/// `[½, 8)` reads the central table; `[8, ∞)` takes the lean direct
/// [`lgamma_stirling_fast`] with the ten-term [`LGAMMA_TAIL_F64`] up to
/// [`LGAMMA_CUTOFF`] = 40 and the cheaper six-term [`LGAMMA_TAIL_F64_FAR`] on the
/// hot `z ≥ 40` tail.  The caller restricts `|z|` to below [`LGAMMA_FAST_BOUND`].
#[inline]
fn lgamma_fast(z: f64) -> (DoubleDouble, f64) {
    if z < 0.5 {
        let w = DoubleDouble::from_sum(1.0, -z);
        let sinpi = abs_sinpi_dd_lean(z);
        if w.high < LGAMMA_FAST_CUTOFF {
            // ln Γ(1−z) from the recurrence-free piecewise table (no recurrence, no
            // recurrence log); combine with `− ln|sin πz|`.  The `ln|sin πz|` term
            // adds its own slack to the leg's gate: near a half-integer `z` the sine
            // approaches 1, where `ln_fast`'s relative error degrades to ≈2⁻⁶¹ (the
            // old code logged `|sin πz|·∏`, never near 1), so it is budgeted at the
            // looser [`LGAMMA_REFLECT_SIN_REL`], not the table's own [`LGAMMA_PIECE_REL`].
            let (pos, gate) = lgamma_piecewise(w);
            let ln_sin = ln_fast_sum(sinpi);
            // `gate` is CORE-MATH's tight (≈1×) bound on `pos`'s error; the reflection
            // soundness test demands a 2× margin, so double it.  `gate ≪ ulp` of the
            // result, so the extra fallback is negligible.  The `ln|sin πz|` term is
            // already ≈2× its own error.
            return (
                LN_PI + neg(ln_sin + pos),
                crate::fast_mul_add(
                    ln_sin.high.abs(),
                    LGAMMA_REFLECT_SIN_REL,
                    crate::fast_mul_add(2.0, gate, LGAMMA_REFLECT_SIN_ABS),
                ),
            );
        }
        let (pos, gate) = lgamma_pos_fast(w);
        return (LN_PI + neg(ln_fast_sum(sinpi) + pos), gate);
    }
    if z < LGAMMA_FAST_CUTOFF {
        // Near the roots `z = 1, 2` the result is tiny; the relative-gated root
        // series ([`lgamma_root_fast`]) certifies it where the piecewise leg's
        // absolute floor would defer to the accurate path.
        if let Some(root) = lgamma_root_fast(z) {
            return root;
        }
        return lgamma_piecewise(DoubleDouble { high: z, low: 0.0 });
    }

    let inv = 1.0 / z;
    let u = inv * inv;
    let tail = if z < LGAMMA_CUTOFF {
        crate::poly(u, &LGAMMA_TAIL_F64) * inv
    } else {
        crate::poly(u, &LGAMMA_TAIL_F64_FAR) * inv
    };
    (lgamma_stirling_fast(z, tail), lgamma_stirling_ziv(z, inv))
}

// ── Double-double middle Ziv tier ────────────────────────────────────────────
//
// The lean fast leg is ≈2⁻⁶⁶; the accurate path below is ≈2⁻¹⁵⁰ triple-double but
// costs ≈1.8 µs (one TD `ln` plus, for `y < LGAMMA_CUTOFF`, the TD recurrence).  A
// fast-leg straddle that the corpus's hardest ≈2⁻¹¹⁶ ties do *not* require would
// still pay that full TD price.  This double-double tier (≈2⁻¹⁰⁵) sits between the
// two: it resolves essentially every straddle at ≈10× lower cost, leaving the TD
// path only for the genuine hard-to-round ties its own sound gate defers.  Because
// it is gated, any value it certifies is the correctly-rounded result the TD path
// would have returned — `tests/lgamma.rs`'s worst-case corpus verifies that
// bit-for-bit (those ties are exactly where this tier runs).

/// Natural logarithm of a positive double-double, double-double accurate
/// (≈2⁻¹⁰⁵): the middle tier's counterpart of [`ln_fast_sum`], using the accurate
/// [`ln_dd`](crate::f64_::ln_dd) in place of the lean [`ln_fast`](crate::f64_::ln_fast).
#[inline]
fn ln_dd_sum(s: DoubleDouble) -> DoubleDouble {
    crate::f64_::ln_dd(s.high)
        + DoubleDouble {
            high: s.low / s.high,
            low: 0.0,
        }
}

/// Direct Stirling `ln Γ(t)` for a positive double-double `t ≥ LGAMMA_CUTOFF`,
/// double-double accurate (≈2⁻¹⁰⁵): the middle tier's counterpart of
/// [`lgamma_stirling_fast`], with the accurate [`ln_dd_sum`] and the Bernoulli tail
/// carried as a double-double ([`poly_dd_of_td`] over the high+mid words of
/// [`LGAMMA_TAIL_TD`] — the accurate path's own coefficients, good to ≈2⁻¹¹⁶ at
/// `t ≥ 40`, far inside this tier's budget).
#[inline]
fn lgamma_stirling_mid(t: DoubleDouble) -> DoubleDouble {
    let inv = t.recip();
    let u = inv * inv;
    let tail = poly_dd_of_td(u, &LGAMMA_TAIL_TD) * inv;

    ln_dd_sum(t)
        * (t + DoubleDouble {
            high: -0.5,
            low: 0.0,
        })
        + neg(t)
        + HALF_LN_2PI
        + tail
}

/// Relative Ziv slack for the [`lgamma_pos_mid`] leg, scaled by the **intermediate**
/// magnitude (not the result).
///
/// The leg's error is dominated by [`ln_dd`](crate::f64_::ln_dd)'s ≈2⁻⁹⁵ relative
/// slack on the two large logs it forms — the Stirling lead `(t−½)·ln t` and the
/// recurrence product's `ln ∏` — whose `≈ln Γ(t)` magnitudes cancel down to the
/// small `ln Γ(y)`.  So the *absolute* error tracks `|stirling| + |ln ∏|`, not the
/// (possibly tiny, post-cancellation) result; the gate must scale with that sum.
/// `2⁻⁹³` covers the measured worst `err / magnitude ≈ 2⁻⁹⁶` with an ≈8× margin
/// (`ziv_soundness::lgamma_mid_leg_is_sound`), and stays far below `ulp(result)`
/// so it still certifies essentially every straddle — deferring only the corpus's
/// ≈2⁻¹¹⁶ hard ties to the triple-double path.
const LGAMMA_MID_ZIV_REL: f64 = crate::exp2i(-93);

/// `ln Γ(y)` for positive `y` as a double-double via the middle Ziv tier, with its
/// absolute error bound.
///
/// Recurrence up to [`LGAMMA_CUTOFF`] then [`lgamma_stirling_mid`] — the
/// double-double analogue of [`lgamma_pos_td`], minus the central table (the
/// recurrence reaches the Stirling regime from any `y ≥ ½`).  Near the roots
/// `z = 1, 2` the recurrence-minus-Stirling difference cancels to `ln Γ → 0`, so
/// the root-anchored relative series [`lgamma_root_fast`] (no cancellation) runs
/// instead.  The gate scales with the intermediate magnitude (see
/// [`LGAMMA_MID_ZIV_REL`]).
#[inline]
fn lgamma_pos_mid(y: DoubleDouble) -> (DoubleDouble, f64) {
    // Root windows: `ln Γ → 0`, so the recurrence-minus-Stirling difference would
    // cancel; the result-anchored series carries the tiny value with no
    // cancellation.  Use the *double-double* argument `y − {1,2}` (exact by
    // Sterbenz) — the reflection feeds a `1 − z` with a nonzero low word, which
    // [`lgamma_root_fast`]'s `f64` entry would drop.
    if (y.high - 1.0).abs() < LGAMMA_ROOT_WINDOW {
        let s = poly_dd_of_td(
            y + DoubleDouble {
                high: -1.0,
                low: 0.0,
            },
            &LGAMMA_ROOT1_TD,
        );
        return (s, LGAMMA_ROOT_ZIV_REL * s.high.abs());
    }
    if (y.high - 2.0).abs() < LGAMMA_ROOT_WINDOW {
        let s = poly_dd_of_td(
            y + DoubleDouble {
                high: -2.0,
                low: 0.0,
            },
            &LGAMMA_ROOT2_TD,
        );
        return (s, LGAMMA_ROOT_ZIV_REL * s.high.abs());
    }
    let steps = (LGAMMA_CUTOFF - y.high).ceil().max(0.0) as i64;
    let t = y + DoubleDouble {
        high: steps as f64,
        low: 0.0,
    };
    let stirling = lgamma_stirling_mid(t);
    if steps > 0 {
        let ln_prod = ln_dd_sum(recurrence_product_dd(y, steps));
        let mag = stirling.high.abs() + ln_prod.high.abs();
        (stirling + neg(ln_prod), LGAMMA_MID_ZIV_REL * mag)
    } else {
        (stirling, LGAMMA_MID_ZIV_REL * stirling.high.abs())
    }
}

/// `ln|Γ(z)|` as a double-double via the middle Ziv tier, with its error bound —
/// the double-double counterpart of [`lgamma_fast`]'s reflection-aware dispatch.
///
/// For `z < ½` it reflects through `ln π − ln|sin πz| − ln Γ(1−z)` (the caller's
/// `sin_is_reliable` guard already kept `sin πz` normal); the `ln|sin πz|` term
/// adds [`ln_dd`](crate::f64_::ln_dd)'s relative slack on its own magnitude to the
/// [`lgamma_pos_mid`] gate for `1−z`.  For `z ≥ ½` it is [`lgamma_pos_mid`] directly.
#[inline]
fn lgamma_mid(z: f64) -> (DoubleDouble, f64) {
    if z < 0.5 {
        let (pos, pos_gate) = lgamma_pos_mid(DoubleDouble::from_sum(1.0, -z));
        let ln_sin = ln_dd_sum(abs_sinpi_dd(z));
        let value = LN_PI + neg(ln_sin + pos);
        let gate = crate::fast_mul_add(LGAMMA_MID_ZIV_REL, ln_sin.high.abs(), pos_gate);
        (value, gate)
    } else {
        lgamma_pos_mid(DoubleDouble { high: z, low: 0.0 })
    }
}

// ── Triple-double accurate `ln|Γ|` path ──────────────────────────────────────
//
// A double-double accurate leg would be ≈2⁻¹⁰⁵ relative — its `ln` (`ln_dd`) and
// `|sin πz|` (`abs_sinpi_dd`) cap there.  `lgamma`'s corpus
// has ties as far as 64 bits past the round bit (the published worst case
// `0x1.129b17eed6bebp+579`), i.e. a relative band of ≈2⁻¹¹⁶ is needed, and the
// reflection's `sin(πz)` cancellation near a negative integer amplifies the
// deficit further.  A double-double path straddles ~268 k of those near-ties and
// mis-rounds them by 1 ulp.
//
// The fix mirrors `tgamma`: lift the whole accurate assembly to triple-double,
// reusing the [`TripleDouble`] ops above.  The two transcendental ingredients —
// a triple-double `ln` ([`ln_td`], ≈2⁻¹⁵⁰) and a triple-double `ln|sin πz|`
// (via [`sinpi_kernel_td`], ≈2⁻¹⁵⁰ relative even for tiny `sin`) — are ported
// from CORE-MATH's `as_logd_accurate` / `as_sinpipid_accurate` (the same design
// CORE-MATH's correctly-rounded `lgamma` uses).  The central table, Stirling
// tail, recurrence product, and reflection are then the double-double assembly
// lifted limb-for-limb to triple-double.

// CORE-MATH-faithful `(f64, f64)` double-double primitives, used by the ported
// `ln`/`sin` so the transcription is 1:1 (their fold ordering differs from the
// `DoubleDouble` operators').

/// `fasttwosum`: exact `a + b` as `(sum, err)`, requires `|a| ≥ |b|`.
#[inline]
fn fast_two_sum(a: f64, b: f64) -> (f64, f64) {
    let s = a + b;
    let z = s - a;
    (s, b - z)
}

/// `muldd`: `(xh+xl)·(ch+cl)` as a double-double pair (CORE-MATH ordering).
#[inline]
fn c_muldd(xh: f64, xl: f64, ch: f64, cl: f64) -> (f64, f64) {
    let ahhh = ch * xh;
    let l = crate::fast_mul_add(ch, xl, cl * xh) + crate::fma(ch, xh, -ahhh);
    (ahhh, l)
}

/// `sumdd`: `(xh+xl)+(yh+yl)` as a double-double pair (2Sum on the high words).
#[inline]
fn c_sumdd(xh: f64, xl: f64, yh: f64, yl: f64) -> (f64, f64) {
    let (sh, sl) = if xh.abs() > yh.abs() {
        fast_two_sum(xh, yh)
    } else {
        fast_two_sum(yh, xh)
    };
    (sh, sl + (xl + yl))
}

/// `fastsum`: `(xh+xl)+(yh+yl)` with `|xh| ≥ |yh|` assumed.
#[inline]
fn c_fastsum(xh: f64, xl: f64, yh: f64, yl: f64) -> (f64, f64) {
    let (sh, sl) = fast_two_sum(xh, yh);
    (sh, (xl + yl) + sl)
}

/// `mulddd`: `(ch+cl)·x` (a double-double times a scalar) as a double-double pair —
/// a 1:1 port of CORE-MATH's `mulddd`.
#[inline]
fn c_mulddd(x: f64, ch: f64, cl: f64) -> (f64, f64) {
    let ahhh = ch * x;
    (ahhh, crate::fast_mul_add(cl, x, crate::fma(ch, x, -ahhh)))
}

/// `polydddfst`: Horner `Σ c[k]·xᵏ` over a *scalar* `x` (double-double coefficients,
/// `seed` injected at the top), using [`c_mulddd`] — a 1:1 port of CORE-MATH's
/// `polydddfst` (`polydd` with the cheaper double-double × scalar step).
#[inline]
fn c_polydddfst(x: f64, c: &[DoubleDouble], seed: (f64, f64)) -> (f64, f64) {
    let n = c.len();
    let (mut ch, mut cl) = fast_two_sum(c[n - 1].high, seed.0);
    cl += seed.1 + c[n - 1].low;
    for k in (0..n - 1).rev() {
        let (mh, ml) = c_mulddd(x, ch, cl);
        let (sh, sl) = c_fastsum(c[k].high, c[k].low, mh, ml);
        ch = sh;
        cl = sl;
    }
    (ch, cl)
}

/// `polydd`: Horner `Σ c[k]·xᵏ` over a double-double `x`, with `seed` injected
/// at the top coefficient — a 1:1 port of CORE-MATH's `polydd`.
#[inline]
fn c_polydd(xh: f64, xl: f64, c: &[DoubleDouble], seed: (f64, f64)) -> (f64, f64) {
    let n = c.len();
    let (mut ch, mut cl) = fast_two_sum(c[n - 1].high, seed.0);
    cl += seed.1 + c[n - 1].low;
    for k in (0..n - 1).rev() {
        let (mh, ml) = c_muldd(xh, xl, ch, cl);
        let (sh, sl) = c_fastsum(c[k].high, c[k].low, mh, ml);
        ch = sh;
        cl = sl;
    }
    (ch, cl)
}


/// `ln(s)` for a positive triple-double `s`, as a triple-double.
///
/// `ln(s) = ln(s.high) + ln(1 + (s.mid+s.low)/s.high)`, with the offset
/// `r = (mid+low)/high` formed as a double-double (an exact `mid+low` numerator
/// over `high`) so [`ln1p_small_td`] reaches triple-double — the bare-`f64` `r`
/// would cap the logarithm at ≈2⁻¹⁰⁷.
#[inline]
fn ln_sum_td3(s: TripleDouble) -> TripleDouble {
    let num = DoubleDouble::from_sum(s.mid, s.low);
    let r = num / s.high;
    td_add(ln_td(s.high), ln1p_small_td(r))
}

/// `∏_{j=0}^{n−1} (y + j)` as a triple-double for a positive double-double `y`,
/// on four parallel lanes — the triple-double, dd-base analogue of
/// [`recurrence_product_dd`].  Each factor `y + j` is an exact double-double
/// (the [`Add`] folds the bottom bits of `y.high` into the low word), folded
/// into a triple-double lane by [`dd_mul_td`].
#[inline]
fn recurrence_product_dd_td(y: DoubleDouble, n: i64) -> TripleDouble {
    let factor = |j: i64| {
        y + DoubleDouble {
            high: j as f64,
            low: 0.0,
        }
    };

    let mut p = [TD_ONE; 4];
    let mut j = 0;
    while j + 4 <= n {
        p[0] = dd_mul_td(factor(j), p[0]);
        p[1] = dd_mul_td(factor(j + 1), p[1]);
        p[2] = dd_mul_td(factor(j + 2), p[2]);
        p[3] = dd_mul_td(factor(j + 3), p[3]);
        j += 4;
    }
    while j < n {
        p[0] = dd_mul_td(factor(j), p[0]);
        j += 1;
    }
    td_mul(td_mul(p[0], p[1]), td_mul(p[2], p[3]))
}

/// `0` as a triple-double.
const TD_ZERO: TripleDouble = TripleDouble {
    high: 0.0,
    mid: 0.0,
    low: 0.0,
};

/// `ln Γ(2.875 + d)` for `d ∈ [−½, ½]` as a triple-double — `ln` of the central
/// `Γ` minimax [`TGAMMA_TD`] (which has no zero on `[2.375, 3.375]`, so `ln_sum_td3`
/// of it stays well-conditioned), reusing the table `tgamma` already carries.
#[inline]
fn lgamma_central_td(d: DoubleDouble) -> TripleDouble {
    ln_sum_td3(poly_td(dd_to_td(d), &TGAMMA_TD))
}

/// `± ln ∏` of the ≤ 5 central-cell recurrence factors, in triple-double — the
/// triple-double analogue of [`lgamma_recurrence_log`].
#[inline]
fn lgamma_recurrence_log_td(y: DoubleDouble, i: i64) -> TripleDouble {
    if i > 0 {
        let yc = y + DoubleDouble {
            high: -(i as f64),
            low: 0.0,
        };
        ln_sum_td3(recurrence_product_dd_td(yc, i))
    } else if i < 0 {
        td_neg(ln_sum_td3(recurrence_product_dd_td(y, -i)))
    } else {
        TD_ZERO
    }
}

/// `½` of the near-root window: within `|y − 1| < ⅛` or `|y − 2| < ⅛` the
/// result-anchored Taylor series replaces the cancelling central form.
const LGAMMA_ROOT_WINDOW: f64 = 0.125;

/// `ln Γ(y)` as a triple-double for a positive double-double `y` (`y.high ≥ ½`).
///
/// `ln Γ` has zeros at `z = 1, 2`; within `⅛` of either, the
/// `ln Γ(1+x) = Σ cₖ xᵏ` / `ln Γ(2+x)` *result-anchored* series ([`LGAMMA_ROOT1_TD`]
/// / [`LGAMMA_ROOT2_TD`]) carries the small value with no cancellation — a
/// triple-double cannot survive the otherwise ~28-bit loss as `y → 1, 2`.  Off
/// the roots and below `LGAMMA_FAST_CUTOFF`, reduce onto the central cell and read
/// the direct minimax [`lgamma_central_td`] plus the ≤ 5-factor recurrence log.
/// Above the cutoff there are no roots, so reduce upward to the Stirling region
/// `t = y + steps ≥ LGAMMA_CUTOFF` via `ln Γ(y) = ln Γ(t) − ln ∏_{j=0}^{steps−1}(y+j)`
/// and apply Stirling `(t−½)·(ln t − 1) + (½ln 2π − ½) + tail(1/t²)`, kept sharp
/// by the triple-double product [`recurrence_product_dd_td`].
#[inline]
fn lgamma_pos_td(y: DoubleDouble) -> TripleDouble {
    if y.high < LGAMMA_FAST_CUTOFF {
        // Result-anchored series within ⅛ of a root (`x = y − 1` or `y − 2` exact).
        if (y.high - 1.0).abs() < LGAMMA_ROOT_WINDOW {
            let x = dd_to_td(
                y + DoubleDouble {
                    high: -1.0,
                    low: 0.0,
                },
            );
            return poly_td(x, &LGAMMA_ROOT1_TD);
        }
        if (y.high - 2.0).abs() < LGAMMA_ROOT_WINDOW {
            let x = dd_to_td(
                y + DoubleDouble {
                    high: -2.0,
                    low: 0.0,
                },
            );
            return poly_td(x, &LGAMMA_ROOT2_TD);
        }
        let (i, d) = lgamma_center_reduce(y);
        // `td_add_exact`: the recurrence log cancels the central `ln Γ` near the
        // roots `z = 1, 2` (where `ln Γ → 0`).
        return td_add_exact(lgamma_central_td(d), lgamma_recurrence_log_td(y, i));
    }

    let steps = (LGAMMA_CUTOFF - y.high).ceil().max(0.0) as i64;
    let t = y + DoubleDouble {
        high: steps as f64,
        low: 0.0,
    };

    // tail = P(u)/t with u = 1/t², in triple-double.
    let inv_t = td_recip(dd_to_td(t));
    let u = td_mul(inv_t, inv_t);
    let tail = td_mul(poly_td(u, &LGAMMA_TAIL_TD), inv_t);

    // lnΓ(t) = (t−½)·(ln t − 1) + (½ln(2π) − ½) + tail.
    let ln_t_m1 = td_add_f64(ln_sum_td(t), -1.0);
    let t_m_half = dd_to_td(
        t + DoubleDouble {
            high: -0.5,
            low: 0.0,
        },
    );
    let stirling = td_add(
        td_add(td_mul(ln_t_m1, t_m_half), HALF_LN_2PI_M_HALF_TD),
        tail,
    );

    if steps > 0 {
        // `td_add_exact`: `ln Γ(t) − ln ∏` cancels heavily when `y` is small (the
        // Stirling lead and the recurrence log are both ≈ the same large value).
        td_add_exact(
            stirling,
            td_neg(ln_sum_td3(recurrence_product_dd_td(y, steps))),
        )
    } else {
        stirling
    }
}

/// `½·ln(2π) − ½` as a triple-double.
const HALF_LN_2PI_M_HALF_TD: TripleDouble = TripleDouble {
    high: 0.4189385332046728,
    mid: -3.8782941580672414e-17,
    low: -1.323971596849807e-33,
};

/// `ln|Γ(z)|` as a triple-double via the accurate path, the Ziv fallback.
///
/// `#[cold] #[inline(never)]` for the same reason as before: the rarely-taken
/// accurate leg is bulky (the ported triple-double `ln` / `sin` plus the
/// triple-double recurrence) and inlining it would only bloat [`lgamma`]'s hot
/// body.
#[cold]
#[inline(never)]
fn lgamma_dd(z: f64) -> TripleDouble {
    if z < 0.5 {
        // Reflection ln|Γ(z)| = ln π − ln|sin(πz)| − ln Γ(1−z); `1 − z` is exact.
        // `ln|sin πz|` keeps full *relative* accuracy near the negative integers,
        // where this difference cancels hardest.
        let ln_sin = ln_abs_sinpi_td(z);
        let pos = lgamma_pos_td(DoubleDouble::from_sum(1.0, -z));
        // `td_add_exact`: the reflection `ln π − ln|sin πz| − ln Γ(1−z)` cancels
        // hard near the negative integers and wherever `ln Γ` crosses zero.
        td_add_exact(LN_PI_TD, td_neg(td_add_exact(ln_sin, pos)))
    } else {
        lgamma_pos_td(DoubleDouble { high: z, low: 0.0 })
    }
}

/// `ln π` as a triple-double.
const LN_PI_TD: TripleDouble = TripleDouble {
    high: 1.1447298858494002,
    mid: 1.0265951162707826e-17,
    low: -1.3722612652165766e-34,
};

/// The natural logarithm of the absolute value of the gamma function
#[must_use]
#[inline]
pub fn lgamma(z: f64) -> f64 {
    if z == 0.0 || z >= LGAMMA_OVERFLOW {
        return f64::INFINITY;
    }
    if z.is_nan() {
        return z;
    }

    // Non-positive integers are poles; Γ(1) = Γ(2) = 1 give the exact zeros.
    if z < 0.5 && z == z.floor() {
        return f64::INFINITY;
    }
    if z == 1.0 || z == 2.0 {
        return 0.0;
    }

    // Ziv two-step: a lean leg (central table or lean Stirling) gated against the
    // accurate triple-double path.  The leg returns its own absolute error bound —
    // the tight [`LGAMMA_TABLE_ERR`] in the moderate band, the `t`-scaled
    // [`lgamma_stirling_ziv`] for Stirling.  Restricted to `|z| < LGAMMA_FAST_BOUND`,
    // where those gates certify the leg; either gate also defers a result that
    // cancels toward zero (it then spans many ulps), to the accurate path.
    //
    // The reflection (`z < ½`) leg's `ln|sin πz|` uses a double-double `sin`; its
    // low word degrades once `sin(πz) = π|r|` (with `r = z − round(2z)/2` exact)
    // approaches the subnormal range, where the gate — which only budgets the
    // `ln Γ(1−z)` leg — can no longer see that error and would certify a wrong
    // value (e.g. tiny `z`, or `z` extremely close to a negative integer).  Skip
    // the fast leg there and resolve `ln|sin πz|` on the relatively-accurate
    // triple-double accurate path.
    let sin_is_reliable = z >= 0.5 || {
        // `q·½` is exact (`q` integer-valued, ½ a power of two) and `z − q·½` is
        // Sterbenz-exact, so `r` is the exact reduced residual.
        let half_q = (2.0 * z).round_ties_even() * 0.5;
        let r = z - half_q;
        core::f64::consts::PI * r.abs() >= LGAMMA_SIN_RELIABLE
    };
    if sin_is_reliable && z > -LGAMMA_FAST_BOUND && z < LGAMMA_FAST_BOUND {
        let (value, gate) = lgamma_fast(z);
        let lo = value.high + (value.low - gate);
        let hi = value.high + (value.low + gate);
        if lo == hi {
            return lo;
        }

        // Double-double middle tier: resolves the straddle at ≈10× below the
        // triple-double path's cost, deferring only the corpus's hardest ties.
        let (value, gate) = lgamma_mid(z);
        let lo = value.high + (value.low - gate);
        let hi = value.high + (value.low + gate);
        if lo == hi {
            return lo;
        }
    }

    td_round(lgamma_dd(z))
}

/// Soundness of the [`lgamma_mid`] middle-tier Ziv gate.
///
/// The gate must *upper-bound* the leg's true error with margin, or a confident
/// `lo == hi` could certify a value on the wrong side of a rounding boundary — the
/// erf/erfc bug this discipline guards against.  The triple-double accurate path
/// ([`lgamma_dd`], ≈2⁻¹⁵⁰) is the in-house correctly-rounded reference, so the leg's
/// error is its disagreement with that path, measured here to its full precision by
/// the exact high-order cancellation `(mid.high − td.high) + mid.low − td.mid − td.low`.
/// The worst `error / gate` ratio across `[−9.5, 200]` (both the reflection and the
/// positive side, skipping the near-pole humps the special ladder handles) must stay
/// `< ½` — a ≥ 2× margin.
#[cfg(test)]
mod mid_tier_soundness {
    use super::*;

    #[test]
    fn lgamma_mid_leg_is_sound() {
        let mut s = 0x9e37_79b9_7f4a_7c15u64;
        let mut next = || {
            s ^= s << 13;
            s ^= s >> 7;
            s ^= s << 17;
            (s >> 11) as f64 / (1u64 << 53) as f64
        };
        let mut worst = 0.0_f64;
        let mut worst_z = 0.0_f64;
        for _ in 0..4_000_000u64 {
            let z = -9.5 + 209.5 * next();
            // The near-pole humps never reach this leg (the special ladder and the
            // `sin_is_reliable` guard divert them).
            if z <= 0.0 && (z - z.round()).abs() < 1.0 / 256.0 {
                continue;
            }
            let (v, g) = lgamma_mid(z);
            let td = lgamma_dd(z);
            let err = ((v.high - td.high) + v.low - td.mid - td.low).abs();
            let ratio = err / g;
            if ratio > worst {
                worst = ratio;
                worst_z = z;
            }
        }
        assert!(
            worst < 0.5,
            "middle-tier gate unsound: worst error/gate = {worst:.3} at z = {worst_z}"
        );
    }
}

#[cfg(test)]
mod fold_ordering {
    use super::*;

    /// The three `add_ordered` folds of [`lgamma_stirling_fast`] each require the
    /// running sum to dominate the term being folded in.  The Stirling lead
    /// `(z−½)·ln z` and every partial sum grow monotonically for `z ≥ 8`, so the
    /// tightest case is the cutoff `z = 8`; sweeping `[8, 1024]` (a superset of
    /// the `[8, LGAMMA_FAST_BOUND]` fast-leg band) confirms it on the real
    /// arithmetic (`ln_fast`, the `f64` tail, the folds).
    #[test]
    fn lgamma_stirling() {
        // z = 8, 8.125, …, 1024 (8128 steps of 1/8 covering the fast-leg band).
        for k in 0..=8128 {
            let z = crate::fast_mul_add(f64::from(k), 0.125, LGAMMA_FAST_CUTOFF);
            let inv = 1.0 / z;
            let tail = crate::poly(inv * inv, &LGAMMA_TAIL_F64) * inv;

            // Fold 1: lead ⊕ (−z) needs |lead.high| ≥ |z|.
            let lead = crate::f64_::ln_fast(z) * (z - 0.5);
            assert!(lead.high.abs() >= z, "fold 1 at z = {z}");

            // Fold 2: (lead − z) ⊕ ½ln(2π) needs |·| ≥ |½ln(2π)|.
            let a1 = lead.add_ordered(DoubleDouble { high: -z, low: 0.0 });
            assert!(a1.high.abs() >= HALF_LN_2PI.high.abs(), "fold 2 at z = {z}");

            // Fold 3: (… + ½ln(2π)) ⊕ tail needs |·| ≥ |tail|.
            let a2 = a1.add_ordered(HALF_LN_2PI);
            assert!(a2.high.abs() >= tail.abs(), "fold 3 at z = {z}");
        }
    }
}

#[cfg(all(test, feature = "mpfr"))]
mod ziv_soundness {
    use super::*;
    use rug::Float;

    fn mix(i: u64) -> u64 {
        let mut z = i.wrapping_mul(0x2545_F491_4F6C_DD1D);
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// The exact double-double value the [`tgamma`] fast leg (table eval through
    /// the recurrence) certifies against [`TGAMMA_ZIV_EPS`], for `z` whose
    /// recurrence needs no rescaling (`e2 == 0` — the only inputs the gate runs on).
    fn fast_leg(z: f64) -> DoubleDouble {
        let (i, d) = tgamma_reduce(z);
        let (value, e2) = tgamma_recurrence(z, i, tgamma_table_eval(d));
        debug_assert_eq!(e2, 0, "fast-leg gate runs only on e2 == 0");
        value
    }

    /// The fast leg's Ziv gate must be *sound*: `TGAMMA_ZIV_EPS` has to exceed the
    /// fast leg's true worst-case relative error with margin, or a confident
    /// `lo == hi` could certify a value on the wrong side of a rounding boundary
    /// (exactly the erf bug this mirrors).  Sweep the active band `(−100, 171.6)`
    /// where the recurrence stays rescale-free (`e2 == 0`), skipping the poles and
    /// the tiny-`z` 1/z overflow corner, comparing the un-rounded fast-leg pair to
    /// a 250-bit MPFR `Γ`.
    #[test]
    fn tgamma_fast_leg_is_sound() {
        // Cover the whole rescale-free range with margin: `i = round(z − 2.875)`
        // and `|i| ≤ TGAMMA_DOWNWARD_DIRECT` downward keeps `e2 == 0`, i.e.
        // `z > 2.875 − 100`.  Stay just inside for safety.
        //
        // The band `(−97, 171.6)` straddles zero, so sample each sign half on its
        // own bit-monotonic range — `(−97, −0)` and `(0, 171.6)` — and pick one per
        // draw.  A single bit-walk up from `(−97).to_bits()` instead climbs *away*
        // from zero (`0xC058… → 0xFFFF…`) into `z ≤ −97`, where the downward
        // recurrence loops `≈|z|` times: it once fed `fast_leg` a `−2.2e14` and spun
        // for days.  Both endpoints stay strictly interior (the `% (b − a)` excludes
        // `b`), matching "just inside for safety".
        let neg = ((-0.0f64).to_bits(), (-97.0f64).to_bits());
        let pos = (0.0f64.to_bits(), 171.6f64.to_bits());
        let mut worst = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..300_000u64 {
            let h = mix(k);
            let (a, b) = if h & 1 == 0 { neg } else { pos };
            let z = f64::from_bits(a + (h >> 1) % (b - a));
            // Skip non-positive integers (poles) and the near-pole / tiny-z humps
            // where Γ spans signed zeros or the 1/z corner overflows — those never
            // reach the gate (handled by the special-case ladder).
            if z <= 0.0 && (z - z.round()).abs() < 1.0 / 64.0 {
                continue;
            }
            if z.abs() < 1.0 / 1024.0 {
                continue;
            }
            let e = fast_leg(z);
            if !e.high.is_finite() || e.high == 0.0 {
                continue;
            }
            let got = Float::with_val(250, e.high) + Float::with_val(250, e.low);
            let truth = Float::with_val(250, z).gamma();
            if truth == 0.0 || !truth.is_finite() {
                continue;
            }
            let rel = (Float::with_val(250, &got - &truth).abs() / truth.abs()).to_f64();
            if rel > worst {
                worst = rel;
                worst_x = z;
            }
        }
        println!(
            "tgamma fast leg: worst rel error 2^{:.2} at z={worst_x:e}; eps = 2^{:.2}",
            worst.log2(),
            TGAMMA_ZIV_EPS.log2()
        );
        assert!(
            TGAMMA_ZIV_EPS > 2.0 * worst,
            "TGAMMA_ZIV_EPS = 2^{:.2} does not cover the fast leg's 2^{:.2}",
            TGAMMA_ZIV_EPS.log2(),
            worst.log2()
        );
    }

    /// The **Stirling** fast leg (`z ≥ TGAMMA_STIRLING_CUTOFF`) must be sound: its
    /// `z`-scaled gate [`tgamma_stirling_ziv_rel`] has to exceed the un-rounded
    /// leg's true relative error with margin, or a confident `lo == hi` could
    /// certify a value on the wrong side of a boundary.  Reconstruct the leg's
    /// `[1, 2)` mantissa (`Γ = m · 2^q`), compare it to a 250-bit MPFR `Γ` scaled
    /// by the exact `2^-q`, and require the gate to clear `2×` the worst margin
    /// across the whole Stirling range `[8, 171.6)`.
    #[test]
    fn tgamma_stirling_leg_is_sound() {
        let (lo, hi) = (TGAMMA_STIRLING_CUTOFF.to_bits(), TGAMMA_OVERFLOW.to_bits());
        let mut worst_margin = f64::INFINITY;
        let mut worst_rel = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..400_000u64 {
            let b = lo.wrapping_add(mix(k) % hi.wrapping_sub(lo));
            let z = f64::from_bits(b);
            let (m, q) = tgamma_stirling_fast(z);
            let got = Float::with_val(250, m.high) + Float::with_val(250, m.low);
            let truth = Float::with_val(250, z).gamma();
            let q32 = i32::try_from(q).expect("q in i32 range");
            let truth_m = truth >> q32; // Γ(z) · 2^-q, exact
            if truth_m == 0.0 || !truth_m.is_finite() {
                continue;
            }
            let rel = (Float::with_val(250, &got - &truth_m).abs() / truth_m.abs()).to_f64();
            let margin = tgamma_stirling_ziv_rel(z) / rel;
            if margin < worst_margin {
                worst_margin = margin;
                worst_rel = rel;
                worst_x = z;
            }
        }
        println!(
            "tgamma Stirling leg: worst margin {worst_margin:.2}× at z={worst_x:e} \
             (rel 2^{:.2}, gate 2^{:.2})",
            worst_rel.log2(),
            tgamma_stirling_ziv_rel(worst_x).log2()
        );
        assert!(
            worst_margin > 2.0,
            "Stirling gate margin {worst_margin:.2}× at z={worst_x:e} is below 2×"
        );
    }

    /// The [`lgamma`] **reflection** fast leg (`z < ½`) must be sound *wherever it
    /// is allowed to run* — i.e. where `lgamma`'s `LGAMMA_SIN_RELIABLE` guard lets
    /// the double-double `sin(πz)` through.  Its gate budgets only the
    /// `ln Γ(1−z)` leg, so the guard's job is to keep the `ln|sin πz|` slack
    /// inside that gate; this checks the *absolute* error of the un-rounded fast
    /// pair against a 300-bit MPFR `ln|Γ|` stays under the returned gate (the
    /// erf-style soundness check).  Without the guard, tiny `z` and near-integer
    /// `z` violate this by many ulps (the bug this guard fixes).
    #[test]
    fn lgamma_reflection_fast_leg_is_sound() {
        // Sample the reflection band (−256, ½): representation-uniform magnitudes
        // across the exponent range, both signs of the offset from an integer.
        let mut worst_ratio = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..300_000u64 {
            let h = mix(k);
            // |z| ∈ [2⁻⁶⁰, 256), value-uniform in the exponent.
            let e = 1023 - (h % 60);
            let mag = f64::from_bits((e << 52) | (h >> 12)) * ((h >> 1 & 0xff) as f64 + 1.0);
            let z = if h & 1 == 0 { mag } else { -mag };
            if !(z > -256.0 && z < 0.5) || z == 0.0 {
                continue;
            }
            // Apply the same reliability guard `lgamma` uses; only inputs that pass
            // it ever reach the gate.
            let half_q = (2.0 * z).round_ties_even() * 0.5;
            let r = z - half_q;
            if !(core::f64::consts::PI * r.abs() >= LGAMMA_SIN_RELIABLE) {
                continue;
            }
            // Skip non-positive integers (poles) — handled by the special ladder.
            if z <= 0.0 && (z - z.round()).abs() == 0.0 {
                continue;
            }

            let (value, gate) = lgamma_fast(z);
            if !value.high.is_finite() {
                continue;
            }
            let got = Float::with_val(300, value.high) + Float::with_val(300, value.low);
            let truth = Float::with_val(300, z).ln_abs_gamma().0;
            if !truth.is_finite() {
                continue;
            }
            // The gate certifies when `value ± gate` round alike; soundness needs
            // the true error well inside `gate` so a confident `lo == hi` can't sit
            // on the wrong side of a boundary.
            let abs_err = Float::with_val(300, &got - &truth).abs().to_f64();
            let ratio = abs_err / gate;
            if ratio > worst_ratio {
                worst_ratio = ratio;
                worst_x = z;
            }
        }
        println!(
            "lgamma reflection fast leg: worst |err|/gate = {worst_ratio:.3} at z={worst_x:e}"
        );
        assert!(
            worst_ratio < 0.5,
            "reflection fast leg error reaches {worst_ratio:.3}× its gate at z={worst_x:e} \
             — the LGAMMA_SIN_RELIABLE guard is unsound"
        );
    }

    /// The **root-anchored** fast leg (`z` within ⅛ of 1 or 2) must be sound: its
    /// *relative* gate [`LGAMMA_ROOT_ZIV_REL`] times `|value|` has to exceed the dd
    /// series' true absolute error with margin, or a confident `lo == hi` could
    /// certify a value on the wrong side of a boundary.  Near the roots `ln Γ → 0`
    /// so this gate is the only guard between the tiny result and a mis-round;
    /// sweep both windows (skipping the exact zeros `z = 1, 2`) and require the
    /// gate to clear `2×` the worst |err| against a 300-bit MPFR `ln|Γ|`.
    #[test]
    fn lgamma_root_fast_leg_is_sound() {
        let mut worst_ratio = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..400_000u64 {
            let h = mix(k);
            // Uniform over the two ⅛-windows [0.875, 1.125] ∪ [1.875, 2.125].
            let center = if h & 1 == 0 { 1.0 } else { 2.0 };
            let u = (h >> 1) as f64 / (1u64 << 63) as f64; // [0, 1)
            // Bound the product to a local so this stays a plain add (no `mul_add`
            // shape for `suboptimal_flops`); `off ∈ [−⅛, ⅛)`.
            let off = (u - 0.5) * (LGAMMA_ROOT_WINDOW * 2.0);
            let z = center + off;
            if z == 1.0 || z == 2.0 {
                continue;
            }
            // The exact window boundary (`|z − center| = ⅛`) falls to the table
            // leg, like the real `lgamma_fast` does — skip it here.
            let Some((value, gate)) = lgamma_root_fast(z) else {
                continue;
            };
            let got = Float::with_val(300, value.high) + Float::with_val(300, value.low);
            let truth = Float::with_val(300, z).ln_abs_gamma().0;
            if !truth.is_finite() {
                continue;
            }
            let abs_err = Float::with_val(300, &got - &truth).abs().to_f64();
            let ratio = abs_err / gate;
            if ratio > worst_ratio {
                worst_ratio = ratio;
                worst_x = z;
            }
        }
        println!("lgamma root fast leg: worst |err|/gate = {worst_ratio:.3} at z={worst_x:e}");
        assert!(
            worst_ratio < 0.5,
            "root fast leg error reaches {worst_ratio:.3}× its gate at z={worst_x:e} \
             — LGAMMA_ROOT_ZIV_REL is unsound"
        );
    }

    /// The **positive Stirling** fast leg (`8 ≤ z < LGAMMA_FAST_BOUND`) must be
    /// sound under the new `t`-scaled gate [`lgamma_stirling_ziv`]: the gate has to
    /// exceed the un-rounded leg's true absolute error with margin, or a confident
    /// `lo == hi` could certify a value on the wrong side of a rounding boundary.
    /// Tightening the gate from a flat `2⁻⁵⁶` to `(t − ½)·2⁻⁶⁴ + 2⁻⁵⁸` is only safe
    /// if it stays a sound bound across the whole band, so compare the fast pair to a
    /// 300-bit MPFR `ln|Γ|` and require the gate to clear `2×` the worst |err|.
    #[test]
    fn lgamma_positive_stirling_leg_is_sound() {
        let (lo, hi) = (8.0f64.to_bits(), LGAMMA_FAST_BOUND.to_bits());
        let mut worst_ratio = 0.0_f64;
        let mut worst_x = 0.0_f64;
        for k in 0..400_000u64 {
            let b = lo.wrapping_add(mix(k) % hi.wrapping_sub(lo));
            let z = f64::from_bits(b);
            let (value, gate) = lgamma_fast(z);
            if !value.high.is_finite() {
                continue;
            }
            let got = Float::with_val(300, value.high) + Float::with_val(300, value.low);
            let truth = Float::with_val(300, z).ln_abs_gamma().0;
            if !truth.is_finite() {
                continue;
            }
            let abs_err = Float::with_val(300, &got - &truth).abs().to_f64();
            let ratio = abs_err / gate;
            if ratio > worst_ratio {
                worst_ratio = ratio;
                worst_x = z;
            }
        }
        println!(
            "lgamma positive Stirling leg: worst |err|/gate = {worst_ratio:.3} (margin \
             {:.2}×) at z={worst_x:e}",
            1.0 / worst_ratio
        );
        assert!(
            worst_ratio < 0.5,
            "positive Stirling fast leg error reaches {worst_ratio:.3}× its gate at z={worst_x:e} \
             — the lgamma_stirling_ziv gate is unsound"
        );
    }
}
